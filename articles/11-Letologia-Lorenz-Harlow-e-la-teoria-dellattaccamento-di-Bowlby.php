<h2>L'influenza dell'etologia</h2>
<p>Per comprendere la teoria dell'attaccamento occorre considerare l'influenza dell'<strong>etologia</strong>, definita come lo studio comparato del comportamento animale. Il padre dell'etologia è <strong>Konrad Lorenz</strong>, che dall'osservazione dei comportamenti animali introdusse alcuni concetti poi ripresi da Bowlby.</p>

<h3>Konrad Lorenz e l'imprinting</h3>
<p>Un primo concetto è quello di <strong>imprinting</strong>: secondo Lorenz, negli animali esiste un <strong>periodo sensibile</strong> in cui i piccoli riconoscono e apprendono le caratteristiche della figura principale del loro allevamento; questo apprendimento, una volta avvenuto in quella finestra temporale, diventa irreversibile.</p>
<p>Lorenz studiò questo fenomeno nelle <strong>ochette selvatiche</strong>: nelle prime 48 ore di vita, i piccoli imparano a seguire il primo oggetto in movimento (di solito la madre) e lo riconoscono come figura principale del proprio allevamento, senza più tornare indietro una volta passata questa finestra temporale. Per verificarlo, Lorenz si sostituì alla madre oca nelle prime ore di vita di alcuni anatroccoli, immergendosi in acqua: i piccoli iniziarono a seguire lui e a ignorare la madre biologica, che a sua volta li ignorò e arrivò persino ad attaccarli. Una volta passata la finestra temporale, l'<strong>imprinting più naturale</strong> non fu più possibile. Lorenz notò inoltre che, da adulte, queste oche cercavano di riprodurre comportamenti sociali e sessuali tipici della specie umana: la separazione precoce dalla madre aveva quindi determinato delle <strong>alterazioni nel normale sviluppo socio-emozionale</strong>.</p>
<p>Secondo Lorenz, il comportamento sociale delle specie animali dipende da risposte istintive selezionate dall'evoluzione per garantire la sopravvivenza della specie: nasciamo con schemi innati di risposte socio-emotive che si attivano nell'incontro con l'ambiente (di solito la madre biologica). Questi istinti sono specie-specifici: se cambia la specie di riferimento, come nell'esperimento di Lorenz, qualcosa va storto, perché si tratta di risposte stereotipate che, fuori dalla finestra del periodo critico, non possono più essere modificate dall'esperienza.</p>

<h3>Harry Harlow e l'esperimento delle scimmiette</h3>
<p>Un altro contributo alla teoria dell'attaccamento viene da <strong>Harry Harlow</strong>, che nel 1958, nell'articolo "The nature of love", descrisse alcuni celebri esperimenti sui comportamenti affettivi delle scimmiette. All'epoca era diffusa l'idea che il bambino si legasse alla figura di allevamento solo perché questa garantiva la sopravvivenza fisiologica (il nutrimento); Harlow volle verificare quanto contasse davvero il solo nutrimento rispetto ad altri tipi di bisogno.</p>
<p>Harlow separò delle scimmiette dalla madre biologica tra le 6 e le 12 ore dopo la nascita e le allevò con due <strong>madri surrogato</strong>: una schematica, di metallo, che però forniva il latte a richiesta; l'altra, priva di latte, ma dalle fattezze più simili a una scimmia adulta e ricoperta di stoffa morbida. Osservò che le scimmiette, oltre a nutrirsi dal latte della madre di metallo, passavano la maggior parte del tempo aggrappate alla madre di stoffa, che diventava la loro base per affrontare oggetti minacciosi introdotti nella gabbia. Le scimmiette che avevano trascorso più tempo con la madre di stoffa mostravano inoltre comportamenti di curiosità ed esplorazione dell'ambiente più frequenti e intensi rispetto a quelle cresciute soprattutto con la madre di metallo.</p>
<p>Questo dimostrava che <strong>esistono dei bisogni primari che vanno al di là del soddisfacimento dei bisogni fisiologici</strong>. Secondo la teoria classica di <strong>Sigmund Freud</strong>, la libido non è legata a nessun oggetto a priori, e la scelta dell'oggetto è casuale e strumentale alla scarica energetica: seguendo questa logica, le scimmiette avrebbero dovuto legarsi alla madre di metallo, l'unica in grado di soddisfare il bisogno di nutrimento. Invece preferivano caratteristiche come la morbidezza e il calore: per le scimmiette il bisogno primario non era essere nutrite, ma avere contatto con una figura di allevamento protettiva e calda. Le scimmiette cresciute solo con la madre di metallo, al contrario, mostravano comportamenti più isolati, simili a stati depressivi o autistici: il solo nutrimento, quindi, non basta a garantire uno sviluppo psichico sano.</p>

<h2>John Bowlby e la Scuola Inglese delle Relazioni Oggettuali</h2>

<p>Bowlby si definì sempre uno psicoanalista, pur essendo la sua teoria dell'attaccamento considerata 
    come una <strong>teoria a sé</strong> all'interno della psicologia dinamica.</p>
<p>Tra gli autori psicoanalitici che più lo influenzarono troviamo <strong>Fairbairn</strong>, 
che sostenenva che la motivazione fondamentale della vita non è la ricerca di piacere ma la ricerca di relazioni. 
Fairbairn aveva anche spiegato in questo modo la coazione a ripetere (che aveva portato Freud a introdurre la pulsione di morte): 
per lui le persone hanno un tale bisogno di relazioni umane che preferiscono restare in legami disfunzionali piuttosto che isolarsi completamente.</p>




<h3>I principi della teoria dell'attaccamento</h3>
<p>Secondo Bowlby, la <strong>motivazione primaria degli esseri umani è la ricerca di contatto</strong>, di attaccamento, con una 
figura di allevamento principale. Questa motivazione è innata e specie-specifica, e si manifesta in comportamenti universali 
quali la ricerca di vicinanza, la suzione, il sorriso, l'abbraccio, il pianto e il seguire.</p>

