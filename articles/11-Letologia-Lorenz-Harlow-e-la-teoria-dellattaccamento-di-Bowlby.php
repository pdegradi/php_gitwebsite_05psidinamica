<h2>La seconda critica alla teoria dell'attaccamento e il suo superamento</h2>
<p>La seconda critica rivolta a <strong>Bowlby</strong> riguardava il metodo: per essere verificata empiricamente, la teoria dell'attaccamento traduce i concetti psicoanalitici in <strong>definizioni operazionali</strong> (definizioni basate su comportamenti osservabili e misurabili). Secondo alcuni autori psicoanalitici, questa semplificazione era già di per sé un problema, perché rischiava di distorcere concetti troppo complessi per essere ridotti a comportamenti osservabili.</p>

<p>Nonostante questa critica, la psicoanalisi contemporanea condivide molti aspetti con la teoria dell'attaccamento, che oggi viene rivalutata e reintegrata nelle prospettive più attuali:</p>
<ul>
<li>come nelle teorie della <strong>svolta relazionale</strong> (descritta da Mitchell), anche nella teoria dell'attaccamento l'ambiente sociale ha un ruolo centrale nella formazione della mente;</li>
<li>le esperienze della prima infanzia restano fondamentali per lo sviluppo della personalità;</li>
<li>Bowlby condivide con la psicoanalisi contemporanea l'idea di un <strong>inconscio rappresentazionale</strong>: non più un inconscio rimosso come in Freud, ma un inconscio implicito, vicino sia alla psicodinamica contemporanea sia alla psicologia cognitiva.</li>
</ul>
<p>Per le teorie della svolta relazionale possono esistere differenze costituzionali tra le persone, ma il loro significato dipende soprattutto da come reagiscono le persone significative intorno a noi: biologia e ambiente si influenzano a vicenda fin dall'inizio, in un processo continuo, e non vanno quindi studiati separatamente.</p>

