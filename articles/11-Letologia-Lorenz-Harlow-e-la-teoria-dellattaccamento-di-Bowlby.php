<p>Bowlby sostiene che gli istinti umani (in questo caso, i comportamenti di attaccamento) sono già 
"tarati" fin dalla nascita per funzionare bene in un ambiente sociale umano tipico — 
non sono pulsioni "grezze" (polemica con freud) e asociali che entrano in conflitto con l'ambiente e devono essere addomesticate. </p>

<p>Infine Per Bowlby le ipotesi teoriche vanno sempre valutate sulla base di studi empirici.</p>

<p>Per Bowlby l'attaccamento è ricerca di sicurezza, caratterizzata da:</p>
<ul>
<li>il bisogno di <strong>stare vicino</strong> a un'altra persona, e di tornare vicino a lei se questa vicinanza viene a mancare;</li>
<li>il bisogno che questa persona sia <strong>sempre la stessa</strong>, riconosciuta dal bambino: di solito è la madre biologica, 
ma può essere chiunque svolga stabilmente questo ruolo, per esempio una madre adottiva.</li>
</ul>



<h3>L'attaccamento come istinto e il sistema di attaccamento</h3>
<p>L'<strong>attaccamento è un istinto innato, e selezionato per il mantenimento della specie</strong>. 
I legami emotivi intimi si sviluppano grazie al sistema di attaccamento presente sin dalla nascita.</p>

<p>Come per Lorenz, anche per Bowlby il <strong>comportamento di attaccamento svolge una funzione biologica fondamentale, cioè 
garantisce la sopravvivenza</strong>, aumentando le probabilità di sopravvivenza del bambino. Il centro di questa teoria 
è la specie, non l'individuo. Ed è proprio questo uno degli aspetti più criticati dalla comunità psicoanalitica dell'epoca.</p>





<h3>I comportamenti di attaccamento</h3>
<p>I comportamenti di attaccamento possono essere:</p>
<ul>
<li><strong>comportamenti segnale</strong>: per esempio vocalizzare, sorridere;</li>
<li><strong>comportamenti avversivi</strong>: per esempio gridare o piangere, per richiamare l'attenzione della madre;</li>
<li><strong>comportamenti attivi</strong>: per esempio avvicinarsi e seguire.</li>
</ul>
<p>La vicinanza garantisce il senso di sicurezza che, a sua volta, permette l'attivarsi di <strong>comportamenti esplorativi</strong>, i quali 
invece non si attivano quando la sicurezza è minacciata: non dovendo spendere energie per garantirsi la sicurezza, 
il bambino può dedicarle all'esplorazione dell'ambiente e a uno sviluppo cognitivo, emotivo e motorio più rapido ed efficace 
(proprio come le scimmiette di Harlow cresciute con la madre di stoffa).</p>






<h3>Il sistema di accudimento</h3>
<p>Il <strong>sistema di accudimento</strong> è il sistema che si attiva 
nella figura di allevamento principale quando i comportamenti di attaccamento del bambino segnalano il bisogno di vicinanza e 
sicurezza. Include comportamenti che offrono vicinanza, aiuto e protezione dal pericolo (per esempio un abbraccio confortante).</p>

<p>All'epoca di Bowlby era diffusa l'idea che il bambino 
andasse lasciato piangere per non viziarlo, mentre Bowlby e Ainsworth mostreranno che sono proprio i bambini le cui madri 
rispondono con più empatia e immediatezza a sentirsi più sicuri, e quindi a essere meno "viziati", perché possono impiegare 
le proprie energie nell'esplorazione dell'ambiente.</p>





<h3>L'attaccamento nell'arco del ciclo di vita</h3>
<p>Bowlby introdusse un concetto importante: l'attaccamento non riguarda solo la prima infanzia, ma <strong>è un tema centrale 
della vita umana nell'arco dell'intero ciclo di vita</strong></p>

</p>Le esperienze vissute con le figure di attaccamento nei primi anni rappresentano il modello 
su cui si organizzano tutti i legami affettivi successivi, comprese le aspettative sulle situazioni nuove, la suscettibilità 
alla paura, la valutazione del proprio valore personale e la possibilità di ricevere riconoscimento e aiuto.</p>





<h3>I modelli operativi interni (MOI)</h3>
<p>Attraverso le esperienze con le figure di accudimento, l'individuo costruisce i <strong>modelli operativi interni</strong> 
(MOI): rappresentazioni mentali di chi si prende cura di noi, di noi stessi e della relazione tra i due, che guidano il modo 
in cui interpretiamo gli eventi e ci fanno formare aspettative sulla nostra vita relazionale.</p> 

<p>Si formano perché le prime 
interazioni con i genitori, ripetute nel tempo, vengono astratte in modelli generali di come funziona di solito una relazione: 
un concetto vicino all'<strong>inconscio rappresentazionale</strong> già incontrato nella teoria intersoggettiva (l'inconscio 
preriflessivo), cioè un contenuto inconscio non perché rimosso, ma perché implicito — proprio il punto di contatto tra la 
psicologia dinamica contemporanea e la psicologia cognitiva.</p>





<h3>Il metodo: la sensibilità empirica di Bowlby</h3>
<p>Rispetto alle teorie psicoanalitiche precedenti, Bowlby aggiunge un elemento nuovo: le <strong>ipotesi teoriche devono essere 
valutate sulla base di studi empirici</strong>. In particolare, la teoria dell'attaccamento doveva essere verificata 
attraverso l'<strong>osservazione diretta del comportamento del bambino in situazioni angosciose di separazione dalla 
figura materna</strong>.</p> 

<p>Le definizioni astratte della teoria andavano quindi tradotte in operazioni basate su osservazioni 
delle situazioni di separazione dalla figura di allevamento principale.</p> 

<p>Proprio questa operazione, 
secondo Anna Freud, Melanie Klein e gli altri esponenti della società psicoanalitica dell'epoca, rischiava di 
distorcere concetti psicoanalitici troppo complessi per essere tradotti in definizioni operazionali.</p>


