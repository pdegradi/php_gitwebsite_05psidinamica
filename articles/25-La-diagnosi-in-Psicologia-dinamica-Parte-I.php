<h2>La diagnosi psicologica</h2>

<p>Secondo Dazzi, Lingiardi e Gazzillo (2009), la <strong>diagnosi psicologica</strong> è sia il processo con cui si cerca di
conoscere il funzionamento psichico di una persona, sia la denominazione attribuita a quel funzionamento attraverso una
terminologia condivisa dalla comunità scientifica.</p>

<h3>Cosa deve identificare la diagnosi?</h3>

<p>La diagnosi deve cogliere gli aspetti specifici che rendono unico il paziente e quelli che ha in comune con altre persone.
Senza elementi condivisi sarebbe impossibile comunicare tra clinici o scegliere trattamenti sostenuti dalla letteratura.</p>

<h3>A cosa serve la diagnosi psicologica?</h3>

<p>La diagnosi psicologica serve a tre scopi principali.</p>

<ul>
<li><strong>Condividere le informazioni</strong> tra clinici e con il paziente usando un linguaggio semplice e sintetico.</li>
<li><strong>Orientare il trattamento</strong> confrontando le ipotesi sul paziente con la letteratura clinica ed empirica.</li>
<li><strong>Fare ricerca e orientare la clinica</strong> raccogliendo informazioni sistematiche su gruppi con caratteristiche
comuni.</li>
</ul>

<h3>La formulazione del caso</h3>

<p>La diagnosi non si limita a un'etichetta. Si completa con la <strong>formulazione del caso</strong>, cioè un resoconto
narrativo e sistematico delle informazioni raccolte. Il testo descrive sia l'unicità del paziente sia gli elementi che
permettono di collocarlo in un quadro psicologico conosciuto. Serve a comunicare con chiarezza quanto emerso al paziente o a un
altro professionista.</p>






<h2>La diagnosi descrittiva</h2>
<p>Il riferimento internazionale più usato oggi in psicologia e psichiatria è la <strong>diagnosi descrittiva</strong>,
rappresentata soprattutto dal <strong>DSM</strong> (il Manuale Diagnostico e Statistico dei Disturbi Mentali, giunto alla
quinta edizione). Si basa sulle informazioni riferite dai pazienti (i sintomi) o direttamente osservabili (i segni).</p>
<p>È <strong>ateorica</strong>: non si fonda su un modello di funzionamento mentale predefinito, ma solo su ciò che il paziente
riporta e su ciò che è osservabile in modo oggettivo o attraverso misure standardizzate. Questo permette la comunicazione tra
clinici di orientamento diverso, per esempio tra psichiatri e psicoterapeuti, senza che un modello teorico definito a priori
influenzi la definizione del quadro psicologico del paziente.</p>
<p>È inoltre <strong>categoriale</strong>: identifica sindromi discrete, come se ogni disturbo (la depressione, il disturbo
d'ansia generalizzato, la fobia specifica, la schizofrenia) fosse un quadro a sé, separato dagli altri. La depressione, per
esempio, è definita da un elenco di sintomi di cui il paziente deve presentarne almeno cinque, tra cui almeno due obbligatori,
per almeno due settimane consecutive (umore depresso, riduzione dell'energia, alterazioni dell'appetito, insonnia, perdita di
piacere nelle attività). Nell'ultima edizione, il DSM-5 (Associazione psichiatrica americana, 2013), la descrizione
categoriale di ogni diagnosi è accompagnata anche da alcuni aspetti dimensionali, come la valutazione della gravità dei sintomi
o la presenza di sintomi transdiagnostici.</p>



<h3>La diagnosi descrittiva categoriale</h3>
<p>Tra i <strong>vantaggi</strong> della diagnosi categoriale:</p>
<ul>
<li>crea un linguaggio comune tra professionisti di orientamenti diversi, e tra clinica e ricerca, snellendo la comunicazione.</li>
<li>può avere un effetto <strong>normalizzante</strong> per il paziente, che scopre che i suoi sintomi sono noti al clinico e
condivisi con molte altre persone.</li>
<li>fornisce al clinico indicazioni su sintomi che potrebbero manifestarsi nel tempo, per esempio in termini di crisi attese.</li>
</ul>
<p>Tra gli <strong>svantaggi</strong>:</p>
<ul>
<li>porta a un'eccessiva <strong>comorbilità</strong>: un paziente riceve più diagnosi insieme, e la comorbilità è la norma più
che l'eccezione. Questo obbliga a stabilire una gerarchia tra disturbo primario e secondario, con il rischio di sottovalutare
i sintomi del disturbo definito secondario.</li>
<li>porta a un'eccessiva <strong>eterogeneità interna</strong>: due pazienti con la stessa diagnosi possono presentare quadri
sintomatologici molto diversi. Una ragazza di vent'anni e una donna anziana possono avere entrambe una diagnosi di
depressione, ma ragioni esistenziali, motivazioni ed esperienze di vita molto diverse, che forse richiedono trattamenti
diversi.</li>
<li>non prevede tutte le possibili cause di sofferenza dei pazienti, e rischia di favorire fenomeni di etichettamento e stigma.
Per questo è preferibile la formula "persona con disturbo depressivo" piuttosto che "depresso", per sottolineare che
l'individualità della persona resta distinta dal disturbo.</li>
</ul>



<h3>Lo scetticismo della psicologia dinamica</h3>
<p>Il mondo della psicologia dinamica ha sempre nutrito forti dubbi sulla diagnosi categoriale descrittiva: per la prospettiva
psicodinamica è importante dare il massimo valore ai significati personali e all'unicità dell'individuo. D'altra parte, per
identificare gli aspetti in comune tra pazienti diversi, e per condividere le informazioni nella comunità clinica e
scientifica, resta comunque necessario un linguaggio semplice che sottolinei gli aspetti generalizzabili del quadro
sintomatologico presentato da quel particolare individuo.</p>






<h2>La diagnosi psicodinamica</h2>
<p>La valutazione in psicologia dinamica non si concentra sui sintomi e sui segni, ma su aspetti più inferenziali e comprensivi: i
meccanismi di difesa, le angosce, il tipo e il livello di compromissione delle funzioni psichiche, le relazioni oggettuali. La
valutazione psicodinamica si concentra quindi su aspetti di personalità che si manifestano nel tempo e in contesti diversi,
intesi come modi stabili di pensare, sentire, regolare le emozioni, gestire gli impulsi e agire. Se da un lato la diagnosi in
psicologia dinamica si concentra su aspetti strutturali (l'inconscio rappresentazionale, la memoria implicita, i modi di fare,
gli schemi, i <strong>MOI</strong>, cioè i modelli operativi interni), dall'altro ha la peculiarità di essere molto orientata
su una teoria ben definita, quella psicodinamica appunto.</p>



<h3>La diagnosi strutturale secondo Kernberg</h3>
<p>Il primo modello di diagnosi psicodinamica è la <strong>diagnosi strutturale</strong> presentata da <strong>Otto
Kernberg</strong>. È basata su un modello psicoanalitico integrato, che unisce la psicoanalisi freudiana e kleiniana, la
Psicologia dell'Io, la teoria delle relazioni oggettuali, le ricerche sull'infanzia e sulla biologia delle emozioni. Il suo
obiettivo non è categorizzare i disturbi, ma elaborare un profilo delle diverse organizzazioni di personalità, inferendo il
livello di funzionamento da un insieme di indicatori capaci di rendere conto di numerosi processi emotivi, cognitivi,
motivazionali e comportamentali direttamente osservabili. La diagnosi strutturale rivolge quindi l'attenzione ad aspetti
stabili di personalità, non solo a segni e sintomi.</p>



<h3>Le organizzazioni della personalità</h3>
<p>Kernberg identifica tre macrostrutture di personalità:</p>
<ol>
<li>psicotica.</li>
<li>borderline.</li>
<li>nevrotica.</li>
</ol>
<p>Queste tre macrostrutture vengono identificate in base alla valutazione di tre diversi criteri:</p>
<ul>
<li><strong>diffusione vs integrazione dell'identità</strong>: il livello di integrazione degli aspetti di sé (per esempio buoni e
cattivi), degli altri, e degli affetti connessi a tali aspetti. Ognuno di noi ha aspetti poco coerenti tra loro (per esempio
essere socievoli e allo stesso tempo poco gentili), e il livello di integrazione di questi aspetti incoerenti, all'interno
della propria personalità come di quella altrui, definisce il livello di integrità dell'identità.</li>
<li>prevalenza di <strong>meccanismi di difesa maturi vs primitivi</strong>: i meccanismi primitivi si organizzano attorno alla
scissione delle rappresentazioni di sé e degli altri in "tutto buono" e "tutto cattivo" (per esempio identificazione
proiettiva, diniego, idealizzazione), e impediscono la formazione di rappresentazioni differenziate e complesse di sé e
dell'altro. I meccanismi maturi, invece, non distorcono la realtà e permettono soluzioni di compromesso (per esempio
rimozione, spostamento, formazione reattiva).</li>
<li><strong>tenuta dell'esame di realtà</strong>: il livello di differenziazione tra sé stessi e la propria vita interiore e
quella degli altri, tra la fantasia e la realtà. È la capacità di valutare realisticamente i propri sentimenti, comportamenti
e pensieri nel quadro delle norme sociali condivise.</li>
</ul>



<h3>La valutazione dell'organizzazione della personalità</h3>
<p>In base a questi tre criteri, la personalità <strong>nevrotica</strong> presenta un'identità integrata (le rappresentazioni di
sé e dell'oggetto sono integrate, così come gli aspetti incoerenti di sé e dell'altro), usa difese mature, e mantiene l'esame
di realtà. La personalità <strong>psicotica</strong> presenta invece una dispersione dell'identità (gli aspetti contraddittori
del Sé e degli altri sono scarsamente integrati e tenuti separati), usa difese primitive, e ha l'esame di realtà alterato. La
personalità <strong>borderline</strong> può presentare entrambe le strutture per quanto riguarda l'integrazione dell'identità,
usa difese primitive come la personalità psicotica, ma mantiene in parte la capacità di esaminare la realtà, cioè di
differenziare il Sé dagli altri e gli aspetti intrapsichici dalle percezioni e dagli stimoli esterni.</p>



<h3>L'intervista strutturale</h3>
<p>Come si arriva a valutare questi criteri, e quindi a definire l'organizzazione di personalità del paziente? Attraverso
un'intervista strutturale. Il modello di Kernberg prevede che il clinico svolga un colloquio orientato a identificare
l'organizzazione della personalità del paziente, esplorando e interpretando, attraverso una serie di domande, la relazione
terapeutica, i sintomi, i tratti caratteriali patologici, le difficoltà e i conflitti del paziente. Il colloquio si divide in
tre fasi:</p>
<ul>
<li>nella <strong>fase iniziale</strong>, il clinico approfondisce la richiesta del paziente e i tratti caratteriali patologici,
cercando di capire perché il paziente ha chiesto aiuto intraprendendo un percorso psicoterapeutico.</li>
<li>nella <strong>fase centrale</strong>, le domande si concentrano sulla rappresentazione di sé stessi e degli altri.</li>
<li>nella <strong>fase conclusiva</strong>, l'analista chiede al paziente se ci sono temi importanti non ancora trattati.</li>
</ul>



<h3>L'intervista strutturata per la valutazione dell'organizzazione di personalità</h3>
<p>Queste domande sono state formalizzate nell'<strong>intervista strutturata per la valutazione dell'organizzazione di
personalità</strong> (Buchheim et al., 2006, Clarkin et al., 2007). La somministrazione richiede circa due ore. Il valutatore
assegna un punteggio a ogni risposta, da 0 (assenza di patologia) a 2 (presenza di una patologia di personalità), seguendo le
istruzioni del manuale. Per alcuni elementi è previsto anche il punteggio 3, mentre una risposta incompleta o mancante riceve il
punteggio 9. Il punteggio per ogni criterio equivale alla media dei punteggi degli elementi relativi a quella dimensione, e il
valutatore assegna infine un punteggio complessivo per ogni dimensione, da 1 (assenza di patologia) a 5 (funzionamento
patologico). L'intervista è uno strumento utile per ottenere risultati replicabili e promuovere la ricerca clinica in
psicologia dinamica. Sia il modello strutturale di Kernberg sia le altre proposte di diagnosi psicodinamica non nascono con
l'obiettivo di sostituire la diagnosi descrittiva categoriale, ma di accompagnarla, approfondirla e integrarla, per avvicinare
la ricerca alla pratica clinica.</p>






<h2>La Shedler-Westen Assessment Procedure (SWAP)</h2>
<p>Un altro modello diagnostico è la <strong>Shedler-Westen Assessment Procedure</strong> (SWAP, procedura di valutazione di
Shedler e Westen), proposta da <strong>Drew
Westen</strong> e <strong>Jonathan Shedler</strong>: una procedura di valutazione dei tratti e degli stili, sani e patologici,
della personalità di adulti e adolescenti. Per tratti di personalità si intendono le tendenze a reagire in modi specifici e
relativamente stabili a situazioni intrapersonali o interpersonali vissute in modo analogo, un concetto vicino a quello di MOI
o di memoria implicita. La SWAP è fondata su una concezione dimensionale della personalità, e ritiene che tutti gli individui
abbiano caratteristiche riconducibili a stili di personalità, differenziandosi per il livello di intensità di aderenza a un
particolare stile e per il livello di interazione tra i diversi aspetti. L'idea della SWAP è che una concezione dimensionale
della personalità debba essere associata a una concezione categoriale, per poter formulare una diagnosi appropriata.</p>



<h3>La diagnosi funzionale</h3>
<p>La diagnosi della personalità si basa su quattro domini funzionali:</p>
<ol>
<li>le motivazioni, gli standard ideali, i valori morali, le paure e i conflitti.</li>
<li>gli stili cognitivi, le strategie e le capacità di regolazione delle emozioni, i meccanismi di difesa e, in generale, le
capacità e le risorse psicologiche.</li>
<li>le rappresentazioni di sé, degli altri, e delle relazioni tra sé e gli altri.</li>
<li>il modo in cui questi domini si sono sviluppati durante il corso della vita.</li>
</ol>



<h3>Gli obiettivi della SWAP</h3>
<p>Gli obiettivi della SWAP sono fornire, attraverso l'esplorazione sistematica dei quattro domini funzionali, e quindi delle
risorse e dei tratti patologici dell'individuo, una formulazione del caso condivisibile e generalizzabile. La diagnosi
psicodinamica tende cioè a integrare la diagnosi categoriale descrittiva attraverso metodi che possono essere usati sia in
clinica sia in ricerca in modo sistematico, per definire non solo la diagnosi ma una diagnosi completa, che è appunto la
formulazione del caso. La SWAP ha quindi lo scopo di avvicinare la clinica alla ricerca, attraverso una procedura di
valutazione empirica della personalità.</p>
<p>La SWAP segue una procedura <strong>Q-sort</strong> (ordinamento Q, una classificazione forzata). Per ogni costrutto di indagine, lo strumento è composto da una serie di
affermazioni descrittive delle caratteristiche del costrutto, che il valutatore deve distribuire gerarchicamente, posizionando
per primo l'item che ritiene descriva meglio la persona valutata. Il clinico compila lo strumento dopo aver lasciato che il
paziente si esprima in modo aperto e approfondito, in modo da ottenere uno strumento condivisibile tra clinici e ricercatori.
In totale lo strumento è composto da 200 item (SWAP-200), ognuno valutato su una scala da 0 (non descrive affatto il paziente)
a 7 (descrive totalmente il paziente). Il clinico è però vincolato da una <strong>distribuzione fissa</strong>: deve attribuire
un numero specifico di item a ciascun punteggio (la metà degli item deve avere punteggio 0, 22 su 200 punteggio 1, 18 item
punteggio 2, 14 punteggio 4, 12 punteggio 5, 10 punteggio 6 e 8 punteggio 7), per ridurre al minimo le differenze soggettive di
valutazione tra clinici. Gli item della SWAP derivano dai criteri del DSM, dalla letteratura clinica ed empirica su
personalità, disturbi di personalità, meccanismi di difesa e di coping, stili cognitivi, e dall'esperienza clinica degli
autori. Si raccomanda al clinico di valutare gli item della SWAP dopo tre-cinque colloqui di valutazione iniziale.</p>



<h3>La diagnosi con la SWAP</h3>
<p>La SWAP fornisce due tipi di diagnosi:</p>
<ul>
<li><strong>diagnosi categoriale</strong>: viene fatta in fattori PD ("personality disorders", disturbi di personalità). Il
profilo del paziente, cioè l'organizzazione e il punteggio dei 200 item, viene valutato in base alla sua somiglianza,
calcolata tramite sistemi statistici, con prototipi di disturbi di personalità basati sui criteri dell'Asse II del DSM.</li>
<li><strong>diagnosi dimensionale</strong>: viene fatta in fattori Q (stili di personalità). Il profilo del paziente viene
valutato in base alla sua somiglianza con stili di personalità definiti su base empirica a partire da circa 500 descrizioni
SWAP di pazienti reali con disturbo di personalità diagnosticato con il DSM.</li>
</ul>



<h3>I fattori Q o stili di personalità</h3>
<p>La SWAP fornisce una lista di fattori Q, o stili di personalità:</p>
<ul>
<li><strong>disforico</strong>: caratteristiche di inadeguatezza, inferiorità, fallimento, infelicità, depressione, vergogna o
imbarazzo, colpa, debolezza, impotenza, dipendenza, sottomissione, passività e bassa assertività.</li>
<li><strong>antisociale psicopatico</strong>: disonestà, bassa moralità, rabbia, ostilità, impulsività, manipolazione degli altri,
basso interesse per le conseguenze delle proprie azioni e per i danni provocati agli altri, bassa empatia.</li>
<li><strong>schizoide</strong>: assenza di relazioni o amicizie strette, restrizione della gamma di emozioni e delle capacità
sociali, timidezza, riservatezza, inibizione, difficoltà a comprendere il comportamento altrui, bassa capacità di descrivere
gli altri, bassa comprensione delle proprie motivazioni, tendenza a pensare in termini concreti, presenza di aspetti o modi di
fare atipici.</li>
<li><strong>paranoide</strong>: tendenza a tenere il broncio, sentirsi incompreso, maltrattato, vittimizzato, rabbia, ostilità,
arroganza, moralismo, bassa tolleranza alle critiche.</li>
<li><strong>ossessivo</strong>: il più adattivo tra questi stili. Coscienziosità, responsabilità, alti standard morali ed etici,
alta capacità di usare i propri talenti e le proprie energie in modo efficace, tendenza a vedersi come una persona logica e
razionale, a essere controllante, a un'eccessiva dedizione al lavoro, a trovare significato negli obiettivi a lungo termine.</li>
<li><strong>istrionico</strong>: dipendenza affettiva, con richiesta eccessiva di approvazione e rassicurazione, tendenza a
sviluppare attaccamenti intensi rapidamente, a innamorarsi di chi non è disponibile, a esprimere in modo eccessivo le
emozioni, bassa capacità di calmarsi, eccessiva paura dell'abbandono e del rifiuto.</li>
<li><strong>narcisistico</strong>: tendenza a fantasie di successo, bellezza, potere, talento, a sentirsi privilegiato e con
maggiori diritti, a cercare di essere al centro dell'attenzione, ad aspettarsi di essere perfetto, a provare invidia per gli
altri e a pensare che gli altri siano invidiosi di lui.</li>
</ul>



<h3>Il fattore Q disforico</h3>
<p>Lo stile disforico rappresenta circa il 20% dei pazienti valutati attraverso la SWAP, ed è per questo suddiviso in cinque
sottofattori:</p>
<ul>
<li><strong>evitante</strong>: tendenza a essere timidi, riservati, a evitare le situazioni sociali per il timore dell'imbarazzo,
a essere passivi, poco assertivi e con basse capacità sociali.</li>
<li><strong>depressivo (nevrotico) ad alto funzionamento</strong>: accanto all'umore disforico e ai sensi di colpa, si trovano
aspetti più funzionali, come empatia, standard etici e morali, intuitività e tendenza a risultare simpatici.</li>
<li><strong>emotivamente disregolato</strong>: tendenza a provare emozioni che sfuggono al controllo, frequenti pensieri e
tentativi suicidari.</li>
<li><strong>dipendente-masochista</strong>: tendenza a coinvolgersi o a rimanere in relazioni in cui si subiscono abusi emotivi o
fisici, ad attaccarsi agli altri in modo rapido e intenso, a un'eccessiva dipendenza.</li>
<li><strong>esteriorizzazione dell'ostilità</strong>: rabbia, ostilità, tendenza a partecipare a lotte di potere, ad accusare gli
altri dei propri fallimenti, a sentirsi vittima.</li>
</ul>






<h2>Una nuova nosografia: la SWAP-II</h2>
<p><strong>Westen e Shedler (2007)</strong> hanno condotto analisi preliminari su un ampio campione, e hanno proposto una nuova
nosografia empiricamente derivata, che prevede quattro cluster di stili di personalità:</p>
<ul>
<li><strong>cluster interiorizzante</strong>: ansioso, depressivo, dipendente, schizoide.</li>
<li><strong>cluster esteriorizzante</strong>: psicopatico, paranoide, schizoide.</li>
<li><strong>cluster borderline</strong>: emotivamente disregolato, istrionico/impulsivo.</li>
<li>uno stile di <strong>alto funzionamento</strong>.</li>
</ul>

