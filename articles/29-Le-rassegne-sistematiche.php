<p>Tutte le rassegne, sistematiche o meno, condividono un obiettivo comune: descrivere la maggior parte della letteratura
disponibile su un tema.</p> 

<img XXclass="zoomable" src="/assets/images/29/EaseUS_2026_09_ 3_10_27_07.webp" />

<p>Le rassegne, incluse quelle narrative, formano il gruppo più ampio. Al loro interno esiste un gruppo più
ristretto, quello delle <strong>rassegne sistematiche</strong>. All'interno di questo esiste un gruppo ancora più piccolo, quello
delle <strong>metanalisi</strong>, cioè le rassegne sistematiche con in più una componente statistica.</p>


<h2>Le rassegne narrative</h2>
<p>Le rassegne narrative hanno, come tutte le rassegne, l'obiettivo di <strong>raggruppare la letteratura esistente su un argomento in
un unico documento</strong>.</p>
<p>L'autore di una rassegna narrativa non ha lo scopo di coprire al 100% tutta la letteratura pubblicata. Vuole piuttosto mettere in
evidenza i punti principali, da un punto di vista parzialmente
oggettivo ma anche influenzato dalle considerazioni personali dell'autore.</p> 
<p>In genere gli autori sono esperti del tema, quindi
la selezione della letteratura non è arbitraria, ma nemmeno completamente sistematica e oggettiva.<p> 
    
<p>Una rassegna narrativa è
quindi principalmente descrittiva, e non utilizza una strategia di ricerca e valutazione della letteratura sistematica.</p>



<h2>Le rassegne sistematiche</h2>
<p>Sono <strong>riassunti</strong> che hanno l'obiettivo di includere tutti gli studi precedenti su un tema di interesse. </p>
<p>Una revisione sistematica viene realizzata attraverso un <strong>processo sistematico</strong>, scientifico rigoroso, per ridurre
quanto più possibile, e documentare, gli errori sistematici e quelli casuali.</p> 

<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 104844.webp" />

<p>Chi conduce una ricerca sistematica vuole
descrivere oggettivamente tutto ciò che è stato pubblicato su un determinato argomento, riducendo la componente soggettiva a
favore di una più oggettiva: per farlo definisce a priori i metodi di ricerca, selezione, osservazione ed estrazione dei dati,
interpretazione e valutazione critica, seguendo linee guida già esistenti. Questo significa anche che, se altri ricercatori
vogliono aggiornare la rassegna anni dopo, possono farlo senza problemi, perché tutto è documentato e protocollato.</p>



<h2>Le meta-analisi</h2>
<p>Le <strong>meta-analisi</strong> non sono altro che rassegne sistematiche che includono una 
<strong>componente statistica</strong></p>

<p>Per esempio, se tre studi valutano le stesse differenze con misure comparabili, le rispettive medie 
possono essere riunite in un'unica media statistica riassuntiva.</p>

<p>Una meta-analisi può:</p>
<ul>
<li><strong>combinare i risultati dei singoli studi</strong>: si può definire anche come un'analisi statistica dei 
risultati di studi indipendenti, che produce una singola stima numerica dell'effetto</li>
<li><strong>esplorare l'eterogeneità tra gli studi</strong>: per esempio, tre studi
condotti in tre paesi diversi, in orari diversi della giornata o in contesti diversi potrebbero dare risultati differenti 
per ragioni che non hanno a che fare con la variabile studiata. 
Questa eterogeneità può essere valutata calcolando un indice statistico di eterogeneità.</li>
</ul>


<p>Tutte le forme di rassegna possono essere utili, comprese quelle narrative che a volte servono per farsi un'idea di un tema. 
Da un punto di vista oggettivo, però, le rassegne sistematiche e le meta-analisi
sono più informative, perché riducono al minimo le interferenze soggettive. Per questo alcune riviste scientifiche
incoraggiano esplicitamente gli autori a inviare rassegne sistematiche e meta-analisi costruite secondo linee guida precise, e
con un piano metodologico reso pubblico prima dell'inizio del lavoro</p> 

<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 105545.webp" />

<p>Un esempio noto è quello della <strong>Sindrome di morte improvvisa dell'infante</strong> (SIDS). 
<p>
Una raccolta sistematica dei dati avrebbe mostrato già negli anni ’70 che la posizione durante il sonno era un importante 
fattore di rischio. Gilbert (2005) stimò che applicare questa evidenza già nel 1970 avrebbe potuto evitare circa 10.000 
morti infantili in Gran Bretagna e almeno 50.000 nel resto del mondo occidentale. 
Questo mostra l’importanza di una visione sistematica e complessiva dei dati nella ricerca e nella pratica clinica.
</p>



<h2>La psicologia basata sull'evidenza empirica</h2>
<p>Da questa esigenza nasce la <strong>psicologia basata sull'evidenza empirica</strong>, parte della più ampia medicina 
basata sull'evidenza. È un <strong>approccio interdisciplinare</strong> secondo cui le decisioni cliniche devono basarsi 
sulle <strong>prove empiriche disponibili</strong>, raccolte e interpretate secondo criteri specifici.</p>

<p>Le evidenze derivano dalla <strong>raccolta sistematica dei dati</strong>. Un singolo studio non è sufficiente, 
perché può presentare limiti ed errori: per questo la ricerca deve essere <strong>sistematica e critica</strong>. 
Inoltre, il valore delle informazioni dipende anche dalla qualità e dalla dimensione dello studio 
(es. uno studio su 3 pazienti fornisce meno informazioni di uno su 300).</p>



<h3>La piramide dell'evidenza</h3>
<p>Una figura spesso usata per capire come utilizzare la letteratura scientifica, e a quale tipo di studio dare più rilevanza,
è la piramide dell'evidenza.</p> 

<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 112706.webp" />

<ul>
    <li>Al livello più basso ci sono gli <strong>articoli con l'opinione di esperti del settore</strong>: 
    sono utili perché danno idee e ispirazioni su temi ancora poco esplorati, ma a livello di evidenza empirica non sono molto forti.</li>
    <li>Al secondo livello ci sono le <strong>descrizioni di casi di pazienti</strong>: 
    interessanti e a volte fonte di ispirazione, ma poco informative dal punto di vista statistico</li>
    <li>Poi ci sono gli <strong>studi caso-controllo</strong>, che confrontano dei gruppi trovando associazioni, ma senza 
poter dire nulla sulla direzione della
relazione (dicono che la variabile A è associata alla variabile B, ma non se è A a causare B, o viceversa, o se esiste una
terza variabile che spiega entrambe)</li>
    <li>Ci sono poi gli <strong>studi longitudinali</strong>, che seguono nel tempo un campione di persone
inizialmente prive della malattia, usando le correlazioni per stimare il rischio assoluto di svilupparla: sono già molto più
informativi, perché danno indicazioni sulla direzione della relazione tra due variabili</li>
    <li>Ci sono poi <strong>gli studi randomizzati controllati</strong>, che permettono di valutare l'efficacia di uno specifico trattamento in
una determinata popolazione.</li>
    <li>Ci sono le <strong>revisioni della letteratura</strong>, che esaminano e sintetizzano in un unico articolo i lavori 
precedentemente prodotti su un certo quesito clinico. 
Proprio per questo le rassegne sistematiche sono gli studi più informativi, e hanno l'ambizione di guidare la ricerca
futura e la pratica clinica.</li>
</ul>




<h3>Come si conduce una rassegna sistematica?</h3>
<p>I passaggi principali sono questi.</p>
<ol>
<li>Definire il quesito della rassegna.</li>
<li>Stabilire i criteri di inclusione ed esclusione, le banche dati e le parole chiave.</li>
<li>Salvare tutti i riassunti e documentare la procedura.</li>
<li>Selezionare i riassunti rilevanti e recuperare i testi completi.</li>
<li>Selezionare gli studi definitivi e controllarne i riferimenti bibliografici.</li>
<li>Cercare anche la letteratura non pubblicata.</li>
<li>Estrarre i dati qualitativi e descrittivi.</li>
<li>Valutare le possibili distorsioni sistematiche.</li>
<li>Presentare e discutere i risultati.</li>
</ol>



<h2>Le linee guida PRISMA</h2>
<p>Esistono linee guida precise, disponibili anche in italiano, che aiutano a seguire tutti questi passaggi senza
dimenticarne nessuno. L'<strong>obiettivo</strong> è che un altro
ricercatore, in un paese diverso, abbia tutte le informazioni utili per poter ripetere esattamente la stessa ricerca e
replicarne i risultati.</p> 

<p>Le più note sono le linee guida <strong>PRISMA</strong>. 
Sono disponibili anche in italiano e comprendono un <strong>elenco di controllo</strong> e un
<strong>diagramma di flusso</strong> che i
ricercatori compilano nello svolgimento del lavoro.</p>




<h3>PRISMA Statement Checklist</h3>

<p>La checklist <strong>PRISMA</strong> raccoglie i principali passaggi da seguire in una 
<strong>rassegna sistematica</strong> e indica dove sono riportate le relative informazioni.</p>
<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 114458.webp" />
<ul>
<li>definire chiaramente il <strong>quesito di ricerca e gli obiettivi</strong>;</li>
<li>stabilire i <strong>criteri di inclusione</strong> degli studi (partecipanti, intervento, lingua, anno, ecc.);</li>
<li>definire una <strong>strategia di ricerca efficace</strong>;</li>
<li>valutare il <strong>rischio di bias</strong> degli studi;</li>
<li>effettuare una <strong>chiara estrazione e sintesi dei dati</strong>.</li>
</ul>

<p>Anche senza una vera meta-analisi, è importante raccogliere dati descrittivi sugli studi, come <strong>numero 
    e caratteristiche dei partecipanti, strumenti utilizzati e modalità di definizione della condizione studiata</strong>.</p>





<h3>PRISMA Statement - Diagramma di flusso</h3>
<p>Oltre all'elenco di controllo, le linee guida PRISMA offrono un <strong>diagramma di flusso</strong> che ogni rassegna sistematica
deve riportare, e che aiuta a capire visivamente come è stata condotta la ricerca e <strong>quali risultati ha portato la
ricerca della letteratura</strong>.</p> 
<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 114522.webp" />
<p>Da una parte si riportano i <strong>motori di ricerca</strong> usati e quanti riassunti sono stati trovati su ciascuno. 
In un altro riquadro si segnala se sono state usate <strong>altre fonti</strong>, 
per esempio contattando esperti o cercando tra <strong>studi non pubblicati</strong>. Si
riporta poi quanti doppioni sono stati esclusi, quanti riassunti sono stati letti e selezionati, quanti studi sono stati
valutati per intero, e infine quanti studi sono stati effettivamente utilizzati nella rassegna sistematica.</p>



<h3>La Cochrane Collaboration</h3>
<p>Le linee guida PRISMA sono state elaborate in collaborazione con la <strong>Cochrane Collaboration</strong>: 
una <strong>iniziativa internazionale senza scopo di lucro</strong> nata con lo <strong>scopo di raccogliere,
valutare criticamente e diffondere le informazioni relative all'efficacia e alla sicurezza degli interventi sanitari</strong>.</p>



<h3>La ricerca e la selezione della letteratura</h3>
<p>Le <strong>strategie di ricerca</strong> comprendono gli studi pubblicati nelle banche dati, il controllo manuale dei
riferimenti, gli studi non pubblicati, gli atti dei convegni e il contatto diretto con esperti. Per una tesi può bastare la
ricerca nelle banche dati. Una vera rassegna sistematica deve usare più canali.</p>
<p>I criteri di inclusione ed esclusione riguardano l'<strong>anno</strong> e la <strong>lingua</strong> di pubblicazione, il
<strong>tipo</strong> di studio, le caratteristiche dei <strong>campioni</strong>, i <strong>metodi</strong> e i dati
riportati.</p> 

<p>È fondamentale anche definire con cura le <strong>parole
chiave</strong>: un motore di ricerca cerca esattamente quello che gli viene chiesto, senza intelligenza propria, quindi
parole chiave scritte bene, comprensive di abbreviazioni e nomi per esteso, permettono di non perdere studi rilevanti. La
ricerca della letteratura si fa su banche dati come PubMed, PsycINFO, MedLine, Embase e la banca dati Cochrane delle rassegne
sistematiche.</p>



<h3>Come funziona la selezione della letteratura?</h3>
<p>Una volta inserite le parole chiave, per esempio su PubMed, si ottiene una lista di riassunti. Invece di leggerli online, con
il rischio di non riuscire più a ricostruire il lavoro fatto, è importante definire con precisione il periodo di ricerca e
salvare tutto su un <strong>software di gestione bibliografica</strong> (per esempio Citavi o EndNote), che permette anche di
gestire più facilmente le citazioni in una tesi o in un articolo scientifico, e di tenere insieme, per ogni studio ritenuto
adeguato, il riassunto, il PDF integrale e i propri commenti e categorizzazioni. In questo modo il lavoro resta sempre
ricostruibile, anche a distanza di anni.</p>



<h3>Chi svolge la ricerca e la selezione della letteratura?</h3>
<p>Idealmente il lavoro di selezione è svolto da almeno <strong>due persone</strong>, come <strong>giudici indipendenti</strong>,
con una terza persona come <strong>supervisore</strong>.</p> 

<p>Se il lavoro viene fatto
indipendentemente da due persone, si può calcolare un <strong>indice di coerenza</strong> tra le due valutazioni. In
alternativa, i giudici possono discutere insieme ogni riassunto e ogni articolo, svolgendo la classificazione <strong>passo
sempre insieme</strong>. Nei casi di dubbio, interviene il supervisore, in modo che il <strong>processo</strong> sia il più
<strong>oggettivo possibile</strong>.</p>



<h2>L'estrazione dei dati qualitativi dalla letteratura selezionata</h2>
<p>Il primo obiettivo di una rassegna sistematica è riassumere la letteratura analizzata: caratteristiche dei campioni
(genere, età), dei metodi usati e così via, fino ad arrivare a una <strong>tabella descrittiva</strong> con le informazioni più
importanti.</p> 

<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 115800.webp" />

<p>Una buona procedura prevede una tabella più sintetica nel corpo dell'articolo e una tabella più ampia, 
come allegato supplementare, con tutti i dettagli.</p>

<p>Bisogna essere sistematici: per tutti gli studi vanno estratte le stesse informazioni. Quando alcune informazioni mancano o non sono chiare,
si può provare a contattare gli autori. Se anche così non si recuperano, si scrive "non chiaro" o "non recuperabile", ma è
importante non perdere mai i dati raccolti.</p>



<h2>La valutazione del rischio di bias</h2>

<p>La letteratura inclusa deve essere valutata criticamente per verificare 
    il <strong>rischio di bias</strong>, cioè errori sistematici che possono portare a una sovrastima o sottostima dei risultati.</p>
<img XXclass="zoomable" src="/assets/images/29/Screenshot 2026-09-03 120157.webp" />
<p>Secondo lo strumento Cochrane, i principali tipi di bias sono:</p>

<ul>
<li><strong>Selection bias</strong>: differenze sistematiche nelle caratteristiche di base dei gruppi confrontati, 
ad esempio quando la randomizzazione non è descritta adeguatamente.</li>
<li><strong>Performance bias</strong>: differenze nel trattamento o nell'esposizione a fattori diversi dall'intervento studiato.</li>
<li><strong>Detection bias</strong>: differenze nel modo in cui vengono rilevati o valutati i risultati.</li>
<li><strong>Attrition bias</strong>: differenze nella proporzione di partecipanti che abbandonano o vengono esclusi dallo studio.</li>
<li><strong>Reporting bias</strong>: differenze tra i risultati effettivamente ottenuti e quelli riportati.</li>
</ul>

<p>Il rischio di bias viene valutato da <strong>due giudici indipendenti</strong> o tramite consenso e 
riassunto in una tabella. 
Il rischio può essere <strong>grave, lieve, incerto o non valutabile</strong>, a seconda del tipo di studio.</p>




