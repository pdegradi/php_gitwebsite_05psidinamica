<h2>La ricerca in psicoterapia</h2>
<p>Il primo obiettivo della ricerca in psicoterapia è valutare se la psicoterapia, considerata nel suo insieme, funziona. Permette
di ottenere cambiamenti? Quali? Esistono dati in grado di dimostrarlo? La sua efficacia è maggiore rispetto ad altri metodi
concorrenti, per esempio gli psicofarmaci tipici della terapia psichiatrica? Quale approccio psicoterapeutico funziona meglio,
quello comportamentale, quello psicodinamico o quello cognitivo? Vi sono terapie migliori di altre, e quali raggiungono i
risultati migliori? Che cosa succede in una psicoterapia che determina un effetto, un cambiamento? Se avvengono dei
cambiamenti, che cosa si modifica nel paziente, e che cosa fanno paziente e terapeuta per raggiungerlo? Quest'ultima domanda
non riguarda solo quali elementi della psicoterapia spiegano il cambiamento, ma anche dove va cercato questo cambiamento, cioè
quali risultati ci si aspetta di trovare nel paziente dopo un determinato trattamento.</p>



<h3>I tipi di ricerche</h3>
<p>Le ricerche in psicoterapia si concentrano principalmente su due aspetti:</p>
<ul>
<li>la <strong>ricerca sull'esito</strong>: la psicoterapia è efficace? C'è un cambiamento? Se sì, in che cosa cambia il paziente?</li>
<li>la <strong>ricerca sul processo</strong>: che cosa succede in una psicoterapia che determina un certo tipo di esito? Quando si
studia quali elementi della psicoterapia spiegano un certo esito, si parla anche di ricerche sulla relazione tra processo ed
esito: cosa, di quello che accade durante la terapia, spiega l'esito?</li>
</ul>



<h3>I fattori specifici e quelli in comune delle diverse psicoterapie</h3>
<p>Una ricerca in psicoterapia può valutare i <strong>fattori specifici</strong>, cioè l'importanza per l'esito della terapia di
alcuni fattori propri di un determinato orientamento (per esempio le strategie usate solo nell'approccio psicodinamico, e non
in quello comportamentale o cognitivo), oppure i <strong>fattori aspecifici</strong>, cioè quei fattori trasversali, presenti
in tutte le terapie al di là dell'orientamento scelto dal terapeuta (per esempio l'alleanza terapeutica). È inoltre
fondamentale definire con precisione cosa si intende per "esito": due studi che valutano l'efficacia dello stesso trattamento
per una stessa patologia, per esempio un trattamento psicodinamico individuale per gli attacchi di panico, possono arrivare a
risultati completamente diversi perché l'esito è stato definito in modo diverso. Per esempio:</p>
<ul>
<li>uno studio che misura quanti attacchi di panico ha il paziente prima e dopo il trattamento potrebbe concludere che il
trattamento è molto efficace, perché ne riduce la frequenza.</li>
<li>ma il trattamento potrebbe non migliorare la qualità della vita del paziente, che pur avendo meno attacchi di panico sviluppa
altri sintomi che ritiene comunque invalidanti. Ridurre gli attacchi di panico non garantisce quindi di migliorare la qualità
di vita, e viceversa: dipende da quale esito si ricerca.</li>
</ul>
<p>È pertanto importante prestare attenzione a più ricerche, più metodi e più risultati validati, per avere un quadro dettagliato
con cui prendere decisioni nella pratica clinica.</p>



<h3>La significatività statistica e la rilevanza clinica</h3>
<p>È inoltre importante considerare, senza confonderli, due concetti fondamentali: la <strong>significatività statistica</strong>
e la <strong>rilevanza clinica</strong>. Un trattamento efficace per la depressione, per esempio, potrebbe essere associato a
una riduzione statisticamente significativa dei punteggi a un questionario auto-valutativo sui sintomi depressivi. Ma è
importante che il clinico combini questo risultato con altre valutazioni, come la rilevanza clinica del cambiamento: riuscire a
mangiare in modo più adeguato potrebbe essere un grande successo per un paziente, e avere poco valore per un altro, che
resterebbe quindi più soggetto a ricadute o a nuovi sintomi, anche a fronte di una riduzione della sintomatologia depressiva
misurata. C'è stato spesso un conflitto tra clinica e ricerca proprio per questo: un clinico può dire "la ricerca mi dice che
il punteggio sul Beck Depression Inventory è calato di 2-3 punti, ma al mio paziente non interessa, perché si sente comunque
male". Non basta quindi un solo studio, un solo risultato, ma è comunque importante poter validare con dati empirici un
determinato trattamento, per poter decidere quale tipo di trattamento sostenere e quale no: entrambe le informazioni,
statistiche e cliniche, sono importanti, e va incoraggiata una collaborazione sempre più stretta tra ricerca e clinica.</p>



<h3>La classificazione degli strumenti per la valutazione dell'esito (Lambert, 2004)</h3>
<p>Un certo esito può risultare di un certo tipo proprio perché lo si misura in un certo modo: misurandolo diversamente si
troverebbero altri risultati. Per questo un solo studio, con un solo metodo, non è mai sufficiente: un argomento è ben
approfondito solo se sono stati usati disegni di ricerca, metodologie, procedure e strumenti diversi, così da arrivare a
risultati combinati, più complessi ma anche più precisi. Gli strumenti di valutazione si distinguono per quattro aspetti:</p>
<ul>
<li>il <strong>contenuto</strong>: la sintomatologia, il funzionamento sociale e interpersonale, il funzionamento lavorativo, il
grado di soddisfazione del paziente, il ricorso a trattamenti successivi, la qualità della vita, i costi della cura, il
cambiamento globale.</li>
<li>la <strong>dimensione temporale</strong>: alla fine della terapia, oppure a distanza di mesi (valutazione di follow-up), per
valutare se un'efficacia a breve termine si mantiene anche a lungo termine.</li>
<li>la <strong>fonte</strong>: il paziente, il terapeuta, un osservatore esterno, che possono portare a giudizi differenti e vanno
quindi presi tutti in considerazione.</li>
<li>il <strong>metodo di misurazione</strong>: interviste, questionari auto-riferiti, indici globali o sintomatologici, indici
fisiologici.</li>
</ul>
<p>Più varietà di metodi e più numerosità di studi ci sono su un argomento, più la conoscenza sarà adeguata, approfondita e
precisa, e più sarà possibile orientare la pratica clinica sulla base della ricerca empirica. È tuttavia raro che un argomento
sia stato studiato in tutti i modi possibili: a volte si prendono decisioni cliniche con molti meno dati, in situazioni meno
ideali. La ricerca resta comunque in continuo sviluppo, e ogni argomento deve tendere a un approfondimento sempre più globale.</p>






<h2>La ricerca clinica: validità</h2>
<p>Lo scopo della ricerca è raggiungere conclusioni ben fondate, cioè valide, sugli effetti di un determinato intervento e sulle
condizioni in cui viene somministrato: la ricerca cerca di essere il più possibile valida, per ottenere risultati
condivisibili, su cui prendere decisioni comuni tra professionisti e orientamenti teorici diversi. Ci sono quattro tipi di
validità che permettono di condividere i dati tra clinici di diversa estrazione:</p>
<ol>
<li>la <strong>validità interna</strong>: valuta in che modo quel tipo di intervento, piuttosto che altre cause, sia responsabile
dei risultati e delle differenze tra i gruppi. Per esempio, confrontando un gruppo trattato con un gruppo in lista d'attesa,
come si può essere sicuri che il risultato dipenda proprio dall'intervento, e non da altre ragioni? Differenze di età, di
livello di educazione o di sesso tra i gruppi sono esempi di minacce alla validità interna. Più uno studio tiene conto delle
variabili intervenienti e confondenti (variabili che possono spiegare il risultato quanto l'intervento stesso), più è preciso
e credibile, anche se uno studio da solo non basta mai.</li>
<li>la <strong>validità esterna</strong>: valuta in che modo sia possibile estendere i risultati ottenuti in una particolare
situazione di ricerca a tutte le persone, gli ambienti, i tempi e le misurazioni. Molti studi psicologici, per esempio,
vengono condotti su studenti universitari, perché sono un campione facile da reclutare. Ma risultati ottenuti su un campione
non clinico di studenti non sono detto siano replicabili su un campione clinico di persone più adulte, che non partecipano per
ottenere crediti ma perché soffrono davvero di un disturbo e vogliono guarire.</li>
<li>la <strong>validità di costrutto</strong>: una volta stabilito che l'intervento è il principale responsabile della variazione
osservata, riguarda quali aspetti specifici dell'intervento possano essere considerati l'agente causale, cioè quale sia la
base concettuale (il costrutto) che sta sotto l'effetto trovato. Una tipica minaccia alla validità di costrutto è
l'<strong>effetto placebo</strong>: le aspettative del paziente e di chi somministra l'intervento possono da sole determinare
un miglioramento, per esempio il solo fatto di ricevere qualcosa, di sentirsi presi in carico, o di credere nell'efficacia di
un trattamento.</li>
<li>la <strong>validità statistica</strong>: valuta in che modo sia possibile dimostrare ed evidenziare una relazione tra
variabili, e come sia possibile rilevare se esistono effetti reali, per esempio confrontando le medie di un gruppo
sperimentale e di un gruppo di controllo prima e dopo un trattamento.</li>
</ol>
<p>Questi effetti potrebbero essere minacciati, per esempio, da una bassa <strong>potenza statistica</strong> (la capacità di un
test di cogliere delle differenze quando queste esistono davvero, che dipende in gran parte dalla numerosità del campione e
dalla variabilità delle procedure). In genere si parte da un'<strong>ipotesi nulla</strong> (H0, principio di falsificabilità),
secondo cui non ci sono differenze tra i gruppi, e si stabilisce un livello di probabilità (definito alfa) che specifica il
rischio di arrivare a una conclusione falsa. I casi possibili sono quattro: rifiutare correttamente l'ipotesi nulla quando è
falsa (decisione corretta). Accettarla per errore quando è falsa, per esempio per un campione troppo piccolo e quindi una bassa
potenza statistica (decisione errata). Rifiutarla per errore quando è vera (decisione errata). Accettarla correttamente quando
è vera (decisione corretta). Uno studio condotto su pochissimi pazienti può dare alcune indicazioni utili a sviluppare ipotesi,
ma resta poco indicativo e poco credibile: non è sufficiente per garantire l'efficacia di un trattamento.</p>






<h2>La ricerca clinica</h2>
<p>La ricerca clinica viene in genere divisa in due grandi blocchi:</p>
<ul>
<li>la <strong>ricerca sperimentale</strong>, nella quale i ricercatori assegnano i pazienti ai diversi tipi di trattamento.</li>
<li>la <strong>ricerca osservazionale</strong>, nella quale i ricercatori osservano gli abituali interventi nella pratica clinica.</li>
</ul>



<h3>La classificazione della ricerca clinica</h3>
<p>Per capire che tipo di disegno di studio è stato scelto in un articolo scientifico, e quindi saperlo leggere, commentare e
interpretare (una capacità importante non solo per chi fa ricerca, ma anche per chi fa pratica clinica e vuole restare
aggiornato su quali trattamenti hanno supporto empirico), bisogna porsi alcune domande in sequenza. La prima domanda è se i
ricercatori hanno assegnato i pazienti a diverse terapie: se sì, si parla di ricerca sperimentale. Se no, di ricerca
osservazionale.</p>
<p>Nella ricerca osservazionale, la seconda domanda è se esiste un gruppo di controllo: se sì, si parla di <strong>studio
analitico</strong>. Se no, di <strong>studio descrittivo</strong>. Nello studio analitico, ci si può chiedere ulteriormente
qual è la direzione della relazione tra esposizione (il processo, o la terapia) ed esito: a seconda della risposta si
distinguono gli <strong>studi di coorte</strong>, gli <strong>studi caso-controllo</strong> e gli <strong>studi
trasversali</strong>.</p>
<p>Nella ricerca sperimentale, invece, ci si può chiedere se i pazienti sono stati assegnati ai diversi trattamenti in modo
casuale: se sì, si parla di <strong>studio randomizzato controllato</strong>, ritenuto il migliore nella ricerca clinica per
valutare l'efficacia di un trattamento, perché tiene sotto controllo più fattori che possono minacciare la validità della
ricerca. Se no, di <strong>studio controllato ma non randomizzato</strong>.</p>



<h3>La ricerca osservazionale descrittiva</h3>
<p>Rientrano nella ricerca osservazionale descrittiva:</p>
<ul>
<li>il <strong>resoconto di un caso singolo</strong>: la descrizione dettagliata delle caratteristiche socio-demografiche, dei
sintomi, dei segni, del trattamento e degli esiti di un singolo paziente con uno specifico disturbo. Dal punto di vista
empirico e statistico dice poco, ma può essere un punto di partenza importante per aprire una nuova area di ricerca su un
certo tema.</li>
<li>il <strong>resoconto di diversi casi</strong>: la stessa descrizione dettagliata, riferita a una serie di pazienti con uno
specifico disturbo.</li>
<li>lo <strong>studio di prevalenza</strong>: la descrizione della presenza di certi sintomi in una popolazione definita, per
esempio attraverso questionari.</li>
<li>lo <strong>studio di sorveglianza</strong>: la descrizione dell'andamento nel tempo di certi sintomi in una popolazione definita.</li>
<li>gli <strong>studi correlazionali ecologici</strong>: la descrizione dell'associazione tra una determinata esposizione e uno
specifico esito in una popolazione definita (per esempio, l'aborto condotto secondo pratiche sicure e legali è associato a
bassa mortalità materna).</li>
</ul>



<h3>La ricerca osservazionale analitica</h3>
<p>La ricerca osservazionale analitica si distingue in base alla relazione temporale tra l'esposizione (il processo o il
trattamento) e l'esito: quando si valutano gli effetti di un'esposizione su un esito si parla di studio di coorte. Quando si
valuta un esito e si va a vedere quale esposizione hanno avuto in passato le persone con quell'esito, rispetto a chi non lo
presenta, si parla di studi caso-controllo. Quando si valutano esposizione ed esito nello stesso momento, si parla di studi
trasversali.</p>



<h3>Gli studi di coorte</h3>
<p>Uno <strong>studio di coorte</strong> segue nel tempo l'esperienza di un gruppo esposto a un determinato fattore, per esempio
un trattamento, confrontandolo con un gruppo non esposto a tale fattore: sono i cosiddetti <strong>studi
longitudinali</strong>. Per esempio, si può esporre oggi un gruppo a un trattamento e un altro no, seguirli per anni, e
osservare se il trattamento riduce il rischio di sviluppare depressione rispetto al gruppo non trattato, tenendo i due gruppi
simili per età, genere e livello di educazione, in modo da poter attribuire l'effetto trovato proprio all'esposizione.
Un'alternativa è guardare retrospettivamente le persone che tempo fa hanno ricevuto un certo intervento, e confrontarne l'esito
attuale con quello di persone simili che non lo hanno ricevuto, oppure combinare i due approcci.</p>



<h3>Gli studi caso-controllo</h3>
<p>Gli <strong>studi caso-controllo</strong> definiscono invece i gruppi in base all'esito, e ricostruiscono retrospettivamente
l'esposizione. Per esempio, i ricercatori reclutano un gruppo di soggetti malati di cancro ai polmoni e un gruppo di soggetti
sani, simili per genere, età e livello di educazione, e guardano indietro nel tempo per valutare se il gruppo malato riporta
più frequentemente, rispetto al gruppo sano, una storia di fumo: si va cioè a vedere se quell'esito corrisponde con maggiore
frequenza a una certa esposizione che potrebbe averlo causato.</p>



<h3>Gli studi trasversali</h3>
<p>Gli <strong>studi trasversali</strong>, infine, misurano nello stesso momento la presenza o l'assenza di un disturbo e la
presenza o l'assenza di un'esposizione. Per esempio, uno studio trasversale può mostrare che le persone sovrappeso riportano
più frequentemente un disturbo d'insonnia rispetto a un gruppo di controllo: si valutano cioè esposizione (l'insonnia) ed esito
(l'obesità) nello stesso momento. In questo tipo di studi la relazione temporale tra esposizione ed esito non può essere
valutata: non si può sapere se è l'obesità a causare l'insonnia, o l'insonnia a causare l'obesità.</p>






<h2>Gli studi sperimentali: il campionamento</h2>
<p>Negli studi sperimentali, la domanda fondamentale è se il campionamento è stato condotto con un metodo casuale o no. Il
campionamento casuale, o <strong>randomizzazione</strong>, comprende due processi: la generazione di una sequenza di
allocazione casuale, e l'occultamento di questa sequenza ai ricercatori che arruolano i partecipanti. Spesso, in letteratura, i
partecipanti vengono assegnati agli interventi sulla base di un criterio sistematico, per esempio la data di nascita o il
numero di partecipazione: questo tipo di assegnazione sistematica non è un vero metodo di campionamento casuale. Esistono vari
metodi di campionamento per minimizzare le minacce alla validità interna, e assegnare i soggetti ai vari gruppi con la stessa
possibilità di essere assegnati a un intervento o a un altro:</p>
<ul>
<li>il <strong>campionamento casuale semplice</strong>: si estrae una quota di unità dalla popolazione con un metodo che
garantisce la casualità dell'estrazione, di solito un generatore di numeri casuali. Se il campione è troppo piccolo, questo
metodo rischia di creare gruppi troppo eterogenei. Se è grande, invece, le differenze individuali si distribuiscono bene tra i
due gruppi.</li>
<li>il <strong>campionamento per randomizzazione a blocchi</strong>: le unità che costituiranno il campione vengono scelte dalla
popolazione secondo un rapporto predefinito, in genere 1:1, non sull'intera popolazione ma su gruppi definiti di una certa
numerosità (per esempio, ogni otto pazienti, quattro vengono assegnati a un intervento e quattro a un altro).</li>
<li>il <strong>campionamento per randomizzazione stratificata</strong>: prima dell'estrazione del campione, la popolazione viene
suddivisa in strati basati su un fattore che influenza la variabile studiata, e all'interno di ciascuno strato si sceglie un
campione con randomizzazione semplice o sistematica. In questo modo si tengono sotto controllo le variabili intervenienti: è
utile soprattutto quando il campione è piccolo, e la randomizzazione semplice rischierebbe di creare alterazioni importanti.</li>
</ul>



<h3>Uno studio "in cieco"</h3>
<p>Per ridurre le minacce alla validità della ricerca, uno studio randomizzato controllato deve essere condotto <strong>"in
cieco"</strong>: partecipanti, ricercatori/clinici e chi raccoglie e analizza i dati non dovrebbero conoscere il gruppo di
appartenenza dei soggetti. Nella ricerca in psicoterapia, partecipanti e clinici non possono restare all'oscuro del gruppo di
intervento a cui appartengono, ma chi raccoglie e analizza i dati sì. Per esempio, se come esito si sceglie un questionario
auto-riferito, lo si può far somministrare, prima e dopo il trattamento, da persone che non sanno se quel paziente fa parte del
gruppo sperimentale o del gruppo di controllo.</p>



<h3>Gestire la perdita dei partecipanti dall'inizio alla fine dell'intervento (dropouts)</h3>
<p>Un altro problema importante della ricerca clinica sperimentale è che i metodi di campionamento casuale hanno poco senso se,
alla fine, non si possono analizzare tutti i soggetti assegnati ai vari interventi. È però molto probabile, ed è anche giusto
che sia così, che alcuni pazienti non completino l'intera procedura: un paziente può interrompere la partecipazione quando
vuole, senza doverne dare spiegazione al clinico, e questo è eticamente fondamentale. A livello statistico, per gestire questo
problema:</p>
<ul>
<li>è importante descrivere in modo dettagliato il flusso dei partecipanti, specificando con quanti si è partiti e quanti hanno
concluso il trattamento, sia nel gruppo di intervento sia in quello di controllo.</li>
<li>si includono nelle analisi statistiche tutti i partecipanti inizialmente assegnati in modo randomizzato (il cosiddetto metodo
<strong>intention-to-treat</strong>), stimando i dati mancanti in base a quelli conosciuti, per esempio inserendo la media o
la mediana dei partecipanti rimasti, o un valore predefinito.</li>
<li>bisogna comunque sempre specificare in modo preciso e dettagliato quali partecipanti sono stati inclusi nelle analisi.</li>
</ul>






<h2>Le rassegne sistematiche e le metanalisi</h2>
<p>L'obiettivo della ricerca in psicoterapia è guidare le decisioni nella pratica clinica: uno studio solo non basta a orientare
le scelte cliniche, ne servono molti, ed è importante poter riassumere i risultati in maniera sistematica e, ancora meglio,
statistica, per valutare con più precisione lo stato dell'arte della ricerca su un determinato argomento. Per questo, i
ricercatori usano la <strong>rassegna sistematica</strong> o la <strong>metanalisi</strong>. Entrambe prevedono una ricerca
sistematica della letteratura su uno specifico argomento e la sua valutazione critica, ma la metanalisi aggiunge, rispetto alla
rassegna sistematica, il riassunto statistico dei risultati numerici degli studi disponibili.</p>



<h3>La ricerca della letteratura</h3>
<p>Sia la rassegna sistematica sia la metanalisi partono da una ricerca sistematica della letteratura. Le linee guida
<strong>PRISMA</strong> (elementi preferenziali per presentare rassegne sistematiche e meta-analisi) specificano come riportare
e documentare questa ricerca. Vanno identificati tutti i risultati e i riassunti reperibili nelle banche dati usando parole
chiave. Dalla valutazione dei riassunti si eliminano i duplicati. Si leggono poi per
intero solo gli articoli che, seguendo criteri sistematici, soddisfano gli obiettivi della ricerca. Un metodo utile per
reperire altri articoli è controllare anche i riferimenti bibliografici, contattare esperti del settore per sapere se conoscono
studi rilevanti, e cercare anche studi non ancora pubblicati (per esempio negli atti dei convegni), perché gli studi con
campioni piccoli vengono pubblicati più spesso solo se riportano grandi risultati: la letteratura pubblicata rischia quindi di
mancare proprio degli studi piccoli con risultati negativi, che non trovano differenze tra i gruppi. Si deve riportare nel
dettaglio il numero e la ragione dei risultati esclusi, quanti studi sono stati letti per intero, quanti di questi sono stati
esclusi, quanti sono stati utilizzati nella sintesi qualitativa della rassegna sistematica e, per una metanalisi, quanti
avevano dati riportati in modo corretto e sufficiente, anche dopo aver eventualmente contattato gli autori.</p>



<h3>La metanalisi: sintesi quantitativa</h3>
<p>La <strong>metanalisi</strong> è un metodo che permette di riassumere la letteratura attraverso il calcolo di una misura di
effetto. I risultati dei singoli studi vengono combinati in una stima unica dell'effetto totale, una media ponderata anche in
base alla numerosità campionaria di ciascuno studio (gli studi con campioni più grandi ricevono un peso maggiore), insieme agli
intervalli di confidenza, cioè una stima dei valori plausibili per quella misura. I risultati della metanalisi si riassumono in
un <strong>diagramma a foresta</strong>, dove ogni studio compare con la propria stima e il proprio intervallo di
confidenza, insieme a una media totale ponderata che rappresenta la stima riassuntiva quantitativa del risultato, derivata da
molti studi e quindi più credibile e più stabile di quella di un singolo studio.</p>



<h3>La metanalisi: vantaggi e limiti</h3>
<p>I <strong>vantaggi</strong> della metanalisi sono il riassunto sistematico della letteratura, l'aumento della potenza
statistica e una maggiore validità esterna. Bisogna però stare attenti,
perché ogni studio è stato condotto in un contesto e con una procedura diversa, con il rischio di "mettere insieme le mele con
le arance". I <strong>limiti</strong> comprendono l'eterogeneità degli studi inclusi e la <strong>distorsione di
pubblicazione</strong>, per cui gli studi con
campioni piccoli si pubblicano più facilmente se riportano effetti grandi (per questo è consigliato includere anche la
