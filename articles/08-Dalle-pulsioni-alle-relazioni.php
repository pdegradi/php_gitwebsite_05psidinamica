<h2>La teoria freudiana delle pulsioni</h2>
<p>Prima di parlare delle teorie di Sullivan (psicoanalisi interpersonale) e di Mitchell (modello relazionale), è utile
ripassare la teoria delle pulsioni di Freud.</p>

<p>Per Freud, ogni essere umano nasce con tensioni fisiche innate — le <strong>pulsioni sessuali e aggressive</strong> — che
spingono per essere soddisfatte. Ma la società limita questa soddisfazione, ponendo delle esigenze proprie. Nasce così un
conflitto tra la natura (le pulsioni) e la società (le sue regole). Da questo conflitto nasce il nostro modo di pensare
razionale, il <strong>pensiero secondario</strong>, guidato dal principio di realtà.</p>

<p>Le nostre capacità cognitive, in altre parole, si sviluppano proprio per gestire questo conflitto: servono a conciliare una
natura umana non fatta per la società con un ambiente che ci chiede di adattarci.</p>

<p>Il pensiero secondario nasce quindi dalle prime frustrazioni: il bambino scopre di non poter soddisfare da solo i propri
bisogni pulsionali. Per gestire questo conflitto, la mente costruisce due strutture che controllano gli impulsi istintivi:
l'<strong>Io</strong> e il <strong>Super-io</strong>. Individuo e società restano quindi sempre un po' in contrasto tra loro, e
il compito dello sviluppo diventa la <strong>socializzazione</strong>, cioè imparare ad adattarsi al mondo in cui viviamo.</p>



<h3>La svolta relazionale</h3>
<p>Gli orientamenti psicoanalitici contemporanei "relazionali" (la teoria interpersonale di Sullivan, il modello relazionale di
Mitchell, la teoria intersoggettiva) prendono le distanze dal modello pulsionale della psicoanalisi classica. Per queste teorie
la funzione principale della mente non è scaricare le pulsioni, ma <strong>formare e preservare i legami con gli altri</strong>: 
il legame con gli altri non è un modo secondario per risolvere le pulsioni, ma l'essenza stessa della vita psichica.</p>

<p>Nel modello di Freud, anche se soddisfare le pulsioni richiede comunque l'ambiente (pensiamo al Super-io, che nasce
interiorizzando persone significative), la personalità resta definita soprattutto dalle pulsioni stesse, innate e biologiche.
È il senso della celebre frase di Freud: "l'anatomia è il nostro destino".</p>

<p>Le teorie relazionali ribaltano questa idea. Possono esistere differenze biologiche tra le persone, ma il loro significato
dipende da come reagiscono le persone intorno a noi: biologia e relazioni si influenzano a vicenda in un ciclo continuo, e non
si possono più separare.</p> 

<p>Pensiamo a un modo di dire comune: quando una persona arrabbiata "finalmente mostra quello che pensava
davvero", stiamo usando un'idea di origine freudiana — che esistano emozioni più "vere" e primitive, nascoste sotto una
maschera razionale imposta dalla società. Per le teorie relazionali questa distinzione non ha senso: la personalità è sempre un
insieme inseparabile di biologia e ambiente, non esiste una parte "vera" e una "finta".</p>






<h2>La psicoanalisi interpersonale Harry Stack Sullivan</h2>
<img XXclass="zoomable" src="/assets/images/Harry-Stack-Sullivan.webp" />
<p>L'autore che ha influenzato di più i modelli relazionali è Sullivan (1892-1949), che ha proposto la <strong>psicoanalisi
interpersonale</strong>.</p> 

<p>Per Sullivan l'essere umano si è evoluto come creatura sociale, orientata all'interazione con gli
altri: già in questa definizione l'autore si contrappone all'idea freudiana secondo cui l'essere umano nascerebbe in
opposizione con la società.</p> 

<p>La personalità prende forma in un ambiente fatto di altre persone: il Sé è qualcosa che compare
nell'interazione con gli altri, ed è definito come lo schema relativamente permanente delle situazioni interpersonali
ricorrenti che caratterizzano la vita umana.</p> 

<p>Le modalità di interazione, specialmente quelle più precoci, vengono quindi
interiorizzate e si ripetono anche in età adulta, in altre relazioni, diventando parte della nostra personalità.</p>




<h3>Il campo interpersonale e la teoria del campo di Kurt Lewin</h3>
<img XXclass="zoomable" src="/assets/images/Kurt-Lewin.webp" />
<p>Per Sullivan non ha senso parlare separatamente di individuo e di realtà sociale: esiste solo il <strong>campo delle relazioni
interpersonali</strong>, che include entrambi gli elementi e definisce la personalità. La personalità può essere compresa solo
all'interno di questo campo interpersonale, che comprende l'individuo, la realtà sociale e la relazione tra i due.</p> 

<p>Sullivan fu
influenzato soprattutto dalla <strong>teoria del campo</strong> di Kurt Lewin (1890-1947), secondo cui il comportamento umano può essere
compreso solo considerando la totalità dei fatti coesistenti in un dato momento, nella loro interdipendenza: questa totalità
comprende lo spazio fisico e reale (la realtà esterna), lo spazio di vita (l'individuo e la sua rappresentazione psicologica
dell'ambiente) e lo spazio di confine (la relazione tra individuo e realtà esterna).</p>

<p>La relazione tra individuo e realtà esterna non è quindi la semplice somma delle parti: la relazione stessa ha un proprio
ruolo, che aggiunge qualcosa in più.</p>




<h3>La teoria evolutiva di H.S. Sullivan</h3>
<p>Il neonato oscilla tra uno stato di benessere quasi assoluto e uno stato di tensione legato a un qualche tipo di bisogno
(bisogno di soddisfacimento). L'espressione dei bisogni, per esempio attraverso il pianto, tende a provocare una risposta
soddisfacente da parte dell'adulto: il bambino ha fame, piange, la madre se ne accorge e lo allatta.</p>

<p>La relazione tra bisogni e risposte tende inoltre a essere integrativa, cioè gratificante anche per l'adulto:
nell'allattamento, per esempio, il bambino vuole essere allattato e la madre vuole allattare per svuotare il seno.</p> 

<p>A questi
processi Sullivan ha dato il nome di <strong>tendenze integrative</strong>. Queste tendenze non sono fondamentali solo alla
nascita, ma per tutto l'arco della vita: anche nell'adulto, i bisogni di soddisfacimento tendono a produrre reciprocità, cioè
bisogni diversi negli adulti tendono a suscitare bisogni complementari in altri adulti.</p>



<h3>Il legame empatico</h3>
<p>Se i bisogni di soddisfacimento tendono a essere integrativi, come mai allora i rapporti umani sono spesso così complessi e
conflittuali? Per Sullivan la chiave sta nella natura "contagiosa" delle emozioni umane: una persona allegra tende a rendere
allegri anche gli altri, così come stare con una persona molto annoiata tende a trasmettere noia. Questa diffusione degli stati
d'animo nelle relazioni interpersonali prende il nome di <strong>legame empatico</strong>.</p>
<p>Il legame empatico può però funzionare anche in negativo - per le emozioni negative (si pensi ad esempio allo stato di 
ansia e frustazione che prova la madre e che può trasmettere anche al bambino).</p>



<h3>L'ansia come tendenza disintegratrice</h3>
<p>A differenza della tensione legata ai bisogni di soddisfacimento, la tensione legata all'ansia non può essere ridotta dalla
madre o da chi si prende cura del bambino. Per questo l'ansia agisce come <strong>tendenza disintegratrice</strong>, cioè
funziona in modo opposto rispetto agli altri stati affettivi.</p> 

<p>Sullivan distingue l'ansia dalla paura: la paura è adattiva, si
esprime con il pianto e l'agitazione e provoca una reazione risolutiva dell'adulto. 
L'ansia, invece, è problematica perché non ha un oggetto definito: il bambino
non riesce a spiegarsi perché prova quel disagio, e la madre non sa come risolverlo.</p>

<p>Fin dall'inizio il bambino organizza l'esperienza in stati ansiosi e stati non ansiosi. Dato che l'ansia si trasmette
dall'adulto attraverso il legame empatico, il bambino raggruppa tutte le esperienze specifiche di ansia vissute non solo con la
madre, ma in generale con gli adulti che si prendono cura di lui, in un'unica esperienza generale di "<strong>madre cattiva o
ansiosa</strong>". Al contrario, raggruppa tutte le esperienze non ansiose vissute nell'esperienza generale di "<strong>madre
buona o non ansiosa</strong>".</p>




<h3>La prospettiva evolutiva</h3>
<p>Con lo sviluppo, il bambino partecipa in modo sempre più attivo a queste esperienze. All'inizio, le esperienze di "madre
buona" e "madre cattiva" sono vissute passivamente: il bambino le subisce senza capirle. Poi impara a prevederle: comincia a
capire quando starà per arrivare la "madre buona" e quando la "madre cattiva".</p>

<p>In un passaggio successivo, il bambino scopre qualcosa di più importante: che la comparsa della "madre buona" o della "madre
cattiva" dipende da quello che fa lui stesso. I suoi comportamenti che portano alla "madre buona" diventano positivi ai suoi
occhi, e formano il cosiddetto "<strong>buon me</strong>". Quelli che portano alla "madre cattiva" diventano negativi, e
formano il "<strong>cattivo me</strong>".</p>

<p>Non tutte le esperienze ansiose hanno però la stessa intensità. Quelle più forti possono essere così sconvolgenti da restare
fuori dalla coscienza del bambino: non riesce a organizzarle in un'immagine di sé che riconosce come propria. Restano quindi
come esperienze "estranee", che il bambino non sente sue: sono le cosiddette "<strong>esperienze non-me</strong>".</p>


<h3>Il sistema del Sé</h3>
<p>Il <strong>sistema del Sé</strong> è l'insieme dei processi con cui il bambino cerca di vivere il "buon me" ed evitare il
"non-me". Il "buon me" dipende dalle relazioni con le persone importanti nella sua vita. Per questo il Sé del bambino si forma
gradualmente dentro una rete di relazioni specifica, non in astratto.</p>

<p>Questo spiega perché l'ansia di una madre dipenda da come è fatta quella madre in particolare. Per esempio: se durante il
cambio il bambino inizia a giocare con i propri genitali, alcune madri non ci faranno caso, altre invece si preoccuperanno. Lo
stesso comportamento del bambino diventa quindi "ansioso" solo per alcuni bambini, cresciuti in certe famiglie, e non per
altri.</p>

<p>Crescendo, il bambino diventa sempre più simile a suo padre e sua madre, nello specifico: la gamma di esperienze possibili
si restringe. Il sistema del Sé tende a diventare stabile, ma non è del tutto rigido. Ci sono fasi dello sviluppo — come il
bisogno dell'amico del cuore in preadolescenza — in cui nascono nuovi bisogni relazionali, e che rallentano questa rigidità
permettendo una nuova integrazione.</p>




<h3>I bisogni e le operazioni di sicurezza</h3>
<p>Quando proviamo ansia, si attivano i <strong>bisogni di sicurezza</strong>. Per gestire la tensione che ne deriva, il sistema
del Sé mette in atto i comportamenti che in passato hanno funzionato per ridurre l'ansia. Questi comportamenti si chiamano
<strong>operazioni di sicurezza</strong>.</p>

<p>Per Sullivan, un'area della nostra esperienza diventa conflittuale nella prima infanzia solo se genera ansia negli adulti
che si prendono cura di noi — e ogni madre reagisce in modo diverso agli stessi comportamenti del bambino. Le difficoltà
psicologiche, compresa la psicopatologia, non dipendono quindi dalla natura delle pulsioni in sé, come diceva il modello
classico. Dipendono invece da come reagisce l'ambiente umano intorno a noi: soprattutto dalle prime relazioni, e in misura
minore da quelle vissute nel resto della vita.</p>





<h2>Il modello relazionale Stephen Mitchell</h2>
<img XXclass="zoomable" src="/assets/images/Stephen-Mitchell.webp" />
<p>Passiamo ora al modello relazionale proposto da Stephen Mitchell (1946-2000), il primo a proporre un modello che riassuma tutti
gli orientamenti psicoanalitici centrati sulle relazioni interpersonali.</p> 

<p>La scuola psicoanalitica viene spesso criticata perché
composta da tante linee di pensiero che, pur dicendo talvolta cose simili, entrano in contrapposizione tra loro, lasciando
aperto il dubbio su chi abbia ragione.</p> 

<p>Mitchell, insieme a J. Greenberg (1983), propone quindi un modello che raccolga i punti
in comune e le differenze tra le varie teorie: il <strong>modello relazionale</strong>, un tentativo di unificare le principali
teorie della psicoanalisi contemporanea, contrapposto al modello pulsionale classico di Freud.</p> 

<p>Le teorie di riferimento sono le:</p>
<ul>
    <li>teorie inglesi delle relazioni oggettuali</li>
    <li>la Psicologia del Sé di Kohut</li>
    <li>la psicoanalisi interpersonale di Sullivan</li>
    <li>più in generale tutte le ipotesi della psicoanalisi contemporanea che considerano le relazioni con gli altri, e non 
        le pulsioni, l'elemento fondamentale della vita mentale</li>
</ul>
 


<h3>La matrice relazionale</h3>
<p>Per Mitchell, la nostra personalità è fatta di due componenti inseparabili: i nostri fattori costituzionali, e l'ambiente —
cioè le relazioni importanti che viviamo, soprattutto nella prima infanzia ma anche per tutta la vita.</p>

<p>Mitchell riassume i modelli principali della psicoanalisi in tre categorie:</p>
<ul>
<li>la <strong>teoria pulsionale</strong> della psicoanalisi classica di Freud, detta anche teoria psicobiologica: per Freud la
mente è "monadica", cioè riguarda solo l'interno della persona. L'individuo è definito soprattutto dalle proprie pulsioni. Il
pensiero nasce dal bisogno di soddisfarle, e la mente funziona attraverso il conflitto tra pulsioni e difese;</li>
<li>il <strong>modello dell'arresto evolutivo</strong>, che comprende la Psicologia dell'Io e la Psicologia del Sé: anche qui la
mente resta "monadica", ma si ammette che nasce dall'interazione con i genitori nei primi anni. Una volta formato, però, il Sé
funziona in modo indipendente, e da adulti diventiamo meno reattivi alle relazioni. Per questo modello, un ambiente inadeguato
blocca lo sviluppo (da qui il nome "arresto evolutivo"), ed è proprio in questo blocco che va cercata la psicopatologia;</li>
<li>il <strong>modello relazionale</strong>, di Mitchell, Sullivan e delle teorie delle relazioni oggettuali (soprattutto quella
di Fairbairn): qui il rapporto con l'altro è centrale. La mente è "diadica", cioè sociale e interattiva fin dall'inizio.
L'ambiente non si limita a influenzare la mente: la determina. È una teoria psicosociale, non più biologica, in cui il
conflitto centrale nasce dalle relazioni — dai desideri e dalle paure che viviamo con le persone importanti per noi.</li>
</ul>



<h3>La matrice relazionale</h3>
<p>Per Mitchell, ci sono tre modi di pensare alla natura delle relazioni umane. Non sono in contrapposizione tra loro: insieme
formano la <strong>matrice relazionale</strong>, cioè i tre ingredienti che insieme costruiscono l'esperienza umana.</p>
<ul>
<li><strong>relazionale per destino</strong> (componente costituzionale, biologica): non nasciamo "tabula rasa" — qualcosa nella
nostra natura ci spinge verso gli altri fin dall'inizio. Per Sullivan, per esempio, gli esseri umani sono strutturati per
natura in termini relazionali;</li>
<li><strong>relazionale per proposito</strong> (componente intenzionale ed emotiva): cerchiamo attivamente legami forti perché
lo desideriamo. Per Fairbairn, per esempio, la motivazione centrale della vita è cercare e mantenere un legame emotivo intenso
con un'altra persona;</li>
<li><strong>relazionale per implicazione</strong> (processi interpersonali impliciti nella formazione del Sé): i legami con gli
altri sono la base su cui costruiamo la nostra identità. Per Kohut e Winnicott, per esempio, alcuni legami significativi sono
ciò che ci permette di formare un senso di sé solido e coeso.</li>
</ul>


<h3>Le configurazioni relazionali</h3>
<p>La mente è composta da <strong>configurazioni relazionali</strong>: schemi o rappresentazioni interne delle relazioni passate e
presenti dell'individuo. Le configurazioni relazionali proposte da Mitchell sono importanti perché ridefiniscono
l'interpretazione dell'inconscio nella psicoanalisi contemporanea: non più un contenitore di pulsioni aggressive e sessuali, ma
un insieme di schemi, di modalità di relazione apprese soprattutto nella prima infanzia, ma in generale in tutta la vita.</p>

<p>Queste configurazioni includono tre dimensioni: il Sé, l'altro, e lo spazio tra i due.</p> 
    
<p>Torna qui l'influenza della teoria del
campo di Kurt Lewin: non c'è oggetto senza Sé, e non c'è Sé senza oggetto. Sé e oggetto sono in relazione continua, e non
esistono né l'uno né l'altro senza uno spazio di interazione tra loro.</p>





<h3>Le configurazioni relazionali e la matrice relazionale</h3>
<p>Per il modello relazionale, i modelli ripetitivi della nostra esperienza non nascono, come nel modello pulsionale, dal
bisogno di soddisfare spinte e piaceri interni. Nascono invece da un bisogno diffuso: conservare continuità, legami e
familiarità con il proprio mondo di relazioni. Abbiamo un desiderio forte di avere un senso di sé stabile nel tempo, come
persona legata ad altre persone, con un posto preciso in una rete di relazioni — sia reali sia interiorizzate.</p>

<p>La nostra mente nasce da una specifica cultura e lingua, e continua a interagire con esse per tutta la vita. Per questo non è
qualcosa di fisso, ma è fluida e cambia continuamente: ogni relazione ridefinisce un po' la nostra rete interiore di relazioni.
I modelli relazionali importanti che interiorizziamo diventano vere e proprie mappe che guidano la nostra esperienza
soggettiva: sono le <strong>configurazioni relazionali</strong>. Quando queste configurazioni si attivano ripetutamente,
riproducendo schemi di interazione familiari, si forma la <strong>matrice relazionale</strong>.</p>



<h3>Il conflitto relazionale e la tela di Penelope</h3>
<p>Le diverse configurazioni relazionali entrano in conflitto tra loro. Per Mitchell, come già per Freud, il conflitto è
inevitabile — ma qui è un <strong>conflitto relazionale</strong>: nasce dal fatto che ogni relazione umana è complessa, e può
avere significati anche opposti, che riguardano chi siamo, i nostri legami con gli altri, e la distanza giusta da tenere con
loro.</p>

<p>Per gestire questo conflitto, secondo Mitchell, cerchiamo continuamente di ricostruire la nostra matrice relazionale, per
avere un senso di sé stabile e continuo nel tempo. Mitchell usa la metafora di Penelope: nell'Odissea, Penelope tesse la tela
di giorno e la disfa di notte. Questo lavoro infinito le serve per tenere lontani i pretendenti, restare fedele a Ulisse, e
mantenere unito il proprio mondo interiore. Allo stesso modo, tessiamo e disfiamo continuamente la nostra matrice relazionale,
per sentire che la nostra vita ha un senso continuo e una direzione.</p>



<h3>Sé unico e Sé multiplo</h3>
<p>Con un'altra metafora — quella della pellicola cinematografica — Mitchell unisce due idee: il <strong>Sé unico</strong> e il
<strong>Sé multiplo</strong>. Una pellicola è fatta di tanti fotogrammi diversi che, messi insieme, creano qualcosa di continuo.
Allo stesso modo, in ogni momento agiamo in base al contesto in cui ci troviamo: questo potrebbe far pensare che la nostra
personalità sia fatta di tanti Sé diversi (Sé multiplo). Ma queste esperienze fanno parte di una stessa sequenza continua, che
integriamo in un unico senso di Sé (Sé unico): lavoriamo sempre per dare continuità e stabilità alla nostra matrice
relazionale.</p>



<h3>Psicopatologia</h3>
<p>La psicopatologia nasce quando questa capacità di "tessere e disfare" la matrice relazionale smette di funzionare. Tessere e
disfare continuamente è sano: ci rende flessibili e capaci di adattarci a situazioni diverse. La psicopatologia, invece, è la
rigidità: quando una persona ripropone sempre gli stessi schemi relazionali, invece di rispondere in modo flessibile alle
situazioni nuove.</p>



