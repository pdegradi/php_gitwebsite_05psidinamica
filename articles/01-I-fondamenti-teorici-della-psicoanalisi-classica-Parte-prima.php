<p>La <strong>psicologia dinamica</strong> studia i modelli teorici sul funzionamento della mente e sui 
legami interpersonali che derivano dalla psicoanalisi: da quelli più fedeli alla teoria 
classica di <strong>Freud</strong> fino a quelli che se ne distaccano in modo radicale.</p>
<p>La materia comprende anche gli sviluppi della ricerca e le tecniche cliniche nate da questi modelli.</p>
<p><strong>Freud</strong> dà una triplice definizione di psicoanalisi:</p>

<ol>
    <li>Un procedimento per l’indagine di processi psichici altrimenti inaccessibili, ovvero un 
        metodo per portare alla coscienza il materiale inconscio</li>
    <li>Un metodo terapeutico per il trattamento dei disturbi nevrotici, in cui riportare i 
        contenuti inconsci alla coscienza</li>
    <li>Un insieme di conoscenze psicologiche ottenute con i metodi precedenti, che convergono in 
        una nuova disciplina scientifica. Freud parte dall’idea di sviluppare tecniche per curare i 
        disturbi nevrotici, per poi allargare le sue teorie a una visione più generale del 
        funzionamento della mente umana.</li>
</ol>


<h2>L’inconscio prima di Freud, la psichiatria dinamica francese</h2>

<p>Non tutto ciò che Freud afferma è originale: molti concetti sono rielaborazioni di idee già presenti nella 
    medicina psichiatrica della sua epoca.</p>
<p>Un movimento chiamato “psichiatria dinamica francese”, con esponenti come 
    <strong>Charcot</strong> e <strong>Janet</strong>, 
    aveva già iniziato a parlare di inconscio, sostenendo che i disturbi isterici e nevrotici fossero caratterizzati da 
    ricordi traumatici di cui il paziente non era consapevole.</p>
<p>L’obiettivo principale era individuare, nella storia di vita del paziente, un 
    <strong>trauma esterno</strong> — a cui veniva 
    attribuita un’importanza fondamentale — che portava all’isolamento di alcuni contenuti psichici: 
    il ricordo del trauma veniva mantenuto separato dalla coscienza, dando origine ai sintomi psicopatologici.</p>
<p>Già <strong>Charcot</strong> sosteneva che fossero le idee, e non danni neurologici, a essere responsabili dei 
    sintomi nevrotici — in netta contrapposizione con le teorie di <strong>Kraepelin</strong>, secondo cui ogni disturbo 
    mentale aveva una causa neurologica. Pierre <strong>Janet</strong> (1859-1947) condivideva 
    l’idea dell’isolamento delle idee dalla coscienza, ma ne attribuiva la causa a una 
    degenerazione ereditaria congenita del sistema nervoso.</p>

<img XXclass="zoomable" src="/assets/images/01/01.webp" />

<p><strong>Josef Breuer</strong>, amico e collega di Freud, nel testo Studi sull’isteria (1895) riportò i 
propri casi clinici e sviluppò una propria teoria dell’inconscio: le idee si dissociano dalla coscienza 
durante stati di coscienza alterati, ovvero momenti di assenza mentale.</p>

<img XXclass="zoomable" src="/assets/images/01/02.webp" />

<p>Il caso più noto è quello di Anna O. (Bertha Pappenheim), paziente di Breuer, che si trovava ad 
    assistere il padre gravemente malato in condizioni di forte stress. Secondo Breuer, nei momenti 
    di sovraccarico mentale, le informazioni registrate non vengono integrate nel resto dei contenuti 
    accessibili alla coscienza, rimanendo dissociate.</p>

<p>Su questo punto, Freud e Breuer si trovarono in disaccordo.</p>

<h2>Sigmund Freud e la nascita della psicoanalisi</h2>

<p>Nello studio della teoria freudiana è importante seguire la logica che ha guidato l’autore: molti 
    concetti iniziali verranno rivisti o approfonditi dallo stesso Freud, ma è utile partire 
    dalle sue prime riflessioni sull’isteria e sui disturbi nevrotici, per vedere come queste 
    si sviluppino in una teoria più ampia sul funzionamento della mente umana.</p>

<p>Freud condivise con i suoi precursori alcuni punti di partenza:</p>
<ul>
    <li>Esistono <strong>idee</strong> che rimangono <strong>estranee alla coscienza</strong> (l’<strong>inconscio</strong>)</li>
    <li>Questi contenuti psichici isolati e non integrati nella personalità rappresentano 
        <strong>elementi patogeni</strong>. L’idea dell’epoca era che l’inconscio esistesse solo nella psicopatologia: 
        la persona sana avrebbe accesso a tutti i propri contenuti psichici</li>
</ul>

<p>Freud si distacca però subito dai precursori, introducendo due concetti nuovi:</p>

<ul>
    <li>Ogni esperienza è accompagnata da un <strong>ammontare di affetto</strong> (ovvero una risposta emotiva 
        ed emozionale). Quando, in situazioni traumatiche, alcuni contenuti psichici vengono 
        isolati dalla coscienza, con essi viene isolato anche l’affetto ad essi associato, che 
        Freud chiama <strong>affetto incapsulato</strong></li>
    <li>Le idee inconsce <strong>sono state un tempo consce</strong>: questo è il contributo più originale di 
        Freud. Freud sostiene che i contenuti vengano esclusi dalla coscienza attraverso un 
        processo attivo e volontario, perché ritenuti troppo dolorosi o in contraddizione con 
        il resto della personalità. Questo processo Freud lo chiama <strong>rimozione</strong></li>
</ul>

<p>Tra i concetti che rimangono costanti in tutta la teoria freudiana vi è il <strong>principio di costanza</strong>: 
ogni esperienza produce un aumento di eccitamento, e la funzione principale della mente è riportare 
l’organismo ai livelli base necessari per un buon funzionamento. Poiché l’essere umano non può sostenere 
livelli eccessivi di eccitamento, ogni esperienza richiede una scarica. 
Questo, per Freud, è lo <strong>scopo principale della mente</strong>.</p>

<p>In sintesi, il meccanismo di base è:</p>

<ol>
    <li>Si fa un’esperienza;</li>
    <li>Essa si associa a un ammontare affettivo;</li>
    <li>Questo affetto deve essere scaricato per riportare l’organismo ai livelli base di eccitamento;</li>
    <li>Risoluzione</li>
</ol>

<img XXclass="zoomable" src="/assets/images/01/03.webp" />

<h2>Come viene scaricato l’ammontare affettivo</h2>
<p>La via principale con cui la mente scarica l’ammontare affettivo e riporta l’organismo ai 
    livelli base di eccitamento è, secondo Freud, l’<strong>associazione delle idee</strong> (o associazione ideativa): 
    collegare l’esperienza vissuta agli altri contenuti mentali già presenti nella coscienza.</p>

<img XXclass="zoomable" src="/assets/images/01/04.webp" />

<p>Ad esempio, se vivo un’esperienza che provoca un’emozione negativa, riuscire a valutarla in una 
    prospettiva più ampia mi permette di ridimensionarne la valenza negativa. 
    Questo processo ha due funzioni:</p>

<ul>
    <li><strong>Riduce la forza affettiva dell’idea</strong>, permettendo la scarica dell’ammontare di affetto;</li>
    <li>Ha una funzione di <strong>correzione cognitiva</strong>: il contenuto psichico viene messo a 
    confronto con gli altri contenuti mentali, consentendo di vedere l’esperienza in modo 
    più ampio e integrato.</li>
</ul>

<h2>L’affetto incapsulato</h2>

<p>Per Freud, il problema non è dimenticare il ricordo di un evento traumatico, bensì isolare 
    l’<strong>affetto ad esso associato</strong>. Il potenziale patogeno risiede nella scarica inadeguata dell’ammontare 
    affettivo legato all’esperienza originaria: non è il contenuto psichico in sé a essere dannoso, 
    ma il fatto che l’affetto connesso non venga scaricato.</p>

<p>Riportare il trauma inconscio alla coscienza può quindi avere benefici terapeutici, poiché permette 
    la scarica dell’ammontare affettivo attraverso la correzione associativa.</p>

<p>L’affetto incapsulato, non trovando sfogo, fa pressione e si trasforma in sintomi psicopatologici — 
    in particolare in sintomi psicosomatici tipici delle nevrosi. 
    Freud tuttavia non descrive nel dettaglio il processo attraverso cui l’affetto incapsulato si 
    converte in sintomi isterici.</p>

<h2>L’isolamento dei contenuti psichici</h2>

<p>L’isolamento dei contenuti psichici avviene attraverso un atto attivo, volontario e 
    conscio con cui l’individuo esclude dalla coscienza ricordi perturbanti, inaccettabili o 
    in conflitto con il resto della propria personalità. Questo processo 
    è chiamato <strong>rimozione</strong>.</p>

<p>Se da un lato la rimozione invia il contenuto psichico dal conscio all’inconscio, 
    dall’altro un secondo processo — la <strong>resistenza</strong> — impedisce a quel contenuto di tornare 
    alla coscienza. Attraverso la resistenza, l’individuo tiene sistematicamente sotto 
    controllo il materiale inconscio per evitare che riemerga.</p>

<img XXclass="zoomable" src="/assets/images/01/05.webp" />

<h2>La concezione della mente: il modello topico</h2>
<p>Con il modello topico, Freud riformula la sua prima concezione della mente, 
    riconoscendo che non tutto l’inconscio è patologico. La mente è come se fosse organizzata 
    in “<strong>luoghi</strong>” (da qui il termine topica).</p>

<ul>
    <li><strong>Conscio</strong>: contiene le rappresentazioni di cui abbiamo percezione nel momento presente;</li>
    <li><strong>Preconscio</strong>: contiene idee e sentimenti accettabili, 
    non attualmente attivi ma facilmente recuperabili quando necessario. 
    Ad esempio, potrei non ricordare spontaneamente cosa ho mangiato due giorni fa, ma se 
    consultassi un dietologo sarei in grado di ricostruire l’informazione con relativa facilità;</li>
    <li><strong>Inconscio</strong>: contiene idee e sentimenti inaccettabili, difficili da 
    recuperare e mantenuti fuori dalla coscienza.</li>
</ul>

<img XXclass="zoomable" src="/assets/images/01/06.webp" />

<p>Un altro principio fondamentale della teoria freudiana è il 
<strong>determinismo psichico</strong>: ogni azione mentale ha una o più cause/obiettivi, 
anche se non ne siamo consapevoli.</p>

<p>Esempio: Se una persona dimentica ripetutamente un appuntamento con qualcuno, secondo il 
    determinismo psichico non è necessariamente una coincidenza: potrebbe esserci un conflitto 
    inconscio, come il desiderio di evitare quella persona o la situazione.</p>


<h2>Le cause delle azioni: le pulsioni e la teoria delle pulsioni</h2>

<p>Le <strong>pulsioni</strong> sono spinte che nascono da bisogni corporei con l’obiettivo di soddisfare 
tali bisogni, così da riportare l’organismo al livello base di eccitamento (principio di costanza).</p>
<p>Freud riconosce due pulsioni fondamentali:</p>

<ol>
    <li><strong>Pulsioni di autoconservazione</strong>: a servizio della sopravvivenza dell’individuo;</li>
    <li><strong>Pulsioni sessuali</strong>: a servizio della sopravvivenza della specie.</li>
</ol>

<p>La teoria è di natura psicobiologica: Freud si ispirava alla fisica newtoniana e alla biologia 
    darwiniana, concependo gli esseri viventi in termini di materia, forza e movimento.</p>

<p>Ogni pulsione è caratterizzata da quattro dimensioni:</p>

<img XXclass="zoomable" src="/assets/images/01/07.webp" />

<ol>
    <li><strong>Fonte</strong>: il segnale corporeo che indica il bisogno</li>
    <li><strong>Obiettivo</strong>: la soddisfazione del bisogno</li>
    <li><strong>Impeto</strong>: la spinta motivazionale che porta l’individuo ad agire</li>
    <li><strong>Oggetto</strong>: il mezzo attraverso cui il bisogno viene soddisfatto</li>
</ol>

<img XXclass="zoomable" src="/assets/images/01/08.webp" />

<p>Esempio: un neonato che sente la fame (fonte) ha come obiettivo nutrirsi per riportare il corpo 
    ai livelli base. L’impeto lo spinge a cercare la madre (oggetto) per soddisfare il bisogno.</p>

<p>Con la teoria delle pulsioni, Freud introduce il</p>

<ul>
    <li><strong>principio di piacere</strong>: cerca la <strong>gratificazione immediata</strong> 
    dei bisogni, evita il dolore e ricerca il piacere.</li>
    <li><strong>principio di realtà</strong>: Rimanda la gratificazione se necessario, tiene 
    conto dei limiti imposti dalla realtà e delle conseguenze delle azioni.</li>
</ul>

<img XXclass="zoomable" src="/assets/images/01/09.webp" />

<p>Esempio: Immagina di avere fame durante una lezione.</p>

<ul>
    <li>Principio di piacere: “Ho fame, mangio subito.”</li>
    <li>Principio di realtà: “Aspetto la fine della lezione, poi mangerò.”</li>
</ul>

<h2>La teoria della sessualità infantile</h2>

<p>La <strong>teoria della seduzione infantile</strong> di Freud afferma che le nevrosi derivano da 
traumi sessuali realmente subiti nella prima infanzia (prima dei 6 anni), rimossi nell’inconscio 
e riattivati con la pubertà, dando origine ai sintomi.</p>

<p>Freud successivamente concluse che molti di quei traumi non si erano mai verificati: 
    quelli che i pazienti ricordavano come eventi reali erano in realtà ricordi 
    di <strong>desideri</strong>.</p>

<p>Così nel 1897 formulò la <strong>teoria della sessualità infantile</strong>: alla base delle 
nevrosi non vi sono necessariamente traumi sessuali realmente vissuti, ma anche <strong>desideri, 
fantasie e conflitti inconsci</strong> propri del bambino.</p>

<img XXclass="zoomable" src="/assets/images/01/10.webp" />

<p>Secondo Freud la sessualità è presente fin dalla nascita e non compare solo con la pubertà. 
    Per sessualità Freud non intende solo la sessualità genitale adulta, ma la ricerca di piacere 
    attraverso diverse parti del corpo (le <strong>zone erogene</strong>).</p>

<p>Lo sviluppo sessuale avviene attraverso una serie di <strong>stadi psicosessuali</strong> (orale, anale, fallico, 
    latenza e genitale), ciascuno caratterizzato dal predominio di una diversa zona erogena.</p>

<p>Ogni fase dello sviluppo psicosessuale è caratterizzata da un <strong>conflitto</strong> tra le pulsioni del 
    bambino e le richieste della realtà e della società. Per superarlo, il bambino deve imparare 
    a orientare la libido verso forme di gratificazione più mature. 
    Se il conflitto viene risolto, lo sviluppo procede normalmente; se non viene risolto, 
    possono verificarsi fissazioni o regressioni che, secondo Freud, influenzano la personalità 
    e possono favorire la comparsa di disturbi psicologici.</p>

<h3>Le fasi dello sviluppo psicosessuale</h3>

<ol>
    <li><strong>Fase orale</strong> (dalla nascita ai 18 mesi ca.): la zona erogena è la bocca. 
    Il bambino impara a fare i conti con la realtà e a segnalare i propri bisogni, prendendo 
    coscienza di non poterli soddisfare da solo;</li>
    <li><strong>Fase anale</strong> (dai 18 mesi ai 2-3 anni ca.): la zona erogena è l’area anale. 
    Il bambino impara a rinunciare al piacere anale per assecondare i genitori, 
    attraverso l’educazione sfinterica;</li>
    <li><strong>Fase fallica</strong> (dai 2-3 anni ai 5-6 anni ca.): la zona erogena è l’area 
    genitale. Il conflitto centrale è il <strong>complesso di Edipo</strong>, che ha un ruolo determinante 
    nella formazione della personalità e nella salute mentale dell’individuo;</li>
    <li><strong>Fase di latenza</strong> (dai 6 anni alla pubertà): lo sviluppo sessuale subisce un 
    arresto in seguito al superamento del complesso di Edipo. Il bambino, attraverso la scuola, 
    apprende i comportamenti sociali adattivi;</li>
    <li><strong>Fase genitale</strong> (età adulta): fase della maturità sessuale. Si compie 
    il passaggio dall’autoerotismo allo stadio oggettuale: la libido, inizialmente centrata 
    su sé stessi, si dirige verso gli altri, permettendo relazioni sociali e intime soddisfacenti.</li>
</ol>

<p>L’intero sviluppo psicosessuale tende quindi alla socializzazione: dall’attenzione su di 
    sé al progressivo orientamento verso il mondo esterno e le relazioni.</p>

<h3>Il complesso di edipo</h3>

<img XXclass="zoomable" src="/assets/images/01/11.webp" />

<p>Nella fase fallica il bambino prova un forte attaccamento verso il genitore del sesso opposto e 
    vede il genitore dello stesso sesso come un rivale. Secondo Freud, il bambino teme di essere 
    punito dal genitore rivale con la castrazione (angoscia di castrazione), perciò rinuncia a 
    questi desideri, si identifica con il genitore dello stesso sesso e ne interiorizza i valori 
    e le regole, contribuendo così alla formazione della personalità e del Super-Io.</p>

<p>Il complesso di Edipo rappresenta la tappa più importante dello sviluppo psicosessuale. 
    Freud stesso riconobbe la debolezza di questa teoria nel caso delle bambine.</p>

<p>(Gemini) Per la bambina si parla di <strong>Complesso di Elettra</strong> (termine in realtà introdotto da 
    Carl Gustav Jung, ma che descrive la variante femminile). Nelle bambine il processo è speculare 
    ma con una dinamica diversa: non essendoci l’angoscia di castrazione, si parla di 
    “invidia del pene”, e la risoluzione del complesso (e la conseguente formazione del 
    Super-Io) è considerata da Freud un po’ più sfumata e complessa rispetto a quella maschile.</p>

