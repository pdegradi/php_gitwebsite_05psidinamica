<h2>Il sogno secondo Freud e la scoperta del sonno REM</h2>



<h3>Il sogno per Sigmund Freud</h3>
<p>Nel 1900 Freud pubblica "L'interpretazione dei sogni", dove definisce il sogno come la realizzazione di un desiderio. È la
soddisfazione allucinatoria di un desiderio infantile rimosso che, attraverso il lavoro onirico, produce un sogno manifesto
dietro cui si nasconde un sogno latente. Con Freud, sonno e sogno smettono di essere considerati processi passivi.</p>



<h3>Le idee precedenti a Freud</h3>
<p>Prima di Freud il sonno era visto come un processo passivo. Nel 1912 Coriat lo definiva "uno stato passivo di assoluto riposo
del cervello", e nel 1913 Piéron lo descriveva come "uno stato fisiologico periodicamente necessario... caratterizzato da
un'interruzione dei complessi rapporti sensoriali e motori che collegano il soggetto con il suo ambiente". Anche nell'arte di
fine Ottocento il sonno era raffigurato come una sorta di morte reversibile.</p>



<h3>La scoperta del sonno REM (1953)</h3>
<p>Nel 1953 <strong>Eugene Aserinsky</strong> e <strong>Nathaniel Kleitman</strong>, osservando il sonno di alcuni bambini,
notarono fasi con movimenti oculari rapidi sotto le palpebre e un tracciato EEG desincronizzato, simile a quello della veglia.
Questa fase, trovata poi anche negli adulti, venne chiamata sonno <strong>REM</strong> (Rapid Eye Movements, movimenti oculari
rapidi).</p>






<h2>I due processi che regolano il sonno (Borbély, 1982)</h2>
<p>Secondo Borbély, il sonno è regolato da due processi: il <strong>processo omeostatico</strong> (processo S), per cui il tempo
necessario per addormentarsi è inversamente proporzionale alla durata della veglia precedente, e il <strong>processo
circadiano</strong> (processo C), l'orologio biologico interno, regolato soprattutto dal ciclo luce-buio e da stimoli sociali
come l'orario della cena.</p>



<h3>Il processo omeostatico</h3>
<p>Ogni sistema vivente complesso è auto-correttivo, cioè cerca sempre un equilibrio omeostatico (uno stato stabile). Gli stati
di veglia sono regolati da un sistema di cellule e fibre nervose nel tronco encefalico, la <strong>formazione reticolare
attivante</strong>, che invia informazioni a talamo e corteccia. Quando questo sistema si inibisce, si entra nel sonno
profondo. L'equilibrio tra sonno e veglia è regolato dall'inibizione reciproca tra il sistema di veglia e il <strong>nucleo
preottico ventro-laterale</strong>, considerato oggi l'interruttore che fa passare il cervello dalla veglia al sonno.</p>



<h3>Il processo circadiano</h3>
<p>Sonno e veglia sono cicli circadiani (dal latino "circa diem", quasi un giorno) con un ritmo di circa 24 ore, regolati
dall'orologio biologico, la cui base neurobiologica è il <strong>nucleo ipotalamico sopra-chiasmatico</strong>. Il processo
circadiano è regolato anche da segnali temporali esterni, chiamati <strong>Zeitgeber</strong> (in tedesco, "datori di tempo"). Il
principale è il ciclo luce-buio, ma contano anche altri fattori ambientali e sociali, come l'orario della cena o l'attività
sportiva. Non è solo il ciclo sonno-veglia a seguire un ritmo circadiano: anche altre funzioni fisiologiche (come la temperatura
corporea) e comportamentali (come l'orario dei pasti) fanno lo stesso.</p>






<h2>Lo studio del sonno REM</h2>



<h3>Lo studio del sonno</h3>
<p>Il sonno si studia con la <strong>polisonnografia</strong>, una tecnica che misura insieme l'attività cerebrale (EEG), i
movimenti oculari (EOG) e il tono muscolare (EMG). Grazie a questa tecnica sappiamo che il sonno non è affatto un processo
passivo: si articola in fasi ben distinte. Il primo episodio di sonno REM compare dopo circa 90 minuti dall'inizio del sonno. In
una notte di circa 8 ore se ne contano in media 4-5, con il primo che dura circa 20 minuti e i successivi 30-35 minuti. Il sonno
profondo (stadio N3) prevale nella prima parte della notte, il sonno REM nella seconda.</p>



<h3>Il sonno REM</h3>
<p>Durante il sonno REM, il tracciato EEG somiglia a quello della veglia, l'EOG mostra movimenti oculari rapidi, e l'EMG mostra
una drastica caduta del tono muscolare. Questa fase corrisponde al periodo di maggiore incidenza di sogni: circa il 70% dei
risvegli durante il REM è seguito da un resoconto di sogno.</p>



<h3>I correlati neurobiologici del sonno REM</h3>
<p>Durante il sonno REM, i neuroni del <strong>tegmento pontino</strong> (una zona del tronco encefalico) inviano segnali a
talamo e corteccia, generando la desincronizzazione EEG tipica di questa fase. Inviano segnali anche al midollo spinale,
responsabile della perdita di tono muscolare. Gli studi di neuroimaging mostrano che durante il sonno REM si attivano il
tegmento pontino, l'amigdala e la corteccia paraippocampale, il cingolo anteriore e il talamo, mentre si disattivano il cingolo
posteriore e la corteccia prefrontale dorso-laterale. Questa forte attivazione delle aree limbiche (legate alle emozioni) è
stata collegata alla valenza emotiva tipica dei sogni.</p>






<h2>Il sonno nella prima infanzia</h2>
<p>La distinzione in quattro fasi (REM e i tre stadi NREM) non è presente fin dall'inizio. Dalla nascita fino a circa il sesto
mese di vita, il sonno si divide in due sole fasi. Il <strong>sonno attivo</strong> è il futuro sonno REM: occupa circa il 50%
del sonno totale, una proporzione molto più alta che nell'età adulta, collegata all'importanza dell'apprendimento emotivo nei
primi anni di vita. Il <strong>sonno tranquillo</strong> è il futuro sonno NREM, altrettanto il 50%, e non è ancora suddiviso in
sotto-fasi.</p>

<p>Nel documentario "Wide Awake" di Alan Berliner, che racconta il proprio disturbo del sonno nel momento in cui diventa padre,
si osservano bene questi due stati: fasi di sonno profondo e immobile, e fasi di sonno attivo in cui il neonato sorride, muove
il volto ed è possibile osservare movimenti oculari.</p>






<h2>Misurare il sonno</h2>



<h3>La fase di addormentamento</h3>
<p>Generalmente si impiegano 15-20 minuti per passare da uno stato vigile ad assonnato, e poi al sonno leggero, senza che ci sia
una percezione precisa del momento esatto in cui ci si addormenta. Per convenzione si parla di sonno conclamato a partire dallo
stadio N2.</p>



<h3>I metodi di indagine</h3>
<p>Per studiare il sonno si usano diverse tecniche, ciascuna con vantaggi e limiti:</p>
<ul>
<li>la <strong>polisonnografia</strong>, condotta in laboratorio per due notti (la prima di adattamento, la seconda di
misurazione), è costosa, invasiva e artificiosa. Spesso la notte di adattamento, scomoda per chi non è abituato all'ambiente,
viene dormita peggio: per questo la notte successiva di misurazione tende a mostrare un sonno "di recupero" migliore di quello
abituale;</li>
<li>l'<strong>attigrafia</strong> (un dispositivo da polso, o da caviglia nei bambini) permette di valutare il sonno in
ambiente naturale, per periodi più lunghi e a basso costo, ma misurando solo il movimento confonde talvolta l'assenza di
movimento con il sonno vero e proprio;</li>
<li>i <strong>diari del sonno</strong> permettono un'osservazione sistematica e naturale, ma non misurano gli indici
fisiologici;</li>
<li>i <strong>questionari sul sonno</strong> danno una stima retrospettiva della qualità percepita, ma non sistematica.</li>
</ul>
<p>È quindi raccomandata la combinazione di più tecniche.</p>



<h3>Le variabili della continuità del sonno</h3>
<p>Tra le variabili che misurano la continuità del sonno troviamo il <strong>tempo totale a letto</strong>, il <strong>tempo
totale di sonno</strong>, il <strong>tempo totale dedicato al sonno</strong>, la <strong>latenza di addormentamento</strong>,
l'<strong>indice di efficienza del sonno</strong> (il rapporto tra tempo di sonno e tempo a letto: più è alto, migliore è la
qualità del sonno), il <strong>tempo di veglia notturna</strong> e il <strong>risveglio precoce</strong>. Queste variabili si
ottengono con polisonnografia, attigrafia e diari del sonno, e solo in parte con i questionari.</p>



<h3>Le variabili dell'architettura del sonno</h3>
<p>L'architettura del sonno si misura invece attraverso la durata dei diversi stadi (N1, N2, N3, REM), la loro latenza (il
tempo che intercorre dall'inizio del sonno al raggiungimento di ciascuno stadio) e la densità dei movimenti oculari rapidi
durante la fase REM. Sono variabili identificabili solo attraverso la polisonnografia.</p>






<h2>A cosa serve il sonno?</h2>



<h3>Perché dormiamo?</h3>
<p>È una domanda rimasta a lungo senza risposta chiara. Come scriveva <strong>Allan Rechtschaffen</strong> nel 1978, "se il
sonno non servisse a qualche funzione vitale, sarebbe il più grave errore dell'evoluzione". Nonostante i progressi delle
conoscenze, non esiste ancora una risposta definitiva. Probabilmente perché il sonno, come la veglia, svolge insieme diverse
funzioni: emotive, cognitive e sociali.</p>



<h3>Le alterazioni del sonno nei disturbi mentali</h3>
<p>Una metanalisi ha confrontato pazienti con diversi disturbi mentali e soggetti sani su tre variabili: la <strong>continuità
del sonno</strong> (efficienza, tempo totale di sonno, latenza di addormentamento), la <strong>profondità del sonno</strong>
(durata del sonno NREM) e la <strong>pressione del sonno REM</strong> (durata, latenza e densità del REM). La continuità del
sonno risultava alterata in quasi tutti i disturbi, tranne il disturbo esternalizzante e il disturbo affettivo stagionale.
Anche profondità e pressione REM mostravano differenze, seppure meno marcate. Le due ultime variabili risultavano inoltre
particolarmente associate alla comorbilità tra più diagnosi psichiatriche (cioè alla presenza di più disturbi insieme nella
stessa persona). La continuità del sonno emerge quindi come una variabile centrale nella psicopatologia.</p>



<h3>Il sonno e le emozioni (Beattie e colleghi, 2015)</h3>
<p>Una rassegna del 2015 ha riassunto gli studi su deprivazione o cattiva qualità del sonno e regolazione emotiva, utilizzando
neuroimaging, misure fisiologiche, comportamentali e di intelligenza emotiva. I risultati mostrano un forte effetto della
qualità del sonno sui processi affettivi. Chi dorme male o poco mostra una ridotta espressività facciale, difficoltà nel
riconoscere le emozioni, una maggiore reattività emozionale e una correlazione negativa tra qualità del sonno e intelligenza
emotiva.</p>



<h3>Il sonno e la reattività dell'amigdala a stimoli visivi</h3>
<p>In uno studio di neuroimaging, alcuni studenti universitari sani, privati di sonno, sono stati confrontati con un gruppo che
aveva dormito normalmente. Gli studenti privati di sonno mostravano una maggiore reattività dell'amigdala di fronte a immagini
emotivamente negative. Mostravano anche un'alterazione dei circuiti che connettono la corteccia prefrontale (che normalmente
regola le risposte emotive) all'amigdala. La mancanza di sonno sembra quindi compromettere proprio i processi corticali che ci
aiutano a controllare le emozioni.</p>



<h3>L'ipotesi del sonno REM (Matthew Walker)</h3>
<p>Da questi studi nasce l'<strong>ipotesi del sonno REM</strong>, proposta da <strong>Matthew Walker</strong>, che parte da una
definizione di <strong>memoria emotiva</strong> fatta di due elementi: un ricordo, e il <strong>tono affettivo</strong>
(l'intensità emotiva) a esso legato. L'ipotesi viene approfondita nel capitolo successivo.</p>

