<h2>La teoria dell'attaccamento</h2>
<p>Agli inizi degli anni '40 la società psicoanalitica britannica era divisa in tre gruppi teorici: 
    il gruppo di Anna Freud e degli psicologi dell'Io, il gruppo di Melanie Klein e degli esponenti della teoria kleiniana, e, 
    a metà tra i due, gli indipendenti della Scuola Inglese delle Relazioni Oggettuali. È in questo terzo gruppo che si colloca
<strong>John Bowlby</strong>.</p>

<img XXclass="zoomable" src="/assets/images/11/Screenshot 2026-10-05 200742.webp" />

<p>Bowlby ha proposto una teoria del funzionamento psichico basata sulla motivazione primaria di stabilire un legame profondo, 
    di <strong>attaccamento</strong>, con la madre.</p>
    
<p>La teoria di Bowlby sull'attaccamento è stata accolta con molte critiche e poco entusiasmo dalla società psicoanalitica 
britannica.</p>

<p>Va comunque sottolineato che nessun altro autore psicoanalitico ha avuto un'influenza pari a quella di Bowlby nel mettere in 
    relazione la psicoanalisi con altre discipline, come la psicologia empirica e la biologia.</p>

<p>La comunità psicoanalitica dell'epoca muoveva a Bowlby due critiche fondamentali:</p>
<ol>
<li>Bowlby dava <strong>poco</strong> peso alle differenze individuali e costituzionali, 
    mettendo invece in primo piano gli aspetti evolutivi comuni a tutti gli esseri umani e 
    l'importanza del primo ambiente e delle prime relazioni socio-emotive;</li>
<li>La teoria dell'attaccamento, per essere verificata empiricamente, traduce i concetti psicoanalitici 
in <strong>definizioni operazionali</strong> (definizioni basate su comportamenti osservabili e misurabili). 
Secondo alcuni autori psicoanalitici, questa semplificazione era già di per sé un problema, perché rischiava di distorcere 
concetti troppo complessi per essere ridotti a comportamenti osservabili</li>
</ol>



<p>Nonostante queste critiche, la psicoanalisi contemporanea condivide molti aspetti con la teoria dell'attaccamento</p>
<ul>
<li>nella teoria dell'attaccamento l'ambiente sociale ha un ruolo centrale nella formazione della mente;</li>
<li>le esperienze della prima infanzia restano fondamentali per lo sviluppo della personalità;</li>
<li>Bowlby condivide con la psicoanalisi contemporanea l'idea di un <strong>inconscio rappresentazionale</strong>: non più un inconscio
rimosso come in Freud, ma un inconscio implicito, vicino sia alla psicodinamica contemporanea sia alla psicologia cognitiva.</li>
</ul>
<p>Per le teorie della svolta relazionale possono esistere differenze costituzionali tra le persone, ma il loro significato dipende
soprattutto da come reagiscono le persone significative intorno a noi. Biologia e ambiente si influenzano a vicenda fin
dall'inizio, in un processo continuo, e non vanno quindi studiati separatamente.</p>
<img XXclass="zoomable" src="/assets/images/11/Screenshot 2026-10-05 201519.webp" />






<h2>L'influenza dell'etologia</h2>
<p>Per comprendere la teoria dell'attaccamento occorre considerare l'influenza dell'<strong>etologia</strong>, definita come lo studio
comparato del comportamento animale.</p> 

<p>Il padre dell'etologia è <strong>Konrad Lorenz</strong>, che dall'osservazione dei comportamenti animali introdusse alcuni 
concetti poi ripresi da Bowlby.</p>



<h3>Konrad Lorenz e l'imprinting</h3>
<img XXclass="zoomable" src="/assets/images/Konrad-Lorenz.webp" />
<p>Lorenz introdusse il concetto di <strong>imprinting</strong>. Secondo Lorenz, negli animali esiste un <strong>periodo
sensibile</strong> in cui i piccoli riconoscono e apprendono le caratteristiche della figura principale del loro allevamento;
questo apprendimento, una volta avvenuto in quella finestra temporale, diventa irreversibile.</p>
<p>Lorenz studiò questo fenomeno nelle <strong>ochette selvatiche</strong>. Nelle prime 48 ore di vita, i piccoli imparano a seguire
il primo oggetto in movimento (di solito la madre) e lo riconoscono come figura principale del proprio allevamento, senza più
tornare indietro una volta passata questa finestra temporale.</p> 

<p>Per verificarlo, Lorenz si sostituì alla madre oca nelle prime ore di vita di alcune ochette, immergendosi in acqua: 
i piccoli iniziarono a seguire lui e a ignorare la madre biologica, che a sua
volta li ignorò e arrivò persino ad attaccarli.</p> 

<p>Una volta passata la finestra temporale, l'<strong>imprinting più naturale</strong>
non fu più possibile. Lorenz notò inoltre che, da adulte, queste oche cercavano di riprodurre comportamenti sociali e sessuali
tipici della specie umana</strong>.</p>

<p>Secondo Lorenz nasciamo con schemi innati di risposte socio-emotive che si attivano nell'incontro con
l'ambiente (di solito la madre biologica). Questi istinti sono specie-specifici. Se cambia la specie di riferimento, come
nell'esperimento di Lorenz, qualcosa va storto, perché si tratta di risposte stereotipate che, fuori dalla finestra del periodo
critico, non possono più essere modificate dall'esperienza.</p>



<h3>Harry Harlow e l'esperimento delle scimmiette</h3>
<img XXclass="zoomable" src="/assets/images/Harry-Harlow.webp" />
<p>Un altro contributo alla teoria dell'attaccamento viene da <strong>Harry Harlow</strong>, che nel 1958 descrisse alcuni 
celebri esperimenti sui comportamenti affettivi delle scimmiette.</p>

<p>All'epoca era diffusa l'idea che il bambino si legasse alla figura di allevamento solo perché questa garantiva la 
sopravvivenza fisiologica (il nutrimento). Harlow volle verificare ciò.</p>

<p>Harlow separò delle scimmiette dalla madre biologica tra le 6 e le 12 ore dopo la nascita e le allevò con due <strong>madri
surrogato</strong></p> 
<ul>
    <li>una schematica, di metallo, che però forniva il latte a richiesta</li>
    <li>una priva di latte, ma dalle fattezze più simili a una scimmia adulta e ricoperta di stoffa morbida</li>
</ul>
<p>Osservò che le scimmiette, oltre a nutrirsi dal latte della madre di
metallo, passavano la maggior parte del tempo aggrappate alla madre di stoffa, che diventava la loro base per affrontare oggetti
minacciosi introdotti nella gabbia. Le scimmiette che avevano trascorso più tempo con la madre di stoffa mostravano inoltre
comportamenti di curiosità ed esplorazione dell'ambiente più frequenti e intensi rispetto a quelle cresciute soprattutto con la
madre di metallo.</p>
<img XXclass="zoomable" src="/assets/images/11/Screenshot 2026-10-05 203144.webp" />
<p>Questo dimostrava che <strong>esistono dei bisogni primari che vanno al di là del soddisfacimento dei bisogni 
fisiologici</strong>.</p>
<p>Secondo la teoria classica di <strong>Sigmund Freud</strong> le scimmiette avrebbero dovuto legarsi alla
madre di metallo, l'unica in grado di soddisfare il bisogno di nutrimento. Invece preferivano caratteristiche come la morbidezza e
il calore. Per le scimmiette il bisogno primario non era essere nutrite, ma avere contatto con una figura di allevamento protettiva
e calda.</p>






<h2>John Bowlby e la Scuola Inglese delle Relazioni Oggettuali</h2>

<p>Tra gli autori psicoanalitici che più influenzarono Bowlby troviamo <strong>Fairbairn</strong>, 
che sostenenva che la motivazione fondamentale della vita non è la ricerca di piacere ma la ricerca di relazioni.</p> 
<img XXclass="zoomable" src="/assets/images/Fairbairn.webp" />
<p>Fairbairn aveva anche spiegato in questo modo la coazione a ripetere (che aveva portato Freud a introdurre la pulsione di morte). 
Per lui le persone hanno un tale bisogno di relazioni umane che preferiscono restare in legami disfunzionali piuttosto che isolarsi
completamente.</p>



<h3>I principi della teoria dell'attaccamento</h3>
<p>Secondo Bowlby, la <strong>motivazione primaria degli esseri umani è la ricerca di contatto</strong>, di attaccamento, con una 
figura di allevamento principale. Questa motivazione è innata e specie-specifica, e si manifesta in comportamenti universali 
quali la ricerca di vicinanza, la suzione, il sorriso, l'abbraccio, il pianto e il seguire.</p>

<img XXclass="zoomable" src="/assets/images/Bowlby.webp" />

<p>Bowlby sostiene che gli istinti umani sono già <em>tarati</em> fin dalla nascita per funzionare bene in un ambiente 
sociale umano tipico. </p>

<p>Infine Per Bowlby le ipotesi teoriche vanno sempre valutate sulla base di studi empirici.</p>

<p>Per Bowlby l'attaccamento è ricerca di sicurezza, caratterizzata da:</p>
<ul>
<li>il bisogno di <strong>stare vicino</strong> a un'altra persona, e di tornare vicino a lei se questa vicinanza viene a mancare;</li>
<li>il bisogno che questa persona sia <strong>sempre la stessa</strong>, riconosciuta dal bambino: di solito è la madre biologica, 
ma può essere chiunque svolga stabilmente questo ruolo, per esempio una madre adottiva.</li>
</ul>



<h3>L'attaccamento come istinto e il sistema di attaccamento</h3>
<p>L'<strong>attaccamento è un istinto innato, e selezionato per il mantenimento della specie</strong>. 
I legami emotivi intimi si sviluppano grazie al sistema di attaccamento presente sin dalla nascita.</p>

<p>Come per Lorenz, anche per Bowlby il <strong>comportamento di attaccamento svolge una funzione biologica fondamentale, cioè 
garantisce la sopravvivenza</strong>, aumentando le probabilità di sopravvivenza del bambino. Il centro di questa teoria 
è la specie, non l'individuo. Ed è proprio questo uno degli aspetti più criticati dalla comunità psicoanalitica dell'epoca.</p>



<h3>I comportamenti di attaccamento</h3>
<p>I comportamenti di attaccamento sono specie-specifici e diretti verso l'obiettivo di stabilire la vicinanza con la madre. 
    Possono essere:</p>
<ul>
<li><strong>comportamenti segnale</strong>: per esempio vocalizzare, sorridere;</li>
<li><strong>comportamenti avversivi</strong>: per esempio gridare o piangere, per richiamare l'attenzione della madre;</li>
<li><strong>comportamenti attivi</strong>: per esempio avvicinarsi e seguire.</li>
</ul>
<p>La vicinanza garantisce il senso di sicurezza che, a sua volta, permette l'attivarsi di 
<strong>comportamenti esplorativi</strong>, i quali invece non si attivano quando la sicurezza è minacciata.</p>

<p>Non dovendo spendere energie per garantirsi la sicurezza, il bambino può dedicarle all'esplorazione dell'ambiente e a 
uno sviluppo cognitivo, emotivo e motorio più rapido ed efficace.</p>



<h3>Il sistema di accudimento</h3>
<p>Il <strong>sistema di accudimento</strong> è il sistema che si attiva 
nella figura di allevamento principale quando i comportamenti di attaccamento del bambino segnalano il bisogno di vicinanza e 
sicurezza. Include comportamenti che offrono vicinanza, aiuto e protezione dal pericolo (per esempio un abbraccio confortante).</p>



<h3>L'attaccamento nell'arco del ciclo di vita</h3>
<p>Bowlby introdusse un concetto importante: l'attaccamento non riguarda solo la prima infanzia, ma <strong>è un tema centrale
della vita umana nell'arco dell'intero ciclo di vita</strong></p>

<p>Questa visione si contrappone alle <strong>teorie dell'arresto evolutivo</strong> (definizione di Stephen
Mitchell), diffuse tra gli psicologi dell'Io. Per queste teorie l'ambiente dei primi anni è determinante, ma una volta che l'Io
si è formato, il destino dell'individuo è già segnato. Bowlby, al contrario, sostiene che i bisogni di attaccamento restano 
centrali in ogni età.</p>

<p>Le esperienze vissute con le figure di attaccamento nei primi anni rappresentano il modello
su cui si organizzano tutti i legami affettivi successivi, comprese le aspettative sulle situazioni nuove, la suscettibilità
alla paura, la valutazione del proprio valore personale e la possibilità di ricevere riconoscimento e aiuto.</p>



<h3>I modelli operativi interni (MOI)</h3>
<p>Attraverso le esperienze con le figure di accudimento, l'individuo costruisce i <strong>modelli operativi interni</strong> 
(MOI): rappresentazioni mentali di chi si prende cura di noi, di noi stessi e della relazione tra i due, che guidano il modo 
in cui interpretiamo gli eventi e ci fanno formare aspettative sulla nostra vita relazionale.</p> 

<p>Si formano perché le prime interazioni con i genitori vengono astratte in modelli generali di come funziona di solito una relazione: 
un concetto vicino all'<strong>inconscio rappresentazionale</strong> già incontrato nella teoria intersoggettiva (l'inconscio 
preriflessivo), cioè un contenuto inconscio non perché rimosso, ma perché implicito.</p>



<h3>Il metodo: la sensibilità empirica di Bowlby</h3>
<p>Secondo Bowlby le <strong>ipotesi teoriche devono essere valutate sulla base di studi empirici</strong>. 
In particolare, la teoria dell'attaccamento doveva essere verificata attraverso l'<em>osservazione diretta del comportamento 
del bambino in situazioni angosciose di separazione dalla figura materna</em>.</p> 


