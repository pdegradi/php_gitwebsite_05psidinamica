<h2>La diagnosi in psicologia dinamica</h2>



<h3>La diagnosi psicologica</h3>
<p>Secondo la definizione di <strong>Dazzi</strong>, <strong>Lingiardi</strong> e <strong>Gazzillo</strong> (2009), valida per la
psicologia e la psicoterapia in generale: "per <strong>diagnosi psicologica</strong> intendiamo sia il processo per mezzo del quale
cerchiamo di conoscere il funzionamento psichico di un determinato soggetto, sia la denominazione, basata su una terminologia
condivisa dalla comunità scientifica, che attribuiamo a tale funzionamento".</p>



<h3>Cosa deve identificare la diagnosi?</h3>
<p>Da un lato, la diagnosi deve identificare gli aspetti specifici e individuali di quel particolare paziente, unico nella propria
esperienza di vita; dall'altro, deve definire ciò che quel paziente ha in comune con altri, sottolineando gli aspetti
generalizzabili dei sintomi. Senza denominatori comuni tra i profili psicologici, sarebbe impossibile comunicare tra clinici o
basarsi su protocolli di trattamento già validati in letteratura.</p>



<h3>A cosa serve la diagnosi psicologica?</h3>
<p>Serve a <strong>condividere le informazioni</strong> tra clinici (e con il paziente) con un linguaggio semplice e sintetico; a
<strong>orientare il trattamento</strong>, confrontando le proprie ipotesi con la letteratura clinica ed empirica disponibile; e a
<strong>fare ricerca e orientare la clinica</strong>, raccogliendo informazioni sistematicamente su campioni rappresentativi in
base a caratteristiche comuni.</p>



<h3>La formulazione del caso</h3>
<p>La diagnosi psicologica non si esaurisce nell'assegnare un'etichetta: il processo diagnostico si completa nella
<strong>formulazione del caso</strong>, il resoconto narrativo e sistematico delle informazioni raccolte durante la valutazione,
che sottolinea sia gli aspetti individuali del paziente sia il modo in cui si inseriscono in un quadro già conosciuto, con
l'obiettivo di comunicare chiaramente quanto appreso, al paziente stesso o a un altro professionista.</p>






<h2>La diagnosi descrittiva</h2>
<p>Il riferimento internazionale più usato oggi in psicologia e psichiatria è la <strong>diagnosi descrittiva</strong>, rappresentata
soprattutto dal <strong>DSM</strong> (manuale diagnostico e statistico dei disturbi mentali, giunto alla quinta edizione), basata
sulle informazioni riferite dai pazienti (sintomi) o direttamente osservabili (segni). È <strong>ateorica</strong>: non si fonda su
un modello di funzionamento mentale predefinito, ma su ciò che il paziente riporta e su ciò che è osservabile oggettivamente,
permettendo la comunicazione tra clinici di orientamento diverso. È inoltre <strong>categoriale</strong>: identifica sindromi
discrete e separate (per esempio la depressione, definita da un elenco di sintomi di cui il paziente deve presentarne almeno 5, tra
cui i primi due obbligatori, per un periodo di almeno due settimane). Nell'ultima edizione, il DSM-5 (American Psychiatric
Association, 2013), la descrizione categoriale di ogni diagnosi è accompagnata da alcuni aspetti dimensionali, come la valutazione
della gravità dei sintomi o la presenza di sintomi transdiagnostici.</p>



<h3>Vantaggi e svantaggi della diagnosi categoriale</h3>
<p>Tra i <strong>vantaggi</strong>: crea un linguaggio comune tra professionisti di orientamenti diversi e tra clinica e ricerca; può
avere un effetto normalizzante per il paziente, che scopre di non essere un caso isolato; e fornisce indicazioni su sintomi che
potrebbero manifestarsi nel tempo. Tra gli <strong>svantaggi</strong>: porta a un'eccessiva <strong>comorbilità</strong> (un
paziente riceve più diagnosi, rendendo difficile stabilire una gerarchia di trattamento) e a un'eccessiva <strong>eterogeneità
interna</strong> (due pazienti con la stessa diagnosi possono avere storie ed esigenze molto diverse, per esempio una ragazza di 20
anni e un'anziana entrambe con depressione); inoltre non copre tutte le possibili cause di sofferenza e rischia di favorire
etichettamento e stigma (meglio dire "persona con disturbo depressivo" che "depresso", per distinguere la persona dal disturbo).</p>



<h3>Lo scetticismo della psicologia dinamica</h3>
<p>La psicologia dinamica ha sempre nutrito dubbi verso la diagnosi categoriale descrittiva, privilegiando il significato personale e
l'unicità dell'individuo; tuttavia, per poter identificare aspetti comuni tra pazienti diversi e condividerli con la comunità
scientifica, resta comunque necessario un linguaggio che colga gli aspetti generalizzabili.</p>






<h2>La diagnosi psicodinamica</h2>
<p>La valutazione in psicologia dinamica non si concentra su sintomi e segni, ma su aspetti più inferenziali: i meccanismi di difesa,
le angosce, il livello di compromissione delle funzioni psichiche e le relazioni oggettuali — aspetti di personalità intesi come
modi stabili di pensare, sentire, regolare le emozioni e agire, vicini ai concetti già visti di inconscio rappresentazionale,
memoria implicita e MOI.</p>



<h3>La diagnosi strutturale secondo Kernberg</h3>
<p>La <strong>diagnosi strutturale</strong> di <strong>Otto Kernberg</strong> integra la psicoanalisi freudiana e kleiniana, la
Psicologia dell'Io, la teoria delle relazioni oggettuali e le ricerche su infanzia e biologia delle emozioni. Il suo obiettivo non
è categorizzare i disturbi, ma elaborare un profilo dell'organizzazione di personalità, inferendo il livello di funzionamento da
indicatori emotivi, cognitivi, motivazionali e comportamentali osservabili.</p>



<h3>Le organizzazioni della personalità</h3>
<p>Kernberg identifica tre macrostrutture — <strong>psicotica</strong>, <strong>borderline</strong> e <strong>nevrotica</strong> —
valutate secondo tre criteri: la <strong>diffusione vs integrazione dell'identità</strong> (il grado in cui gli aspetti buoni e
cattivi di sé e degli altri sono integrati); la prevalenza di <strong>meccanismi di difesa maturi vs primitivi</strong> (i
primitivi si organizzano attorno alla scissione in "tutto buono"/"tutto cattivo", per esempio identificazione proiettiva, diniego,
idealizzazione; i maturi, come rimozione e spostamento, non distorcono la realtà e permettono soluzioni di compromesso); e la
<strong>tenuta dell'esame di realtà</strong> (la capacità di differenziare sé dagli altri e la fantasia dalla realtà). La
personalità nevrotica presenta un'identità integrata, difese mature ed esame di realtà mantenuto; quella psicotica presenta
identità dispersa, difese primitive ed esame di realtà alterato; quella borderline usa difese primitive ma può presentare
caratteristiche di entrambe le altre due riguardo a identità ed esame di realtà (quest'ultimo parzialmente mantenuto).</p>



<h3>L'intervista strutturale</h3>
<p>Per valutare questi criteri, il modello di Kernberg prevede un colloquio in tre fasi: nella <strong>fase iniziale</strong> il
clinico approfondisce la richiesta di aiuto del paziente e i tratti caratteriali patologici; nella <strong>fase centrale</strong>
esplora le rappresentazioni di sé e degli altri; nella <strong>fase conclusiva</strong> chiede se restano temi non trattati. Questo
colloquio è stato formalizzato nella "Structured Interview of Personality Organization" (Buchheim et al., 2006; Clarkin et al.,
2007), che richiede circa due ore e assegna punteggi da 0 (assenza di patologia) a 5 (funzionamento patologico) per ciascuna
dimensione. Come le altre proposte di diagnosi psicodinamica, questo strumento non intende sostituire la diagnosi descrittiva
categoriale, ma accompagnarla e avvicinare la ricerca alla pratica clinica.</p>






<h2>La Shedler-Westen Assessment Procedure (SWAP)</h2>
<p>Proposta da <strong>Drew Westen</strong> e <strong>Jonathan Shedler</strong>, la SWAP valuta tratti e stili di personalità, sani e
patologici, in adulti e adolescenti, partendo da una concezione dimensionale della personalità che va integrata con una concezione
categoriale per formulare una diagnosi appropriata.</p>



<h3>La diagnosi funzionale: quattro domini</h3>
<p>La diagnosi di personalità si basa su <strong>quattro domini funzionali</strong>: le motivazioni, gli standard ideali, i valori
morali, le paure e i conflitti; gli stili cognitivi, le strategie di regolazione delle emozioni e i meccanismi di difesa; le
rappresentazioni di sé, degli altri e delle relazioni tra i due; e il modo in cui questi domini si sono sviluppati nel corso della
vita.</p>



<h3>La procedura SWAP</h3>
<p>Attraverso l'esplorazione sistematica di questi domini, la SWAP fornisce una formulazione del caso condivisibile e generalizzabile,
avvicinando clinica e ricerca. Segue una procedura <strong>Q-sort</strong>: il clinico, dopo 3-5 colloqui di valutazione,
distribuisce 200 affermazioni descrittive (SWAP-200) su una scala da 0 (non descrive il paziente) a 7 (lo descrive totalmente),
seguendo però una <strong>distribuzione fissa</strong> del numero di item per ciascun punteggio, in modo da ridurre al minimo le
differenze soggettive tra valutatori.</p>



<h3>I fattori Q, o stili di personalità</h3>
<p>La SWAP individua diversi stili di personalità: <strong>disforico</strong> (inadeguatezza, fallimento, depressione, dipendenza,
passività); <strong>antisociale psicopatico</strong> (disonestà, ostilità, impulsività, manipolazione, bassa empatia);
<strong>schizoide</strong> (assenza di relazioni strette, emozioni ristrette, difficoltà a comprendere gli altri);
<strong>paranoide</strong> (sentirsi vittimizzato, ostilità, bassa tolleranza alle critiche); <strong>ossessivo</strong> (il più
adattivo: coscienziosità, alti standard morali, dedizione al lavoro); <strong>istrionico</strong> (dipendenza affettiva,
attaccamenti intensi e rapidi, paura dell'abbandono); e <strong>narcisistico</strong> (fantasie di successo e grandiosità, senso di
privilegio, bisogno di essere al centro dell'attenzione).</p>



<h3>Il fattore Q disforico: cinque sottofattori</h3>
<p>Rappresentando circa il 20% dei pazienti valutati, lo stile disforico è stato ulteriormente suddiviso in: <strong>evitante</strong>
(timidezza, evitamento sociale); <strong>depressivo ad alto funzionamento</strong> (umore disforico ma anche empatia e standard
etici); <strong>emotivamente disregolato</strong> (emozioni fuori controllo, pensieri suicidari);
<strong>dipendente-masochista</strong> (tendenza a rimanere in relazioni abusive); ed <strong>esteriorizzazione
dell'ostilità</strong> (rabbia, lotte di potere, sentirsi vittima).</p>






<h2>Una nuova nosografia: la SWAP-II</h2>
<p>Sulla base di analisi condotte su un ampio campione, Westen e Shedler (2007) hanno proposto una nosografia empiricamente derivata
in quattro cluster: <strong>interiorizzante</strong> (ansioso, depressivo, dipendente, schizoide), <strong>esteriorizzante</strong>
(psicopatico, paranoide, schizoide), <strong>borderline</strong> (emotivamente disregolato, istrionico/impulsivo) e uno stile di
<strong>alto funzionamento</strong>.</p>






<h2>Il Manuale Diagnostico Psicodinamico (PDM Task Force, 2006)</h2>
<p>Il <strong>PDM</strong> mira a integrare le informazioni del DSM, combinando gli aspetti <strong>idiografici</strong> (individuali,
dimensionali) con quelli <strong>nomotetici</strong> (generalizzabili). È opera dell'"Alliance of Psychoanalytic Organizations"
(che riunisce le principali società psicoanalitiche americane e internazionali), e tra i suoi autori figurano Kernberg, Westen e
Fonagy.</p>



<h3>Le caratteristiche principali del PDM</h3>
<p>Aggiunge gli aspetti dimensionali della psicopatologia a quelli categoriali del DSM; dà per scontata sia la comorbilità sia
l'eterogeneità interna ai disturbi; considera l'esperienza soggettiva del paziente, identificando la struttura di personalità come
il contesto in cui sintomi e segni assumono senso; sottolinea la dimensione evolutiva della diagnosi (una persona può cambiare
profilo nel tempo); e pone in rilievo le dimensioni implicite e inferenziali del funzionamento psichico.</p>



<h3>La struttura del PDM</h3>
<p>Il manuale si articola in tre parti: la diagnostica degli adulti, quella di adolescenti, bambini e neonati, e una raccolta di
articoli teorici e di ricerca su cui si fonda la nosografia.</p>



<h3>La classificazione dei disturbi mentali degli adulti</h3>
<p>La diagnosi degli adulti segue tre assi: l'<strong>Asse P</strong>, valutazione dei pattern e dei disturbi di personalità;
l'<strong>Asse M</strong>, valutazione del funzionamento mentale; e l'<strong>Asse S</strong>, valutazione dell'esperienza
soggettiva dei pattern sintomatici dei disturbi clinici.</p>


