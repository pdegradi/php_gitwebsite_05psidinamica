<h2>Melanie Klein (1882–1960)</h2>

<p>Melanie Klein lavorò direttamente con i bambini, applicando i principi psicoanalitici. 
    Il suo obiettivo non era costruire una teoria nuova.</p>

<img XXclass="zoomable" src="/assets/images/04/01.webp" alt="" />

<p>Lo strumento privilegiato dalla Klein fu il <strong>gioco</strong>, 
    considerato l’equivalente del sogno per Freud: un canale di accesso al materiale inconscio rimosso del bambino.</p>

<p>La Klein elaborò una teoria per molti aspetti distante da quella freudiana classica.</p>

<h2>Teoria Kleiniana</h2>

<p>I punti di continuità e di rottura con Freud possono essere così sintetizzati:</p>

<ul>
    <li><strong>origine delle pulsioni</strong>: Le pulsioni rimangono centrali, ma cambiano natura. 
        Per Freud sono forze biologiche (originano da un bisogno corporeo), 
        per Klein sono forze prevalentemente psicologiche.</li>
    <li><strong>rapporto pulsione-oggetto</strong>: per Freud la pulsione non è legata all’oggetto, 
        ma lo cerca per scaricare la tensione. Per Klein la pulsione è intrinsecamente 
        legata all’oggetto (nasce già orientata verso di esso).</li>
    <li><strong>Conflitto tra pulsioni di vita e morte</strong>: Questo conflitto rimane centrale, ma 
        la Klein sposta il focus dalla fase edipica (fallica), cruciale per Freud, alla 
        fase pre-edipica, considerata il vero terreno dello sviluppo psichico.</li>
    <li><strong>Strutture Io, Es, Super-Io</strong>: Per la Klein sono instabili e fluide, costantemente impegnate a contenere 
        la propria aggressività. Per Freud Io e Super-Io sono strutture stabili e 
        basate sulla razionalità.</li>
    <li>La <strong>pulsione di morte</strong> occupa un ruolo centrale, più di quanto non accada in Freud.</li>
</ul>


<h2>Gli affetti, oggetto secondo Freud</h2>

<p>Per Freud, gli affetti si strutturano su due livelli:</p>

<ul>
<li><strong>Esperienza corporea</strong>: ovvero dove nasce questa tensione nel corpo – è 
    la condizione preliminare perché si realizzi l’affetto.</li>
<li><strong>Esperienza fisica</strong>: ovvero la sensazione di piacere o dispiacere che ne deriva.</li>
</ul>

<p>L’esperienza corporea precede e rende possibile quella fisica.</p>

<p>L’<strong>oggetto</strong> è una dimensione marginale della 
    pulsione: è ciò che serve per scaricare la tensione pulsionale.</p>

<p>Freud riteneva che, quando avvertiamo un accumulo di tensione interna, troviamo accidentalmente 
    nel mondo esterno qualcosa che risulta utile a ridurla. La scelta dell’oggetto è quindi:</p>

<ul>
    <li><strong>casuale</strong>: non esiste un oggetto innato o predeterminato 
    verso cui siamo orientati;</li>
    <li><strong>strumentale</strong>: l’oggetto vale in quanto mezzo per scaricare 
    l’energia, non per le sue qualità intrinseche.</li>
</ul>

<p>Per Freud, gli <strong>oggetti</strong> (ad esempio il seno materno) sono i mezzi attraverso cui il bambino 
    soddisfa le proprie pulsioni e riduce la tensione interna.</p>

<p>Con l’esperienza, il bambino associa uno stesso oggetto alla soddisfazione dei suoi bisogni e tende 
    quindi a ricorrere sempre a quell’oggetto. Ad esempio, il seno materno diventa 
    l’oggetto abituale che soddisfa la fame.</p>

<p>La <strong>costanza dell’oggetto</strong> è la capacità del bambino di richiamare alla mente l’immagine del 
    genitore anche quando è assente. Questa capacità non è innata ma si acquisisce con lo sviluppo.</p>

<p>Per Freud, il legame affettivo con i genitori è <strong>secondario</strong> rispetto alla soddisfazione delle 
    pulsioni: il bambino si lega a loro perché sono coloro che soddisfano i suoi bisogni. 
    Inoltre, nessun oggetto è unico o speciale per natura.</p>


<h2>Le pulsioni come forze psicologiche secondo Klein</h2>

<img XXclass="zoomable" src="/assets/images/04/02.webp" alt="" />

<p>Per Klein, come per Freud, pulsioni di vita e di morte sono alla 
    base del funzionamento psichico. La differenza è che per Klein la <strong>pulsione</strong> è già 
    l’<strong>affetto</strong>, è la capacità di amare e odiare. Non esiste distinzione tra esperienza 
    corporea ed esperienza fisica.</p>

<p>Le esperienze vengono così organizzate in categorie affettive:</p>

<ul>
<li>tutto ciò che è associato all’amore → <strong>esperienze buone</strong>;</li>
<li>tutto ciò che è associato all’odio → <strong>esperienze cattive</strong>.</li>
</ul>

<p>La pulsione, per Klein, è quindi una <strong>modalità di organizzazione 
    delle esperienze in categorie buone e cattive</strong>.</p>


<h3>Le pulsioni come rappresentazione delle relazioni oggettuali</h3>

<p>In Klein, l’oggetto non è più consequente alla pulsione (come in Freud), 
    ma ne fa parte fin dall’inizio: le pulsioni sono <strong>intrinsecamente legate all’oggetto</strong>.</p>

<ul>
<li>La <strong>pulsione di vita</strong> (amore, protezione) contiene al suo interno l’immagine 
    di un oggetto allo stesso tempo amato e amorevole.</li>
<li>La <strong>pulsione di morte</strong> (odio, distruzione) contiene al suo interno l’immagine 
    di un oggetto da odiare e capace di odio.</li>
</ul>


<h2>Fantasia inconscia</h2>

<ul>
<li><strong>Freud</strong>: il bambino <strong>non nasce</strong> con la capacità di simbolizzare o fantasticare. 
    La sviluppa gradualmente con l’esperienza.</li>
<li><strong>Klein</strong>: il bambino <strong>nasce già</strong> con un’attività mentale fatta di fantasie inconsce. 
    La fantasia è presente fin dal primo giorno di vita.</li>
</ul>

<p >Per Melanie Klein, la <strong>fantasia inconscia</strong> è il modo in cui il neonato vive mentalmente 
    le proprie esperienze corporee e le proprie pulsioni. Non è una tappa evolutiva, 
    ma è innata e presente fin dalla nascita.</p>

<p>Ad esempio:</p>

<ul>
<li>il bambino ha fame → prova una sensazione spiacevole → nella sua fantasia inconscia 
    può vivere il seno come <strong>oggetto cattivo</strong>, perché non lo sta soddisfacendo;</li>
<li>il bambino viene allattato → prova piacere e sazietà → nella sua fantasia 
    inconscia vive il seno come <strong>oggetto buono</strong>.</li>
</ul>

<p>Queste sono rappresentazioni inconsce e primitive.</p>

<p>Ogni sensazione corporea viene vissuta come una relazione con un oggetto:</p>

<ul>
<li>una sensazione piacevole è collegata a un <strong>oggetto buono</strong>;</li>
<li>una sensazione spiacevole è collegata a un <strong>oggetto cattivo</strong>.</li>
</ul>

<p>Ogni fantasia inconscia è sempre accompagnata da un’emozione (affetto), e ogni 
    emozione è legata a una fantasia inconscia.</p>


<h2>Le relazioni oggettuali e gli oggetti interiorizzati</h2>

<p>La Klein quando parla di <strong>oggetto</strong>, non intende necessariamente un oggetto materiale. 
    In psicoanalisi, un <strong>oggetto</strong> è una persona (o una parte di essa) verso cui sono 
    dirette le pulsioni e gli affetti (esempio nel neonato, può essere il seno materno).</p>

<p>Per la Klein il bambino, fin dalla nascita, costruisce dentro di sé delle 
    <strong>rappresentazioni mentali degli oggetti</strong>, chiamate <strong>oggetti interni</strong>.</p>

<p>Questi oggetti interni non sono copie fedeli della madre reale, ma sono il 
    modo in cui il bambino la vive nella sua fantasia inconscia.</p>

<ul>
    <li>prova piacere e soddisfazione, l’oggetto viene vissuto come <strong>buono</strong>. Esempio 
        un seno che allatta (definito come <strong>seno buono</strong>)</li>
    <li>se prova frustrazione o disagio, viene vissuto come <strong>cattivo</strong>. Esempio seno 
        che non allatta (definito come <strong>seno cattivo</strong>)</li>
</ul>

<p>Queste immagini interne sono influenzate anche dalle pulsioni del bambino:</p>

<ul>
<li>le pulsioni d’amore (libidiche) favoriscono la costruzione di un oggetto buono;</li>
<li>le pulsioni aggressive favoriscono la costruzione di un oggetto cattivo.</li>
</ul>

<p>Per Klein, la nostra mente è popolata da questi oggetti interni e dalle relazioni che 
    instauriamo con essi. Per questo si parla di <strong>teoria delle relazioni oggettuali</strong>: 
    la vita psichica non è fatta solo di pulsioni, ma soprattutto di relazioni con 
    questi oggetti interiorizzati.</p>

<p>Sia per Freud che per Klein, il primo oggetto ricercato dal bambino è un <strong>oggetto 
    parziale</strong> — non una persona intera, ma una parte del corpo del genitore. Il principale 
    è il seno della madre, legato alla pulsione orale.</p>

<h2>La lotta tra amore e odio</h2>

<p>Per Klein esiste fin dalla nascita un conflitto innato tra <strong>amore</strong> (pulsioni di vita) 
    e <strong>odio</strong> (pulsioni di morte). Siamo costantemente impegnati in questa lotta interiore 
    tra il desiderio di amare ed essere amati e l’impulso a distruggere.</p>

<img XXclass="zoomable" src="/assets/images/04/03.webp" alt="" />

<p>La capacità di amare e odiare è in parte <strong>innata</strong>, ed è intrinsecamente legata alla 
    fantasia inconscia.</p>

<p>Il destino psichico — incluso il rischio di psicopatologia — dipende in primo luogo 
    dall’intensità innata delle pulsioni di vita o di morte con cui si nasce.</p>

<p>L’ambiente può avere effetto, ma è secondario rispetto ai fattori costituzionali.</p>

<h2>La mente per la Klein (e confronto con Freud)</h2>

<p>Per Freud, la risoluzione del conflitto edipico produce strutture psichiche stabili e 
    coerenti (Io e Super-Io). La salute mentale non consiste nel soddisfare sempre le 
    pulsioni, ma nell’essere soddisfatti in amore e nel lavoro, con una buona capacità 
    di adattamento alla realtà.</p>

<p>Per Klein, Io e Super-Io sono presenti fin dalla nascita, ma sono strutture <strong>instabili 
    e fluide</strong>, costantemente impegnate a contenere le forze dell’odio. Gli oggetti buoni 
    sono alla base della costruzione dell’Io e del Super-io, mentre gli oggetti cattivi 
    attivano le difese.</p>


<h2>Il senso di Sé</h2>

<p>Questa modalità di pensiero — dividere l’esperienza in buona o cattiva — è la base 
    della costruzione del Sé:</p>

<ul>
    <li>I sentimenti di <strong>odio</strong> verso gli oggetti cattivi generano <strong>angoscia persecutoria</strong>  
        (paura che l’oggetto cattivo possa fare del male) e una visione di sé come entità 
        odiata e distruttiva.</li>
    <li>I sentimenti di <strong>amore</strong> verso gli oggetti buoni producono una visione di sé come 
        entità amata e amorevole.</li>
</ul>


<h2>La teoria dello sviluppo</h2>

<p>Per Freud, lo sviluppo è organizzato in fasi psicosessuali (orale, anale, 
    fallica, ecc.).</p>

<p>Per Melanie Klein, lo sviluppo è organizzato in <strong>posizioni</strong>. Il termine posizione 
    è importante: non indica una fase che viene superata e lasciata alle spalle, 
    ma un modo di funzionare della mente.</p>


<h3>la posizione schizoparanoide (dalla nascita fino a circa 4-6 mesi)</h3>

<p>Il bambino divide il mondo in <strong>oggetti buoni</strong> e <strong>oggetti cattivi</strong> (scissione). 
    Questa scissione è una <strong>difesa sana e adattiva</strong>.</p>


<h3>La posizione depressiva (circa dai 4-6 mesi in poi)</h3>

<p>Il bambino inizia a capire che l’oggetto buono e quello cattivo sono la <strong>stessa 
    persona</strong> (ad esempio la madre). In questo modo il bambino entra in relazione con 
    l’oggetto intero (esempio la madre).</p>

<p>Il bambino entra in relazione sia con l’amore che con l’odio verso oggetti interni. 
    Questa posizione è caratterizzata dall’<strong>angoscia</strong> e dal <strong>senso di colpa</strong> 
    del danno che la propria aggressività infligge all’oggetto buono, perché si rende conto che oggetto 
    buono e cattivo sono la stessa cosa.</p>


<h2>L’invidia</h2>

<p>A volte il neonato desidera distruggere proprio il seno buono, perché non riesce a 
    tollerare la propria dipendenza da esso. Questo impulso distruttivo verso l’oggetto 
    amato è chiamato <strong>invidia</strong>, ed è associato a una pulsione di morte innata particolarmente intensa.</p>

<p>Nei pazienti più gravi (es. disturbi psicotici), alti livelli di invidia si manifestano 
    come ostilità verso il terapeuta o il trattamento stesso, e rappresentano 
    il principale ostacolo alla cura. Secondo Klein, l’intensità dell’invidia dipende 
    da fattori costituzionali innati.</p>


<h2>La mente adulta come struttura instabile</h2>

<p>A differenza di Freud, per cui lo sviluppo procede per tappe sequenziali 
    (fase orale → anale → fallica → ecc.), per Klein le due posizioni non vengono 
    superate, ma <strong>coesistono per tutta la vita</strong>.</p>

<p>Le due posizioni (schizoparanoide e depressiva) <strong>non vengono mai abbandonate 
    definitivamente</strong>. Crescendo, la posizione depressiva diventa quella prevalente perché è 
    più matura, ma la posizione schizoparanoide continua a esistere e può riemergere in 
    qualsiasi momento della vita.</p>

<p>Ad esempio, una persona adulta che attraversa una forte crisi, un lutto o una 
    situazione molto stressante può tornare temporaneamente a ragionare in modo più 
    “schizoparanoide”: tende a vedere le persone come completamente buone o completamente 
    cattive, senza riuscire a coglierne gli aspetti positivi e negativi insieme. 
    Questo, secondo Klein, non è necessariamente patologico: può essere un modo 
    temporaneo della mente per difendersi da emozioni troppo intense.</p>

<p>Anche la posizione depressiva non scompare mai. Nell’adulto continua a manifestarsi come:</p>

<ul>
<li>preoccupazione per le persone amate;</li>
<li>senso di colpa quando si pensa di averle ferite;</li>
<li>desiderio di riparare il danno.</li>
</ul>

<p>Per Klein, quindi, <strong>una mente sana non è una mente che ha superato una posizione</strong>, 
    ma una mente che riesce a muoversi tra queste modalità di funzionamento senza 
    rimanere bloccata in una di esse.</p>


<h3>Il ruolo dell’aggressività</h3>

<p>Per Klein, il problema fondamentale della vita psichica è <strong>gestire la propria 
    aggressività</strong>. Secondo lei, ogni essere umano nasce con pulsioni di amore e di odio. 
    Per tutta la vita queste due forze convivono e sono in conflitto:</p>

<ul>
    <li>da una parte desideriamo amare, proteggere e creare legami;</li>
    <li>dall’altra proviamo anche rabbia, odio e impulsi aggressivi.</li>
</ul>

<p>La maturità psicologica non consiste nell’eliminare l’aggressività (cosa impossibile), 
    ma nel <strong>riconoscerla</strong>, <strong>contenerla e integrarla</strong>, evitando 
    che distrugga le relazioni con gli altri.</p>

<p>Il conflitto tra amore e odio è <strong>innato</strong>, riguarda tutti e non può essere eliminato 
    definitivamente.</p>

<img XXclass="zoomable" src="/assets/images/04/04.webp" alt="" />

<h2>Il ruolo delle esperienze reali</h2>

<p>Ogni individuo nasce con una capacità innata di <strong>amare</strong> e di <strong>odiare</strong>, 
    che deriva rispettivamente dalle pulsioni di vita e dalle pulsioni di morte. La causa della psicopatologia è da 
    ricercare nei <strong>fattori innati</strong> (capacità di amare e odiare).</p>

<p>Tuttavia la Klein riconosce che l’<strong>ambiente</strong> esterno può modulare l’intensità delle 
    pulsioni. La relazione reale con le figure genitoriali — i ritmi dell’accudimento, 
    i tempi e i modi di risposta ai bisogni — può alleggerire le fantasie primitive e 
    favorire il passaggio dalla posizione schizoparanoide a quella depressiva.</p>

