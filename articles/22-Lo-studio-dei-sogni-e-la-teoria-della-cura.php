<h2>L'ipotesi del sonno REM: un sonno per ricordare, un sonno per dimenticare</h2>
<p>Secondo l'ipotesi del sonno REM, questa fase avrebbe una funzione importante per la memoria emotiva. Permetterebbe di
consolidare il ricordo di un evento, ma allo stesso tempo ne ridurrebbe, fino quasi a cancellarlo, il <strong>tono
affettivo</strong> (l'intensità emotiva legata al ricordo). Un evento traumatico, per esempio, viene spesso ricordato con
precisione, ma la sua intensità emotiva tende a scemare nel tempo. Questa riduzione è importante: senza di essa si rimarrebbe
in uno stato di iperattivazione, come accade nell'ansia eccessiva, dannosa per l'organismo. Per questo l'ipotesi è stata
chiamata anche "<strong>un sonno per ricordare e un sonno per dimenticare</strong>". Il sonno REM permetterebbe infatti di
consolidare il ricordo, rinforzando l'attività dell'ippocampo, privandolo però del suo tono affettivo, inibendo l'amigdala.</p>



<h3>Il sonno REM e i ricordi emotivi</h3>
<p>Amigdala e ippocampo si attivano entrambi durante il sonno REM. Questa attivazione potrebbe permettere il recupero di
informazioni emotive già acquisite. Allo stesso tempo, l'interazione tra circuiti sotto-corticali e corticali potrebbe favorire
l'integrazione del nuovo materiale emotivo con quello già appreso, permettendo di "vedere le cose da una prospettiva più
ampia". Le esperienze emotive negative verrebbero così rielaborate durante il sonno REM, confrontate con esperienze già
vissute, e la loro intensità ne risulterebbe ridotta. È un'ipotesi coerente con l'esperienza comune del "lasciar passare una
notte" prima di affrontare meglio una situazione stressante.</p>






<h2>Lo studio dei sogni: dal sonno REM ai sogni</h2>
<p>In psicofisiologia, un <strong>sogno</strong> (o il suo resoconto) è definito come il ricordo dell'attività mentale avvenuta
durante il sonno.</p>



<h3>L'equazione sonno REM e sogni</h3>
<p>Dopo la scoperta del sonno REM, si pensava che i sogni si verificassero esclusivamente durante questa fase. Gli studi hanno
però mostrato che anche risvegliando i soggetti durante il sonno NREM si raccolgono resoconti di sogni, sebbene meno frequenti
e diversi. I sogni REM, infatti, risultano più bizzarri e più intensi emotivamente di quelli NREM.</p>



<h3>I diversi tipi di sogni</h3>
<p>Si distinguono diversi tipi di sogni:</p>
<ul>
<li>i <strong>sogni REM</strong>: rilevati svegliando il soggetto durante questa fase, confermata dall'EEG;</li>
<li>i <strong>sogni NREM</strong>: meno bizzarri e meno intensi;</li>
<li>i <strong>sogni durante l'addormentamento</strong>;</li>
<li>gli <strong>incubi</strong>: sogni REM con emozioni negative intense che provocano il risveglio;</li>
<li>i <strong>terrori notturni</strong>: risvegli improvvisi durante il sonno profondo, associati a forte ansia;</li>
<li>le <strong>rievocazioni post-traumatiche</strong>: sogni REM o NREM in cui si rivive un trauma;</li>
<li>i <strong>sogni lucidi</strong>: il sognatore è consapevole di stare sognando.</li>
</ul>



<h3>I limiti dello studio dei sogni</h3>
<p>Non potendo osservare direttamente l'attività onirica, la ricerca dipende dai resoconti dei sognatori risvegliati. È un limite
importante: non possiamo essere certi che il ricordo corrisponda fedelmente all'esperienza vissuta, e questo ricordo è
influenzato da diverse caratteristiche individuali.</p>



<h3>Ricordare i sogni</h3>
<p>La capacità di ricordare i sogni varia da persona a persona, in base a diversi fattori:</p>
<ul>
<li><strong>personalità</strong>: creatività, apertura a nuove esperienze, memoria visiva;</li>
<li><strong>sonno</strong>: per esempio i risvegli notturni, più frequenti nell'insonnia — ma quando questi si riducono, il numero
di sogni ricordati si allinea a quello delle persone senza insonnia;</li>
<li><strong>il sogno stesso</strong>: i sogni più salienti o emotivamente intensi si ricordano meglio;</li>
<li><strong>la veglia</strong>: le interferenze al risveglio riducono la probabilità di ricordare il sogno.</li>
</ul>
<p>Questo significa che la ricerca può studiare solo una parte, probabilmente non rappresentativa, dei sogni fatti.</p>



<h3>I metodi di indagine: il sogno più recente e i diari dei sogni</h3>
<p>Il <strong>metodo del sogno più recente</strong> chiede di scrivere il sogno più recente ricordato. Non altera l'esperienza,
essendo ricostruttivo, ma rischia di sovra-rappresentare i sogni più bizzarri o salienti. I <strong>diari dei sogni</strong>,
trascritti ogni mattina, riducono questo rischio e permettono un'osservazione naturale e sistematica. Non permettono però di
correlare il contenuto con i processi neurofisiologici della notte.</p>



<h3>Gli studi di laboratorio</h3>
<p>Per colmare questo limite, gli <strong>studi di laboratorio</strong> risvegliano i partecipanti durante la polisonnografia, per
esempio in fase REM, e chiedono il resoconto del sogno. Questo permette di correlare contenuto e fisiologia, ma ha un limite:
soffre dell'artificiosità dell'ambiente (circa il 50% dei sogni raccolti in laboratorio menziona il laboratorio stesso) e
riduce la presenza di contenuti sessuali o aggressivi rispetto ai sogni raccolti a casa.</p>



<h3>L'analisi dei contenuti dei sogni</h3>
<p>Una volta raccolti, i sogni vengono sottoposti ad <strong>analisi dei contenuti</strong>, per trasformarli in dati
quantificabili. Si possono analizzare diversi aspetti:</p>
<ul>
<li><strong>aspetti del contenuto</strong>: per esempio il numero di persone presenti;</li>
<li><strong>aspetti formali</strong>: la lunghezza;</li>
<li><strong>aspetti emotivi</strong>: l'intensità delle emozioni;</li>
<li><strong>aspetti socio-emozionali</strong>: il tipo di interazioni.</li>
</ul>
<p>Per confrontare gruppi diversi, per esempio pazienti depressi e sani, occorre prima formulare un'ipotesi (per esempio, sogni
con più contenuti di rifiuto nella depressione) e poi costruire una scala valida e attendibile per codificarli.</p>



<h3>Le scale di misura e l'accordo tra i giudici</h3>
<p>I resoconti vengono valutati da più giudici indipendenti, in genere almeno due, che non conoscono l'appartenenza del sognatore
ai gruppi in studio. Questo serve a evitare che le proprie aspettative teoriche distorcano la valutazione. Prima di analizzare
i dati, si misura il grado di accordo tra i giudici: un accordo alto indica una scala semplice da usare e poco soggetta a
interpretazioni personali. Uno studio di <strong>Schredl</strong> e colleghi (2004) ha mostrato che addestrare i giudici sulla
codifica preliminare di 100-200 resoconti riduce al minimo le differenze individuali di interpretazione.</p>



<h3>Un solo sogno non basta</h3>
<p>Per confrontare in modo attendibile le differenze individuali di contenuto, forma ed emotività tra i sogni, uno studio di
Schredl e colleghi (2010) ha stimato che servano almeno <strong>20 sogni</strong> a persona.</p>



<h3>La codifica delle emozioni di un sogno</h3>
<p>È stato notato che i ricercatori tendono a sottostimare la presenza di emozioni nei sogni rispetto ai sognatori stessi.
Inoltre, tendono a codificarne la valenza come prevalentemente negativa, mentre i sognatori la percepiscono più bilanciata tra
positivo e negativo.</p>



<h3>La fenomenologia dei sogni</h3>
<p>Circa il 90% dei sogni è auto-riferito, cioè sogniamo prevalentemente noi stessi. Circa il 20% dei sogni raccolti in
laboratorio e il 30% di quelli raccolti nei diari presentano elementi di <strong>bizzarria</strong> (contenuti impossibili
nella realtà fisica, per esempio volare). Questa percentuale varia a seconda di quanto ampia sia la definizione usata. I colori
vengono raramente riportati nei resoconti. La quasi totalità dei sogni riportati coinvolge la vista, il 57% l'udito, mentre le
altre percezioni sensoriali (propriocezione, tatto, gusto, olfatto, dolore) sono molto meno frequenti.</p>



<h3>L'effetto della veglia sui sogni</h3>
<p>Diversi metodi hanno cercato di misurare quanto gli eventi della veglia influenzino i sogni:</p>
<ul>
<li>chiedere direttamente ai soggetti quali elementi del sogno corrispondano a episodi vissuti, un metodo limitato dalla memoria;</li>
<li>mostrare film emotivamente intensi o neutri prima di dormire, con un effetto debole;</li>
<li>valutare esperienze di vita reali particolarmente rilevanti, come un trauma o una psicoterapia in corso, che hanno una forte
influenza;</li>
<li>valutare le attività abituali della veglia, anch'esse fortemente influenti.</li>
</ul>
<p>L'ipotesi più condivisa è che i sogni siano rielaborazioni, fortemente influenzate da ciò che viviamo durante il giorno.</p>
<p>Gli elementi della veglia più presenti nei sogni sono soprattutto tre. Prima di tutto quelli più recenti: la loro influenza si
riduce esponenzialmente col passare del tempo, per cui gli eventi recenti influenzano di più i sogni della prima parte della
notte, mentre quelli più lontani nel tempo influenzano di più i sogni della seconda parte. Poi quelli più emotivamente
rilevanti, per esempio una seduta di psicoterapia. Infine le attività che richiedono meno concentrazione, come una telefonata
con un amico, più di un'attività di studio.</p>



<h3>L'effetto dei sogni sulla veglia</h3>
<p>Tre filoni di ricerca hanno studiato l'effetto inverso, cioè come i sogni influenzano la veglia:</p>
<ul>
<li>l'influenza degli incubi sull'umore del giorno dopo, legata soprattutto alla loro frequenza, a sua volta legata a stress e
personalità;</li>
<li>l'influenza dei sogni sulla creatività: gli elementi creativi nei sogni sono associati alla capacità di ricordarne molti e ad
altri tratti di personalità;</li>
<li>il rapporto tra sogni e psicoterapia: alcuni studi clinici mostrano che l'interpretazione dei sogni può promuovere l'insight
del paziente.</li>
</ul>



<h3>A cosa servono i sogni?</h3>
<p>La ricerca non è andata molto oltre le prime intuizioni di Freud, anche per i limiti metodologici di questo campo: non sappiamo
nulla, per esempio, dei sogni che non ricordiamo. Sono state comunque proposte diverse ipotesi sulla funzione dei sogni:</p>
<ul>
<li>semplici <strong>epifenomeni</strong> del consolidamento della memoria, senza una funzione propria;</li>
<li>un modo per rinforzare la nostra <strong>individualità</strong> all'interno della specie;</li>
<li><strong>protettori dalle minacce</strong>, che permettono di "allenarsi" a situazioni pericolose;</li>
<li><strong>guardiani del sonno</strong>, come sosteneva Freud;</li>
<li><strong>meccanismi compensatori</strong> di aspetti della personalità inibiti in veglia, secondo Jung;</li>
<li>un modo per <strong>dimenticare le informazioni inutili</strong> apprese durante il giorno, il che spiegherebbe la loro bizzarria;</li>
<li>un aiuto a <strong>risolvere i problemi</strong>, combinando nuove e vecchie informazioni (coerente con l'ipotesi del sonno REM);</li>
<li>uno strumento di <strong>regolazione dell'umore</strong>, che attenua le emozioni negative della giornata (anch'essa coerente
con l'ipotesi del sonno REM);</li>
<li>una forma di <strong>desensibilizzazione sistematica</strong>: permettono di provare ansia in uno stato rilassato, il tono
muscolare crollato del sonno REM, riducendone così l'intensità — un principio alla base di alcune tecniche psicoterapeutiche.</li>
</ul>
<p>Nessuna di queste ipotesi ha ricevuto, a oggi, un supporto empirico sufficiente. Solo le teorie della soluzione dei problemi e
della regolazione dell'umore risultano coerenti con l'ipotesi del sonno REM.</p>






<h2>Modulo 3 - La teoria della cura</h2>
<p>Secondo <strong>Mitchell</strong> e <strong>Black</strong>, la psicoanalisi clinica, al di là dei diversi orientamenti teorici,
riguarda fondamentalmente le persone e le loro difficoltà di vita. Si tratta di una relazione impegnata a raggiungere una
comprensione di sé più profonda, un senso più ricco di significato personale e una maggiore libertà. Queste tre caratteristiche
sono presenti in tutte le teorie psicoanalitiche, ma hanno un peso diverso a seconda dell'orientamento: la comprensione di sé è
più centrale nella psicoanalisi classica freudiana, il significato personale in teorie come quella di Winnicott o la Psicologia
del Sé, la libertà nella psicoanalisi intersoggettiva. La definizione di Mitchell e Black cerca quindi di racchiudere tutti
questi orientamenti in un approccio integrato.</p>



<h3>L'evoluzione della teoria psicoanalitica</h3>
<p>Riprendendo quanto visto nelle lezioni precedenti, la psicoanalisi contemporanea si distingue da quella classica freudiana su
quattro punti:</p>
<ul>
<li>la <strong>funzione della mente</strong>: da apparato per scaricare l'eccitamento a strumento per formare e preservare i
legami con gli altri;</li>
<li>l'<strong>inconscio</strong>: dall'inconscio rimosso all'inconscio rappresentazionale;</li>
<li>il <strong>trauma</strong>: da singolo evento con affetto eccessivo, a modalità disadattive di interazioni ripetute;</li>
<li>l'<strong>origine della psicopatologia</strong>: dalla fase edipica ai primi anni di vita.</li>
</ul>
<p>A questo si aggiunge l'influenza di fattori filosofico-culturali più ampi. La fiducia illuminista di Freud, per cui conoscere
sé stessi equivaleva a guarire, ha lasciato spazio, nelle concezioni moderne, a uno scetticismo più profondo. Oggi si dubita
che sia possibile trovare una verità definitiva, su di sé o sul mondo.</p>



<h3>La teoria della cura secondo Freud</h3>
<p>Per Freud, gli obiettivi terapeutici erano:</p>
<ul>
<li>ridurre la sofferenza del paziente, scaricando l'affetto incapsulato e riducendo l'angoscia;</li>
<li>rendere conscio l'inconscio;</li>
<li>rafforzare l'Io, promuovendo controllo e autonomia;</li>
<li>mitigare la severità del Super-io;</li>
<li>favorire l'integrazione dei contenuti psichici isolati;</li>
<li>promuovere l'insight attraverso l'interpretazione del transfert.</li>
</ul>
<p>Il meccanismo chiave della cura, per Freud, era proprio l'<strong>insight promosso dall'interpretazione del transfert</strong>.
Il compito dell'analisi è essenzialmente un lavoro di memoria: mira a recuperare il più rapidamente possibile i ricordi, le
pulsioni e le fantasie infantili rimosse. Per la psicoanalisi classica, ciò che è patologico è qualcosa che un tempo è stato
cosciente. Diventato inaccessibile attraverso la rimozione, può tornare alla coscienza attraverso il lavoro di interpretazione.</p>

