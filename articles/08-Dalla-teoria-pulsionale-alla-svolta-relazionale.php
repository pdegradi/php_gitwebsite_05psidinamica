<!-- <h2>Dalla teoria pulsionale alla svolta relazionale</h2> -->
<p>Per introdurre le teorie di Sullivan (psicoanalisi interpersonale) e di Mitchell (modello relazionale) conviene richiamare la
teoria freudiana delle pulsioni. Secondo Freud, ogni essere umano è caratterizzato da tensioni fisiche innate e asociali che
premono per essere gratificate (le pulsioni sessuali e aggressive), ma questa gratificazione è limitata da esigenze sociali. Il
conflitto tra queste esigenze innate (natura) e le esigenze sociali (società) è alla base del pensiero secondario, che nasce dal
principio di realtà: le capacità cognitive si formano proprio per modulare e risolvere questo conflitto, organizzandosi nelle
strutture dell'Io e del Super-io che controllano gli impulsi istintuali infantili. Individuo e società sono quindi in contrasto tra
loro, e il compito dello sviluppo è la socializzazione, cioè adattarsi al mondo in cui si vive.</p>
<p>Gli orientamenti psicoanalitici contemporanei "relazionali" (la teoria interpersonale di Sullivan, il modello relazionale di
Mitchell, la teoria intersoggettiva) prendono le distanze da questo modello pulsionale: per queste teorie la funzione principale
della mente è formare e preservare i legami con gli altri, che non sono un modo secondario per risolvere le pulsioni, ma l'essenza
stessa della vita psichica.</p>
<p>Per queste teorie possono esistere differenze costituzionali tra le persone, ma i significati che ne derivano dipendono dal modo in
cui le persone significative reagiscono a ciascuno di noi: biologia e processi interpersonali costituiscono cicli continui di
influenza reciproca, e non è più possibile distinguere una componente biologica da una componente relazionale, perché fanno parte
della stessa cosa. Questa svolta relazionale ribalta un'idea diffusa anche nel senso comune, per cui esisterebbero aspetti
emozionali più primitivi e "veri" (per esempio quando diciamo che una persona arrabbiata ha "finalmente mostrato quello che pensava
davvero"), mentre il pensiero razionale sarebbe solo una maschera più artificiale imposta dalla società. Per le teorie relazionali,
invece, la nostra personalità è un insieme inseparabile di aspetti costituzionali e di fattori ambientali: non esiste una
personalità "vera" distinta da una più artificiosa.</p>






<h2>La psicoanalisi interpersonale di Harry Stack Sullivan</h2>
<p>Sullivan (1892-1949) è l'autore che ha influenzato di più i modelli relazionali con la sua psicoanalisi interpersonale. Per lui
l'essere umano si è evoluto come creatura sociale orientata all'interazione con gli altri, in contrasto con l'idea freudiana di un
individuo che nasce in opposizione alla società. La personalità prende forma in un ambiente fatto di altre persone: il Sé compare
nell'interazione con gli altri, ed è definito come lo schema relativamente permanente delle situazioni interpersonali ricorrenti
che caratterizzano la vita di una persona. Le modalità di interazione apprese precocemente vengono interiorizzate e ripetute anche
in età adulta, in altre relazioni.</p>



<h3>Il campo interpersonale e la teoria del campo di Kurt Lewin</h3>
<p>Per Sullivan non ha senso distinguere individuo e realtà sociale: esiste solo il campo delle relazioni interpersonali, che include
entrambi gli elementi e definisce la personalità. Sullivan fu influenzato dalla <strong>teoria del campo</strong> di Kurt Lewin
(1890-1947), secondo cui il comportamento umano si comprende solo considerando la totalità dei fattori coesistenti in un dato
momento, nella loro interdipendenza: <strong>lo spazio fisico reale</strong> (la realtà esterna), <strong>lo spazio di
vita</strong> (l'individuo e la sua rappresentazione psicologica dell'ambiente) e <strong>lo spazio di confine</strong> (la
relazione tra individuo e realtà esterna). La relazione tra individuo e realtà esterna non è quindi la semplice somma delle parti,
perché esiste anche il ruolo della relazione stessa: questo principio del campo è alla base della svolta relazionale in
psicoanalisi.</p>



<h3>La teoria evolutiva di Sullivan</h3>
<p>Il neonato oscilla tra uno stato di benessere quasi assoluto e uno stato di tensione legato a un bisogno (bisogno di
soddisfacimento). L'espressione del bisogno, per esempio attraverso il pianto, tende a provocare una risposta soddisfacente da
parte dell'adulto (la madre si accorge che il bambino ha fame e lo allatta). La relazione tra bisogno e risposta è inoltre
integrativa, cioè gratificante anche per l'adulto (nell'allattamento la madre vuole allattare tanto quanto il bambino vuole essere
allattato): Sullivan chiama questi processi <strong>tendenze integrative</strong>. Queste tendenze non riguardano solo la nascita,
ma restano fondamentali per tutto l'arco della vita: anche nell'adulto, bisogni diversi tendono a suscitare bisogni complementari
negli altri.</p>



<h3>Il legame empatico</h3>
<p>Se i bisogni di soddisfacimento tendono a essere integrativi, perché allora i rapporti umani sono spesso complessi e conflittuali?
Per Sullivan la risposta sta nella natura "contagiosa" delle emozioni: una persona allegra tende a rendere allegri anche gli altri,
così come una persona annoiata trasmette noia. Questa diffusione degli stati d'animo prende il nome di <strong>legame
empatico</strong>. Il legame empatico può funzionare anche in negativo: se una madre riceve una brutta notizia mentre gioca con il
bambino, tornerà da lui con uno stato d'animo diverso (per esempio ansioso) senza dichiararlo apertamente; il bambino, attraverso
il legame empatico, proverà a sua volta quell'ansia e reagirà piangendo, ma in questo caso la madre non riuscirà a calmarlo con
facilità, perché è lei stessa la fonte della tensione. Il disagio del bambino può quindi aumentare ulteriormente l'ansia della
madre, in un circolo vizioso.</p>



<h3>L'ansia come tendenza disintegratrice</h3>
<p>A differenza della tensione legata ai bisogni di soddisfacimento, la tensione legata all'ansia non può essere ridotta dall'adulto
che si prende cura del bambino: per questo l'ansia agisce come <strong>tendenza disintegratrice</strong>, in senso opposto agli
altri stati affettivi. Sullivan distingue l'ansia dalla paura: la paura è adattiva, perché ha un oggetto riconoscibile e provoca
una reazione risolutiva dell'adulto; l'ansia è invece problematica perché non ha un oggetto definito, quindi né il bambino né la
madre riescono a spiegarla o a risolverla.</p>



<h3>Stati ansiosi e stati non ansiosi</h3>
<p>Fin dall'inizio il bambino organizza l'esperienza in stati ansiosi e stati non ansiosi. Poiché l'ansia si trasmette dall'adulto
attraverso il legame empatico, il bambino raggruppa tutte le esperienze di ansia vissute con gli adulti di riferimento in
un'esperienza generale di "madre cattiva o ansiosa", e tutte le esperienze non ansiose in quella di "madre buona o non ansiosa".</p>



<h3>La prospettiva evolutiva</h3>
<p>Con lo sviluppo, il bambino partecipa in modo sempre più attivo a queste esperienze:</p>
<ul>
<li>all'inizio le esperienze di "madre buona" e "madre cattiva" sono vissute passivamente;</li>
<li>successivamente il bambino impara a prevedere quando comparirà l'una o l'altra;</li>
<li>in seguito capisce che la comparsa della "madre buona" o della "madre cattiva" dipende dal proprio comportamento: i comportamenti
associati alla "madre buona" assumono valenza positiva e formano il "<strong>buon me</strong>", quelli associati alla "madre
cattiva" formano il "<strong>cattivo me</strong>";</li>
<li>alcune esperienze provocano nell'adulto (e quindi nel bambino, tramite il legame empatico) un'ansia così intensa da risultare
dirompente: queste esperienze vengono dissociate dal resto della coscienza e non vengono riconosciute come parte di sé (esperienze
"<strong>non-me</strong>").</li>
</ul>



<h3>Il sistema del Sé</h3>
<p>Il <strong>sistema del Sé</strong> corrisponde ai processi attivi con cui il bambino favorisce l'accesso al "buon me" ed esclude il
"non-me". Poiché il "buon me" dipende dalle relazioni con gli altri significativi, il Sé del bambino si forma gradualmente
all'interno di uno specifico campo interpersonale: uno stesso comportamento (per esempio il bambino che gioca con i propri genitali
durante il cambio) può provocare ansia in certe madri e nessuna reazione in altre, e verrà quindi vissuto come ansioso solo dai
bambini le cui famiglie reagiscono in quel modo. Crescendo, il bambino diventa sempre più "il figlio di quella particolare madre e
di quel particolare padre", riducendo la gamma delle esperienze possibili. Il sistema del Sé è descritto come tendenzialmente
stabile, ma non rigido in modo assoluto: esistono fasi evolutive (per esempio il bisogno dell'amico del cuore nella preadolescenza)
in cui emerge il bisogno di nuove forme di relazione, e la rigidità del sistema si allenta permettendo una nuova integrazione.</p>



<h3>I bisogni e le operazioni di sicurezza</h3>
<p>Quando si prova ansia si attivano i <strong>bisogni di sicurezza</strong>: il sistema del Sé promuove i comportamenti che in
passato si sono dimostrati efficaci nel ridurre l'ansia (<strong>operazioni di sicurezza</strong>). Per Sullivan, alcune aree
dell'esperienza diventano conflittuali nella prima infanzia solo se tendono a indurre ansia negli adulti di riferimento: le
difficoltà psicologiche, ed eventualmente la psicopatologia, non dipendono quindi dalla natura delle pulsioni, ma dalla reazione
dell'ambiente umano e dalle relazioni interpersonali precoci, oltre che, in misura minore, da quelle vissute in tutto l'arco della
vita.</p>






<h2>Il modello relazionale di Stephen Mitchell</h2>
<p>Stephen Mitchell (1946-2000) propone un modello che raccoglie i diversi orientamenti psicoanalitici centrati sulle relazioni
interpersonali, spesso in contrasto tra loro. Insieme a J. Greenberg (1983), Mitchell elabora il <strong>modello
relazionale</strong>, un tentativo di unificare in un solo quadro le teorie principali della psicoanalisi contemporanea,
contrapposto al modello pulsionale classico di Freud. Le teorie di riferimento sono le teorie inglesi delle relazioni oggettuali,
la Psicologia del Sé di Kohut e la psicoanalisi interpersonale di Sullivan, ma nel modello relazionale rientrano più in generale
tutte le teorie che considerano le relazioni con gli altri, e non le pulsioni, l'elemento fondamentale della vita psichica.</p>



<h3>La matrice relazionale</h3>
<p>Per Mitchell (1993), "il modo più utile di guardare alla realtà psicologica è operare all'interno di una <strong>matrice
relazionale</strong> che comprenda sia l'ambito intrapsichico che quello interpersonale". Come metafora del suo modello, Mitchell
richiama il disegno di Escher "Mani che disegnano" (Drawing Hands), in cui non si distingue dove inizia una mano e finisce l'altra:
la nostra personalità è un insieme inseparabile di fattori costituzionali e di relazioni significative, vissute soprattutto nella
prima infanzia ma anche in tutto il resto della vita.</p>



<h3>Tre modelli a confronto</h3>
<p>Mitchell riassume i modelli principali della psicoanalisi in tre categorie:</p>
<ul>
<li><strong>la teoria pulsionale</strong> della psicoanalisi classica di Freud (teoria psicobiologica): la mente è "monadica", cioè
intrapsichica, definita soprattutto dalle proprie pulsioni; i processi cognitivi emergono dalla soddisfazione pulsionale e il
funzionamento psichico è caratterizzato dal conflitto tra pulsioni e difese;</li>
<li><strong>il modello dell'arresto evolutivo</strong>, in cui rientrano la Psicologia dell'Io e la Psicologia del Sé: anche queste
teorie conservano un'idea monadica della mente, pur riconoscendo che essa si origina nell'interazione precoce con le figure
genitoriali; una volta formato, il Sé opera però in modo relativamente indipendente e meno reattivo alle relazioni. In questo
modello un ambiente non adeguato comporta un arresto evolutivo, e la psicopatologia va ricercata proprio in questo arresto;</li>
<li><strong>il modello relazionale</strong>, definito in particolare dalle teorie di Mitchell, Sullivan e dalle teorie delle relazioni
oggettuali (tra cui, per Mitchell, soprattutto quella di Fairbairn): qui la mente è "diadica", cioè sociale e interattiva; i
fattori ambientali non solo influenzano la mente ma la costituiscono. È una teoria psicosociale, non più psicobiologica, in cui il
conflitto relazionale (centrato su passioni, desideri e paure vissuti nelle relazioni significative) è al centro del funzionamento
psichico.</li>
</ul>



<h3>La natura delle relazioni personali</h3>
<p>Mitchell distingue tre modi in cui le diverse teorie relazionali intendono il legame con gli altri:</p>
<ul>
<li><strong>relazionale per destino</strong>: le persone sono strutturate in modo da essere inevitabilmente attratte l'una verso
l'altra (per esempio per Sullivan, gli esseri umani sono intrinsecamente relazionali);</li>
<li><strong>relazionale per proposito</strong>: le persone sviluppano legami forti perché lo desiderano attivamente (per esempio per
Fairbairn, la motivazione centrale umana è la ricerca e il mantenimento di un legame emotivo intenso con un'altra persona);</li>
<li><strong>relazionale per implicazione</strong>: i legami interpersonali sono la base per costruire e mantenere un senso di identità
e di sé (per esempio per Kohut e Winnicott).</li>
</ul>
<p>Secondo Mitchell queste tre concezioni non sono in contrasto, ma corrispondono a tre componenti che insieme formano la matrice
relazionale: una componente costituzionale e biologica (non nasciamo "tabula rasa"), una componente intenzionale ed emotiva
orientata alla ricerca di relazioni, e i processi interpersonali impliciti coinvolti nella definizione del Sé.</p>



<h3>Le configurazioni relazionali</h3>
<p>La mente è composta da <strong>configurazioni relazionali</strong>: schemi o rappresentazioni interne delle relazioni passate e
presenti dell'individuo. Questo concetto ridefinisce l'inconscio nella psicoanalisi contemporanea: non più un contenitore di
pulsioni aggressive e sessuali, ma un insieme di modalità relazionali apprese, soprattutto nella prima infanzia ma anche nel resto
della vita. Ogni configurazione relazionale include tre dimensioni: il Sé, l'altro e lo spazio tra i due (richiamando ancora la
teoria del campo di Lewin: non esiste oggetto senza Sé, né Sé senza oggetto, ma solo uno spazio di interazione tra loro).</p>
<p>I modelli ripetitivi dell'esperienza umana non derivano, come nel modello pulsionale, dalla ricerca di gratificazione di pulsioni
interne, ma da una tendenza a conservare la continuità e la familiarità con il proprio mondo relazionale: esiste un desiderio
potente di mantenere un senso di sé duraturo, legato a una rete di altre persone, fatta di relazioni reali e di presenze
interiorizzate. La mente individuale è un prodotto di una specifica matrice culturale e linguistica e, una volta formata, continua
a interagire attivamente al suo interno: per questo non è qualcosa di stabile, ma fluida e in continua evoluzione. Le
configurazioni relazionali interiorizzate vengono attivate ripetutamente per riprodurre modelli familiari di interazione, e questa
ripetizione genera la matrice relazionale.</p>



<h3>Il conflitto relazionale e la tela di Penelope</h3>
<p>Le diverse configurazioni relazionali entrano in conflitto tra loro: per Mitchell, come già per Freud, il conflitto è inevitabile,
ma qui è un conflitto relazionale, perché tutte le relazioni umane importanti hanno significati complessi e talvolta opposti
riguardo alla definizione del Sé, ai legami con gli altri e allo spazio tra sé e gli altri. Gli esseri umani tendono continuamente
a ricostruire la propria matrice relazionale per mantenere un senso di sé stabile e continuo. Mitchell riprende la metafora di
Penelope che, nell'Odissea, tesse la tela di giorno e la disfa di notte per tenere lontani i pretendenti e restare fedele a Ulisse:
in modo simile, ogni persona tesse e disfa continuamente la propria matrice relazionale per conservare un senso di continuità del
proprio significato soggettivo.</p>



<h3>Sé unico e Sé multiplo</h3>
<p>Con la metafora della pellicola cinematografica, composta da molti fotogrammi discontinui che insieme formano un'immagine continua,
Mitchell spiega la compresenza di <strong>Sé unico</strong> e <strong>Sé multiplo</strong>: in ogni momento una persona agisce in
relazione a un contesto specifico, quindi siamo composti da Sé multipli, ma queste esperienze si integrano in una sequenza continua
che percepiamo come un Sé unico e stabile.</p>



<h3>La psicopatologia nel modello relazionale</h3>
<p>È sano e adattivo continuare a tessere e disfare la propria matrice relazionale, perché questo permette di essere flessibili di
fronte a situazioni diverse. La psicopatologia, al contrario, è definita dalla rigidità con cui una persona ripropone sempre gli
stessi modelli e le stesse configurazioni relazionali, invece di dare risposte più flessibili e adatte a nuove situazioni.</p>






<h2>La teoria intersoggettiva</h2>
<p>Anche la teoria intersoggettiva nasce dalla svolta relazionale in psicoanalisi, secondo cui la funzione principale della mente è
formare e preservare i legami con gli altri, e non semplicemente soddisfare le pulsioni. Il modello pulsionale classico riteneva
che il soddisfacimento delle pulsioni comportasse, in alcuni casi, l'interiorizzazione di aspetti del mondo interpersonale (per
esempio il Super-io, interiorizzazione della morale e delle norme dei genitori), ma spiegava comunque la mente umana soprattutto a
partire da pulsioni fisiche predeterminate e innate ("l'anatomia è il nostro destino", per usare le parole di Freud). Nei modelli
relazionali, invece, possono esistere differenze costituzionali tra le persone, ma i significati che ne derivano dipendono dal modo
in cui le persone significative reagiscono a ciascuno di noi: biologia e relazioni interpersonali costituiscono cicli continui di
influenza reciproca, e non si possono più distinguere come componenti separate.</p>
<p>La teoria dell'intersoggettività, proposta da <strong>Robert D. Stolorow</strong> e <strong>George E. Atwood</strong>, è una delle
teorie più recenti in questo ambito. È una teoria del campo che pone al centro della comprensione della mente umana l'ampio sistema
relazionale in cui i fenomeni psicologici prendono forma e in cui l'esperienza viene continuamente modellata: i fenomeni
psicologici non possono essere compresi separatamente dal contesto intersoggettivo in cui si esprimono. Il concetto di
<strong>intersoggettività</strong> si riferisce in particolare al campo psicologico che nasce dall'incontro di due soggettività
organizzate in modo diverso, che si influenzano reciprocamente (per esempio bambino e caregiver, oppure paziente e analista).</p>


