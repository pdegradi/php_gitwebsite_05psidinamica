<h2>L'azione terapeutica nella psicoanalisi contemporanea</h2>



<h3>L'azione terapeutica per la Psicologia del Sé</h3>
<img class="zoomable" src="/assets/images/Heinz-Kohut.webp" />
<p>Partiamo dalla teoria di <strong>Kohut</strong> e dalla Psicologia del Sé, perché rappresenta l'allontanamento più radicale
dalla teoria clinica classica del trattamento psicoanalitico.</p> 

<p>La differenza più grande tra la psicoanalisi classica di Freud e la
Psicologia del Sé di Kohut sta proprio nel modo in cui viene concepito il cambiamento del paziente.</p>



<h3>Cosa determina il cambiamento terapeutico?</h3>
<p>Per Freud il processo fondamentale è l'interpretazione che produce <strong>insight</strong>, in particolare l'interpretazione
del transfert. Il paziente sviluppa sentimenti forti verso il terapeuta, che sono modalità relazionali apprese e disfunzionali. 
Interpretare questi modelli porta alla coscienza i contenuti rimossi e quindi a cambiare.</p>
<p>Per Kohut, invece, il punto centrale dell'intervento terapeutico è la <strong>comprensione empatica</strong> del terapeuta 
(psicologia del Sè).</p>
<p>Per Freud l'empatia restava un mezzo per promuovere l'insight, mentre per la Psicologia del Sé la comprensione
empatica è di per sé una strategia clinica: non è il mezzo, è il fine.</p>



<h3>Lo sviluppo psicologico secondo Kohut</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 184354.webp" />
<p>Uno dei punti fondamentali della teoria di Kohut è il rifiuto della teoria freudiana del narcisismo.</p>
    
<p>Per Kohut, il <strong>narcisismo primario</strong> (l'amore per se stessi) è in armonia con l'amore 
per gli altri. Non occorre rinunciare all'amore per sé per poter costruire relazioni oggettuali, anzi, 
chi ama se stesso è anche più capace di amare gli altri.</p>

<p>All'inizio il bambino vive in uno stato di narcisismo primario, e i genitori empatici cercano di 
soddisfare il suo bisogno di grandiosità. Ma anche i genitori migliori non riescono sempre a soddisfare le richieste del
bambino, e da questi momenti si sviluppano due nuclei di Sé complementari:</p>
<ul>
    <li>il <strong>Sé grandioso</strong>, che ha bisogno di sentirsi onnipotente</li>
    <li>l'<strong>immagine genitoriale idealizzata</strong>, cioè il bisogno di credere che chi si prende cura di 
    noi possa procurarci qualsiasi cosa</li>
</ul>
<p>Il bambino arriva a una visione meno narcisistica della vita attraverso il confronto ripetuto con la realtà (i genitori 
non possono far realizzare quasiasi cosa). Così il bambino vive ripetute <strong>esperienze di frustrazione ottimale</strong>.</p>

<p>Queste esperienze spostano il narcisismo primario verso una struttura psichica nuova (<strong>Se nucleare</strong>),
più realistica e indipendente, attraverso un processo chiamato <strong>internalizzazione trasmutante</strong>. 

Dal Sé nucleare si passa poi al <strong>Sé coeso</strong> e infine al <strong>Sé autonomo</strong> dell'adulto.</p>



<h3>La psicopatologia per la Psicologia del Sé</h3>
<p>La salute mentale dipende dall'acquisizione di un Sé forte e vigoroso all'interno di relazioni strette e amorevoli.</p> 
    
<p>La <strong>psicopatologia</strong>, al contrario, è definita da un'esistenza priva di significato. 
Il paziente, per Kohut, vive l'esistenza come un lavoro faticoso. Può presentare apatia, oppure alternare esplosioni di
creatività a sentimenti dolorosi di inadeguatezza in risposta a percezioni di fallimento.</p>



<h3>Il contesto terapeutico</h3>
<p>Per la Psicologia del Sé, il contesto analitico ha l'obiettivo di soddisfare i bisogni evolutivi rimasti insoddisfatti, in
particolare il bisogno di <strong>comprensione empatica</strong>. Se il paziente non l'ha ricevuta a sufficienza dai genitori,
il terapeuta si sostituisce a quelle figure per fornirla. La comprensione empatica è quindi curativa.</p> 

<p>Come scriveva Kohut (1984):</p>
<blockquote>Ognuno di noi si sente, a ragione, unico e speciale e
non può esistere se non trova conferma da parte degli altri, soprattutto dai genitori e da coloro che in seguito hanno assunto
il significato di oggetti-Sé genitoriali</blockquote>



<h3>Gli oggetti-sé</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 202002.webp" />
<p>Gli <strong>oggetti-sé</strong> sono le interiorizzazioni di altre persone significative come parti del Sé.</p> 
<p>Restano presenti per tutta la vita, ma per una buona salute mentale vanno integrati nella personalità.</p>
<p>Il Sé nucleare integra sia il Sé grandioso sia il Sé idealizzato, cioè l'immagine genitoriale interiorizzata. 
Solo una buona integrazione porta al <strong>Sé coeso</strong>, l'obiettivo dello sviluppo, 
caratterizzato da un buon grado di integrazione, coerenza e vitalità.</p>



<h3>La spiegazione</h3>
<p>Oltre alla comprensione empatica, l'altro elemento curativo fondamentale per la Psicologia del Sé è la
<strong>spiegazione</strong>, un'interpretazione che può assumere due forme.</p>
<ul>
    <li>La <strong>ricostruzione genetica</strong> che collega le modalità di interazione attuali con quanto appreso 
    nelle relazioni genitoriali precoci. </li>
    <li>La <strong>formulazione dinamica</strong> che spiega in termini dinamici ciò che accade nella relazione 
    paziente-analista</li>
</ul>

<p>La spiegazione promuove l'auto-consapevolezza e l'insight. Qui però l'insight non è l'obiettivo primario.</p>

<p>L'obiettivo primario è <strong>rafforzare la fiducia del paziente nel legame empatico</strong> che si costruisce con l'analista.</p>

<p>Per Kohut l'elemento essenziale del trattamento è <strong>sentirsi capiti</strong>.</p>



<h3>L'esperienza emozionale correttiva</h3>
<p>Si tratta della situazione in cui il comportamento del terapeuta è diverso dalle aspettative che il paziente ha costruito nelle
esperienze precoci con i genitori.</p> 

<p>Per esempio, un paziente che si aspetta di essere abbandonato, come è successo con i propri genitori, scopre che il terapeuta 
rimane presente e disponibile a lavorare insieme. Questo gli comunica che "non tutti fanno come i miei genitori".</p>
<p>Il processo non è semplice quanto sembra e serve che sia accompagnata dall'interpretazione e dalla spiegazione.</p>



<h3>La comprensione empatica: fallimento ottimale e spiegazione</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 203129.webp" />
<p>Quando l'analista non fornisce la comprensione empatica necessaria, il paziente può reagire con rabbia, oppure ritirandosi in
modalità relazionali disadattive tipiche della sua storia.</p> 
<p>Attraverso la spiegazione l'analista interpreta quanto successo durante la cura ristabilendo la risonanza empatica.</p> 
<p>Questo processo si chiama <strong>fallimento ottimale</strong>, in analogia con
la frustrazione ottimale dello sviluppo.</p> 
<p>Se ripetute nel tempo queste dinamiche portano il paziente a sviluppare una gamma sempre più ampia di
oggetti-sé, attraverso la stessa <strong>internalizzazione trasmutante</strong> vista nello sviluppo infantile.</p>



<h3>La terapia relazionale breve</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 204018.webp" />
<p><strong>Safran</strong> e <strong>Muran</strong> (2000) hanno proposto un <strong>modello di terapia relazionale
breve</strong>, con aspetti comparabili al concetto di frustrazione ottimale della Psicologia del Sé.</p> 
<p>Il modello si basa sul
concetto di <strong>alleanza terapeutica</strong>, ovvero una relazione collaborativa
tra paziente e terapeuta, un legame affettivo tra loro, e l'accordo sugli obiettivi del trattamento.</p>
<p>L'alleanza terapeutica è stata oggetto di verifica empirica: la ricerca conferma che la sua solidità predice 
l'esito del trattamento.</p>


<p>L'azione terapeutica nel modello di terapia relazionale breve si basa sull'identificazione e la riparazione 
delle <strong>rotture dell'alleanza terapeutica</strong> durante il trattamento (un concetto comparabile al 
fallimento ottimale di Kohut).</p> 
<p>Safran e Muran hanno verificato empiricamente che la risoluzione di queste rotture predice l'esito della terapia.</p>



<h2>L'attaccamento e l'intervento clinico</h2>
<p><strong>Bowlby</strong> (1988) in un articolo si mostrava sorpreso che la teoria dell'attaccamento, 
pur essendo nata in ambito clinico, avesse influenzato molto più la psicologia dello sviluppo che la pratica clinica.</p>



<h3>Il peso delle relazioni</h3>
<p>La teoria dell'attaccamento insieme all'Infant Research hanno spostato
l'origine della psicopatologia verso le relazioni interpersonali, in particolare situazioni traumatiche e relazioni con
genitori poco sensibili.</p> 
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 205119.webp" />
<p>Come visto, la sensibilità genitoriale determina lo stile di attaccamento del bambino, che a sua volta
è legato ai suoi Modelli Operativi Interni e al sistema di regolazione psicofisiologica. Questi tre fattori insieme determinano
la psicopatologia e il funzionamento psicosociale.</p>



<h3>Modelli operativi interni (MOI)</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 205237.webp" />
<p>Nella terapia contemporanea, il concetto di MOI (modelli operativi interni) ha cambiato l'interpretazione della natura 
della mente e quindi dell'intervento clinico.</p>



<h3>La regolazione delle emozioni</h3>
<p>L'attaccamento è oggi interpretato non come semplice vicinanza fisica alla figura di accudimento, ma come "sentirsi sicuri". È
questo senso di sicurezza che permette di regolare le emozioni e affrontare situazioni nuove.</p>



<h3>La pratica clinica</h3>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 205709.webp" />
<p>La pratica clinica sottolinea sempre meno il contenuto di
ciò che il paziente racconta, e sempre più il modo in cui lo racconta. Non si tratta più di informazioni o immagini rimosse da
riportare alla coscienza, ma di interpretare gli aspetti impliciti che si manifestano negli schemi ripetitivi dei comportamenti
e delle modalità relazionali.</p>



<h3>Adult Attachment Interview</h3>
<p>L'<strong>Adult Attachment Interview</strong> (intervista sull'attaccamento adulto) valuta le risposte non in base ai
contenuti ma al loro livello di coerenza. Non conta se il
paziente dice di aver avuto un'infanzia felice o infelice, ma quanto le sue risposte alle domande dell'intervista risultino
coerenti tra loro.</p>
<img class="zoomable" src="/assets/images/24/Screenshot 2026-09-28 205946.webp" />



<h3>La funzione riflessiva o del mentalizzare</h3>
<img class="zoomable" src="/assets/images/Peter-Fonagy.webp" />
<p>La <strong>funzione riflessiva</strong>, concetto introdotto da <strong>Peter Fonagy</strong>, è la capacità di "pensare" i
propri stati mentali e quelli degli altri.</p> 
<p>Più un adulto ha questa capacità, più il bambino impara a percepirsi come dotato di pensieri, emozioni e credenze proprie, 
sviluppando a sua volta una capacità riflessiva. La funzione riflessiva è associata
all'attaccamento sicuro, ed è un fattore chiave nella trasmissione intergenerazionale dello stile di attaccamento.</p>

<p>In terapia, migliorare la funzione riflessiva significa aiutare il paziente a gestire emozioni, impulsi, comportamenti e
relazioni. Significa anche rafforzare la capacità di comprendere i propri stati mentali e quelli altrui, tenendo conto delle
circostanze specifiche di ogni situazione.</p>


<p>Nella pratica clinica un intervento che rafforzi la funzione riflessiva è particolarmente importante. 
Come esempio consideriamo due ambiti. 
<ul>
    <li><strong>trattamento stati borderline</strong>, dove i pazienti tendono a interpretare il comportamento altrui come rifiutante o umiliante,
senza contemplare altre letture possibili.</li>
    <li><strong>interventi sulla diade madre-bambino</strong>, dove
studi clinici mostrano l'efficacia nel promuovere un attaccamento sicuro nel bambino.</li>
</ul>



<h3>L'equazione personale</h3>
<p>Un ultimo aspetto condiviso da tutti gli orientamenti contemporanei è che le caratteristiche personali del terapeuta contano, 
al di là della teoria seguita.</p> 
<p>La consonanza tra le caratteristiche personali di terapeuta e paziente ha quindi un'influenza rilevante sull'esito
della cura.</p>






