<h2>La regolazione emotiva nella prima infanzia</h2>
<p>Con il termine "madre" intendiamo la figura di accudimento principale del bambino, che non è necessariamente 
la madre biologica (può essere una madre adottiva o un padre).</p>

<p>Secondo l'Infant Research, la relazione bipersonale tra madre e bambino promuove lo sviluppo psicofisiologico soprattutto
attraverso le <strong>interazioni faccia a faccia</strong>: è così che il bambino impara il significato del proprio comportamento
espressivo, le caratteristiche delle persone importanti per lui, e le informazioni cognitive e affettive che gli permettono di
inserirsi nella propria cultura e di definire la propria identità.</p>



<h3>Le ricerche di Ed Tronick sulla comunicazione faccia a faccia (1978)</h3>
<img XXclass="zoomable" src="/assets/images/Ed-Tronick.webp" />
<p>Un autore americano, <strong>Ed Tronick</strong>, pubblicò nel 1978 i risultati di uno studio sulla
comunicazione faccia a faccia tra madre e bambino con
l'obiettivo di esaminare le capacità auto-regolatorie del bambino e l'importanza per lui dell'interazione reciproca con la madre<</p>

<p>Lo studio fu condotto su un campione molto piccolo: 7 madri con i rispettivi bambini, di età tra 1 e 4 mesi. Due coppie
furono osservate in 6 sedute, tre coppie in 2 sedute, e due coppie in una sola seduta. È un limite metodologico importante di
questo primo studio, pionieristico ma basato su un campione esiguo.</p>

<p>Vennero definiti come comportamenti da
osservare: vocalizzazioni, direzione dello sguardo, orientamento e posizione del capo, espressione del volto, quantità di
movimento, movimento di palpebre, mani, piedi e posizione della lingua.</p>

<p>Madre e bambino si sedevano l'uno di fronte all'altro, ripresi da due telecamere separate. Veniva chiesto alla madre di svolgere il
<strong>paradigma dello  Still Face</strong>: tenere il viso fermo e con espressione neutra, sospendendo ogni
comunicazione con il bambino, per osservare come questi reagisse all'interruzione del normale feedback emotivo.</p> 

<p>In ordine casuale le madri giocavano con il bambino per 3 minuti oppure tenevano il volto immobile per 3
minuti, poi, dopo una pausa di 30 secondi, si passava alla situazione opposta. Due osservatori indipendenti valutavano i
comportamenti dei volti.</p>

<p>I risultati furono che nella situazione di volto immobile, rispetto al gioco, i bambini sorridevano meno, mantenevano meno a lungo
lo sguardo e il capo
verso la madre, e restavano più a lungo accasciati e immobili sul seggiolino.</p>


<p>Studi successivi hanno mostrato che i bambini reagiscono
su più livelli (comunicativo, comportamentale, affettivo, attentivo) ritirandosi dall'interazione sociale e mostrando disagio
generale, indipendentemente da età e genere.</p>

<p>La maggior parte degli studi sullo Still Face si è concentrata sui comportamenti osservabili, ma alcuni hanno misurato anche indici
fisiologici, trovando durante l'episodio del volto immobile un aumento del battito cardiaco, dei livelli di cortisolo, della
conduttanza cutanea e della temperatura del viso.</p>






<h2>Il modello di mutua regolazione reciproca (Gianino e Tronick, 1988)</h2>
<img XXclass="zoomable" src="/assets/images/Tronick.webp" />
<p>Nel 1988 <strong>Gianino</strong> e <strong>Tronick</strong> proposero il modello della <strong>mutua regolazione
reciproca</strong>: madre e bambino condividono un obiettivo comune, e lo regolano insieme soprattutto attraverso le emozioni.
Questo perché i primi apprendimenti del bambino sono emotivi: già nei primi 6 mesi di vita prova sette emozioni principali —
gioia, interesse, tristezza, rabbia, paura, sorpresa e disagio — e le emozioni si sviluppano prima delle capacità cognitive (lo
stesso aveva osservato Spitz nei bambini istituzionalizzati).</p>



<h3>I tre processi critici della mutua regolazione</h3>
<p>Il successo o l'insuccesso dell'interazione dipende da tre livelli:</p>
<ol>
<li>il sistema nervoso centrale del bambino, che deve saper organizzare i suoi stati fisiologici e il comportamento;</li>
<li>il sistema comunicativo del bambino;</li>
<li>la capacità della madre di capire correttamente ciò che il bambino comunica, e di agire di conseguenza.</li>
</ol>
<p>I primi due livelli sono capacità <strong>auto-regolatorie</strong> del bambino; il terzo è una capacità
<strong>etero-regolatoria</strong> della madre. Questa impostazione valorizza le competenze innate del bambino, e si oppone
all'idea di Freud e della Mahler secondo cui bambino e madre non sarebbero inizialmente differenziati.</p>



<h3>La fase di recupero</h3>
<p>Pochi studi hanno guardato alla <strong>fase di recupero ("Still Face")</strong> dopo il volto immobile, anche se è un momento
importante —
come sostenevano anche Beebe e Lachmann. In uno studio del 1987, <strong>Cohn</strong> e <strong>Tronick</strong> trovarono che
madre e bambino passano solo circa il 30% del tempo in sintonia tra loro: i momenti di disaccordo, gli "scacchi interattivi", sono
quindi la norma, non l'eccezione. Ciò che conta per uno sviluppo sano non è quanto tempo si passa in sintonia, ma la capacità di
riparare questi momenti di disaccordo. Gli scambi ben regolati generano emozioni positive, quelli mal regolati emozioni negative:
il modo in cui la madre risponde a questi momenti insegna al bambino il proprio stile di gestione dello stress.</p>



<h3>Le capacità auto-regolatorie o di coping</h3>
<p>Quando l'interazione con la madre non funziona, il bambino può reagire in modi diversi, più o meno efficaci:</p>
<ul>
<li><strong>attenzione sociale</strong>: il bambino guarda la madre senza emettere segnali;</li>
<li><strong>segnalazione</strong>: agisce per modificare il comportamento della madre (sorridendo, piangendo, o gesticolando in
modo neutro);</li>
<li><strong>attenzione per l'oggetto</strong>: si concentra su qualcosa di diverso dalla madre;</li>
<li><strong>autoconsolazione</strong>: usa il proprio corpo o un oggetto per procurarsi conforto (per esempio succhiando il
ciuccio o le dita);</li>
<li><strong>coping della fuga</strong>: cerca di aumentare la distanza fisica dalla madre voltando la testa o inarcandosi;</li>
<li><strong>allontanamento dello sguardo</strong>: distoglie lo sguardo senza però riuscire a fissare qualcos'altro;</li>
<li><strong>coping del ritiro</strong>: riduce al minimo il coinvolgimento sociale, apparendo spento o perdendo il controllo
posturale.</li>
</ul>



<h3>La mancata corrispondenza e il ruolo della madre</h3>
<p>Le emozioni del bambino riescono a regolare l'interazione solo se la madre è sensibile e disposta a cambiare il proprio
comportamento in risposta; se la madre non risponde, la sintonia si blocca. Il bambino nasce già con buone capacità di
auto-regolazione, ma senza una risposta adeguata dell'ambiente queste capacità non bastano da sole: il rischio è uno sviluppo
psicofisiologico meno sano, e più difficoltà a gestire lo stress in futuro.</p>






<h2>Le differenze individuali nella regolazione affettiva (Montirosso e colleghi, 2015)</h2>
<p>Uno studio più recente, con un campione più ampio, approfondì le differenze individuali nella risposta al volto immobile: 74
bambini di circa 4 mesi e le loro madri, tutti bambini nati a termine e senza problemi clinici, tutte madri senza disturbi
emotivi.</p>


<p>La procedura durava 6 minuti, in tre fasi da 2 minuti ciascuna: gioco libero, volto immobile, e "riunione" (la madre torna a
interagire liberamente). Alla madre venivano anche chiesti un questionario socio-demografico e una checklist per i sintomi
depressivi.</p>

<p>Nel bambino si osservavano quattro comportamenti: interazione negativa, interesse per l'ambiente, controllo sociale (sguardo
verso la madre) e interazione positiva (sorriso e sguardo verso la madre). Nella madre: interazione negativa (ostile, evitante o
intrusiva), interazione non centrata sul bambino, controllo sociale e interazione positiva.</p>


<p>I bambini furono divisi in tre gruppi:</p>
<ul>
<li><strong>socialmente interattivi</strong> (25 bambini): guardano molto sia la madre sia l'ambiente, con interazione positiva
moderata e negativa molto bassa;</li>
<li><strong>non interattivi</strong> (45 bambini, il gruppo più numeroso): molto interessati all'ambiente ma poco alla madre, con
interazione sia positiva sia negativa bassa;</li>
<li><strong>negativamente interattivi</strong> (solo 5 bambini): alti livelli di interazione negativa, bassi in tutto il
resto.</li>
</ul>
<p>Anche le madri seguivano pattern simili ai propri figli: quelle dei bambini socialmente interattivi avevano la miglior
capacità di recupero dopo il volto immobile; quelle dei bambini non interattivi un recupero intermedio; quelle dei bambini
negativamente interattivi guardavano spesso il bambino, ma con poca interazione positiva.</p>


<p>Un risultato inatteso: verso i 6-9 mesi, le coppie madre-figlio maschio passano circa il 50% di tempo in più in stati ben
coordinati, rispetto alle coppie madre-figlia femmina. Le cause non sono ancora chiare. Per Tronick e colleghi, questo conferma
che non esiste un'unica forma "ottimale" di relazione: quello che conta davvero è la capacità di riparare gli errori di
sintonizzazione, non la quantità di sintonia in sé.</p>


<p>Le riparazioni sono importanti perché insegnano al bambino nuove strategie di coping, via via più complesse e adatte al
proprio ambiente: chiedere aiuto, esprimere le proprie emozioni, comunicare meglio i propri stati affettivi.</p> 

<p>Quando le
riparazioni trasformano ripetutamente emozioni negative in positive, il bambino sviluppa un nucleo affettivo positivo: si vede
come efficace, vede le proprie interazioni come positive e riparabili, e vede la madre come affidabile. Per questo, oggi, le
situazioni di recupero sono considerate più importanti per lo sviluppo sano rispetto alla semplice quantità di momenti di
sintonia.</p>


