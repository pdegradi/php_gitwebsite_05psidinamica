<h2>Attaccamento e psicopatologia del bambino</h2>
<img XXclass="zoomable" src="/assets/images/13/Screenshot 2026-10-04 201523.webp" />
<p>Secondo Bowlby, lo sviluppo psicofisiologico nell'infanzia e nell'adolescenza dipende da</p>
<ul>
    <li>l'interazione tra le esperienze precoci di attaccamento</li>
    <li>il contesto attuale</li>
</ul>    
<p>Un attaccamento insicuro non è di per sé una psicopatologia, ma un <strong>fattore di rischio</strong>, mentre un 
attaccamento sicuro è un <strong>fattore di resilienza</strong>. 

<p>Gli studi su questo tema si sono concentrati soprattutto sulla relazione tra stili di attaccamento 
e sintomi <strong>internalizzanti</strong> (ansia, depressione) ed <strong>esternalizzanti</strong> (problemi di 
condotta, attenzione, iperattività) in campioni non clinici.</p>

<p>Un attaccamento evitante è risultato correlato sia ai sintomi internalizzanti sia a quelli esternalizzanti, 
mentre un attaccamento disorganizzato è correlato soprattutto a quelli esternalizzanti.</p> 

<img XXclass="zoomable" src="/assets/images/13/Screenshot 2026-10-04 202234.webp" />

<p>Restano però ancora molte domande aperte su come il contesto attuale influenzi questo legame e su come 
esattamente un attaccamento sicuro funzioni da fattore protettivo.</p>



<h3>L'attaccamento padre-bambino</h3>
<p>Il ruolo del padre nei legami di attaccamento è stato studiato solo di recente, ma i risultati preliminari indicano che:</p>
<ul>
<li>la relazione di attaccamento padre-bambino <strong>predice alcuni esiti di sviluppo</strong></li>
<li>in caso di discordanza tra gli stili di attaccamento dei due genitori, l'attaccamento al padre può funzionare da <strong>fattore
protettivo</strong> (una madre insicura non compromette lo sviluppo se il bambino ha un attaccamento sicuro con il padre, e
viceversa)</li>
<li>in caso di concordanza tra gli stili genitoriali, l'attaccamento al padre <strong>promuove esiti di sviluppo ancora più
positivi</strong></li>
<li>il <strong>gioco</strong> sembra essere l'attività principale in cui si costruisce il legame di attaccamento padre-bambino,
favorendo la regolazione emotiva</li>
<li>il <strong>livello di stress dei genitori diminuisce</strong>, sia nella madre sia nel padre, quando quest'ultimo è coinvolto in
modo paritario nella cura del bambino, con benefici anche per la relazione madre-bambino.</li>
</ul>



<h3>Maternità e carriera</h3>
<p>Come visto nella lezione su <strong>Ainsworth</strong> e <strong>Bowlby</strong>, per molto tempo si è ritenuto importante
che il bambino avesse un'unica figura di accudimento principale, in genere la madre: un'idea che ha pesato anche sul dibattito
su come conciliare maternità e carriera. I risultati più recenti mostrano che non esiste, nei figli di madri lavoratrici, una
particolare predisposizione a uno sviluppo psicofisiologico più complesso. Restano però aperte diverse domande su quali fattori
socio-economici, familiari e lavorativi favoriscano meglio la combinazione tra maternità e carriera.</p>



