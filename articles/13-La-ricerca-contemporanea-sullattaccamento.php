<p>La teoria dell'attaccamento sostiene che i <strong>comportamenti genitoriali</strong> attivano il sistema di 
attaccamento innato in modi diversi. 
<ul>
    <li>Alcuni comportamenti promuovono uno stile di attaccamento sicuro</li>
    <li>Altri facilitano l'instaurarsi di un  attaccamento insicuro</li>
</ul>

<p>Questi stili di attaccamento diventano parti della personalità attraverso la formazione dei MOI (modelli operativi interni), 
schemi mentali di sé, dell'altro e della relazione tra i due, costruiti sulle prime esperienze con chi si 
prende cura di noi, che permettono di formulare aspettative sulle relazioni anche in età adulta.</p>

<p>Il modello di Bowlby include anche una componente clinica. Nel 1944 pubblicò uno studio su un gruppo di 
giovani ladri, ipotizzando che disturbi emotivi e comportamenti delinquenziali potessero dipendere da esperienze 
precoci di separazione dai genitori, capaci di alterare il sistema di attaccamento.</p> 

<p>Da qui nasce l'idea che lo stile di attaccamento sia anche un fattore di rischio (o protezione) per lo 
sviluppo di disturbi mentali in età adulta.</p>

<img class="zoomable" src="/assets/images/13/Screenshot 2026-10-04 192451.webp" />



<h3>I Modelli Operativi Interni: esempi e conferme empiriche</h3>
<p>I <strong>Modelli Operativi Interni</strong> (MOI) funzionano così. Ci basiamo sulle nostre prime esperienze
socio-affettive per definire come siamo noi in una relazione, come è l'altro e come è la relazione tra noi e l'altro.
</p>

<p>Questi schemi ci portano ad affrontare nuove relazioni con aspettative già predefinite.</p>
<img class="zoomable" src="/assets/images/13/Screenshot 2026-10-04 192658.webp" />


<p>Nel primo anno di vita, in uno sviluppo sano, si formano nel bambino degli <strong>script mentali</strong> 
(di base sicura) che permettono di categorizzare e prevedere le esperienze di attaccamento.</p> 

<p>Per esempio, lo script "se mi faccio male, vado dalla mamma e ricevo conforto" è un tipico <strong>script della 
base sicura</strong>, e questi script sono alla base dei MOI.</p>

<p>Per verificare empiricamente la presenza di questi script, alcuni studi hanno usato un metodo 
chiamato <strong>"prompt-word outline method"</strong>. Ai partecipanti viene dato un titolo, per esempio "La mattina
del bambino", e alcune liste di parole (per esempio: mamma, bambino, giocano, coperta, abbraccio, sorriso, storia, fare finta,
orsetto, perso, trovato, riposino) da usare per costruire una storia. Le storie vengono registrate e valutate da giudici
indipendenti.</p>

<p>Chi crea storie coerenti con
lo script (per esempio l'orsetto perso viene ritrovato e il bambino si consola) viene classificato come dotato di MOI di base
sicura. Chi crea storie senza risoluzione (per esempio l'orsetto viene ritrovato ma il bambino non si consola) viene classificato
come privo di questo script, o con uno script ridotto.</p>



<h3>Lo studio dei MOI nella prima infanzia</h3>
<p>Non esistono ancora studi definitivi su come e quando si formino esattamente i MOI, ma alcune evidenze empiriche possono
contribuire a spiegarlo.</p>

<p>Uno studio (Hamlin, Wynn, Bloom e Mahajan 2011) ha osservato bambini di 8 mesi mentre guardavano delle
vignette: i bambini mostravano apprezzamento, per esempio sorridendo, quando individui prosociali ricevevano comportamenti
positivi, e anche quando individui antisociali venivano puniti. È un segno che, già prima della fine del primo anno di vita, i
bambini sanno riconoscere le intenzioni emotive altrui: una capacità che potrebbe essere alla base della formazione dei MOI.</p>

<p>Un altro studio (Xu e Kushnir 2013), mostra che anche i neonati apprendono secondo un pensiero
probabilistico: valutano cioè la probabilità che, per esempio, la madre intervenga in loro soccorso quando si fanno male. Su
questa base costruiscono i propri script e i propri MOI. Più alta è la probabilità stimata, più si consolida uno script di base
sicura.</p>










<h2>Attaccamento e regolazione psicofisiologica dello stress</h2>
<p>A livello fisiologico, le
nostre risposte allo stress sono regolate dall'<strong>asse ipotalamo-ipofisi-surrene</strong> che regola la secrezione di 
cortisolo da parte della ghiandola surrenale ed è presente fin
dalla nascita.</p>

<p>Un numero crescente di studi mostra che la qualità delle cure genitoriali ricevute nella prima infanzia influisce
sul funzionamento di questo sistema, determinando le differenze individuali nella capacità di modulare la risposta allo stress.</p>

<p>Se i primi studi sulla Strange Situation valutavano solo i comportamenti osservabili (il pianto, l'aggrapparsi, il gioco), studi
più recenti hanno aggiunto la <strong>misura della reazione fisiologica</strong>.</p> 
<img XXclass="zoomable" src="/assets/images/13/Screenshot 2026-10-04 194141.png" />
<p>Nei bambini classificati con attaccamento
insicuro si osservano livelli più alti di cortisolo in risposta a nuovi stimoli. 
Un attaccamento sicuro è quindi associato a una regolazione dello stress più efficace.</p>






<h2>Mary Main e la trasmissione intergenerazionale dell'attaccamento</h2>

<img XXclass="zoomable" src="/assets/images/mary-main.webp" />

<p>Le differenze individuali nello stile di attaccamento sono state a lungo spiegate solo con la <strong>sensibilità emotiva
materna</strong> (la capacità della madre di riconoscere e rispondere ai segnali del bambino). Il lavoro di <strong>Mary
Main</strong> ha aggiunto un altro fattore fondamentale: la <strong>trasmissione intergenerazionale</strong> dello stile di
attaccamento, ovvero <em>l'idea che lo stile di attaccamento di un genitore tenda a ripetersi in quello del proprio figlio</em>.</p>

<p>Main spiega queste differenze attraverso una procedura da lei stessa proposta, 
l'<strong>Attachment Adult Interview</strong> (o <strong>AAI</strong>), un'intervista semi-strutturata rivolta agli adulti 
sulla propria prima infanzia. 
Si parte da informazioni oggettive (per esempio la composizione del nucleo familiare) fino a domande più soggettive 
(definire con 5 aggettivi
la relazione con ciascun genitore, ricordare episodi di rabbia, malattia o separazione, riflettere su come queste esperienze
abbiano influenzato la propria personalità attuale).</p>

<p>La valutazione delle risposte si basa non tanto sui contenuti, quanto sul <strong>livello di coerenza</strong> del racconto. Gli
adulti vengono classificati in:</p>
<ul>
<li><strong>individui autonomi</strong>: risposte coerenti, che trattano gli argomenti rilevanti in modo chiaro e sufficientemente
sintetico</li>
<li><strong>individui evitanti</strong>: risposte incoerenti, in cui i genitori sono descritti in termini molto positivi ma gli
episodi raccontati non corrispondono a questa descrizione</li>
<li><strong>individui preoccupati</strong>: risposte prolisse, confuse</li>
<li><strong>individui disorganizzati</strong>: categoria aggiunta da Main, caratterizzata da risposte che rivelano importanti esperienze
traumatiche precoci</li>
</ul>
<p>Confrontando lo stile di attaccamento dei genitori (misurato con l'AAI) con quello dei rispettivi bambini (misurato con la Strange
Situation), Main trovò una forte corrispondenza tra i due (coerentemente con la <em>trasmissione intergenerazionale dello stile 
di attaccamaneto</em>)</p>

<p>Come avviene la trasmissione intergenerazionale? Sono state proposte tre spiegazioni:</p>
<ol>
<li><strong>fattori genetici</strong>: nessun risultato significativo fino ad oggi</li>
<li><strong>fattori cognitivi</strong>: quanto una madre riesce ad assumere sia la propria prospettiva sia quella del bambino. 
Una madre che interpreta correttamente il pianto del figlio è più sensibile, e trasmette più facilmente uno stile sicuro</li>
<li><strong>fattori emozionali</strong>: uno stile sicuro è legato alla capacità di provare e mostrare emozioni sia positive sia
negative, a un atteggiamento aperto verso la richiesta di aiuto, e alla capacità di regolare le proprie emozioni in modo
appropriato.</li>
</ol>






<h2>La funzione riflessiva (mentalizzazione) secondo Peter Fonagy</h2>
<img XXclass="zoomable" src="/assets/images/Peter-Fonagy.webp" />
<p><strong>Peter Fonagy</strong>, collaboratore di Mary Main, introduce il concetto di <strong>funzione riflessiva</strong> (o
<strong>mentalizzazione</strong>), ovvero la capacità di <em>pensare</em> i propri stati mentali e quelli degli altri.</p>

<p>Questa capacità si sviluppa nel bambino grazie al modo in cui l'adulto si relaziona con lui. Se il genitore riesce 
a <em>leggere</em> correttamente gli stati mentali del bambino (capire cosa sta provando e a restituirglielo in modo 
comprensibile) il bambino impara gradualmente a riconoscersi come un individuo con pensieri, emozioni e credenze proprie. 
Da questo riconoscimento di sé nasce la capacità di riconoscere anche gli altri come persone autonome, dotate di una mente
propria. La capacità di mentalizzare si trasmette così dal genitore al bambino.</p>

<p>La funzione riflessiva è quindi legata a un attaccamento sicuro, ed è uno dei fattori alla base della trasmissione
intergenerazionale dello stile di attaccamento. Come per gli altri costrutti misurati con l'AAI, anche qui la valutazione non si
basa sui contenuti del racconto, ma sul modo in cui la persona risponde (per esempio in modo autoriflessivo oppure evasivo).</p>



<h3>La regolazione delle emozioni</h3>
<p>Il modo in cui la madre modula le proprie emozioni davanti al pianto del bambino viene trasmesso al bambino stesso, come
stile di <strong>regolazione delle emozioni</strong>. Se la madre resta irritata, ostile o stressata, cercando solo di ignorare
il proprio disagio, questa modalità poco efficace viene appresa dal bambino.</p> 

<p>Se invece fa un respiro e pensa "è un bambino
piccolo, è normale che pianga, ora sono un po' stanca ma si risolverà", riesce a ridurre l'intensità della propria emozione
negativa: una modalità più efficace, che il bambino apprende a sua volta come proprio stile di regolazione.</p>


