<h2>Correlati neurobiologici dell'attaccamento</h2>

<h3>La psicologia dinamica e lo sviluppo infantile</h3>
<p>Argomento già trattato: il metodo ricostruttivo di Freud, l'Infant Observation (Anna Freud, Esther Bick) e l'Infant Research
(Bowlby, Ainsworth, Sander, Stern, Tronick) sono descritti nei capitoli 10, 11, 14 e 15-16.</p>



<h3>Attaccamento e funzionamento psichico</h3>
<p>Argomento già trattato: i Modelli Operativi Interni, la sensibilità genitoriale, la cognizione materna e la funzione
riflessiva sono descritti nei capitoli 12 e 13.</p>



<h3>L'Infant Research e lo sviluppo psicofisiologico</h3>
<p>Argomento già trattato: la prospettiva sistemica di Sander, il sistema di vita come adattamento reciproco tra organismo e
ambiente, è descritta nel capitolo 15.</p>



<h3>La relazione di attaccamento influenza la struttura e la funzionalità cerebrale</h3>
<p>Il cervello regola il comportamento, ma il comportamento modifica a sua volta la struttura e la funzionalità del cervello.
Questa capacità del sistema nervoso centrale di modificarsi in risposta all'ambiente si chiama <strong>plasticità
neuronale</strong>.</p>



<h3>La maturazione cerebrale</h3>
<p>Nei primi anni di vita, i circuiti cerebrali si formano a partire da una <strong>sovrabbondanza di contatti sinaptici</strong>,
geneticamente determinata. Sono poi i processi di interazione con l'ambiente a guidare la selezione delle connessioni più
efficaci: è la spiegazione biologica di un'idea già vista nell'Infant Research (capitolo 15), cioè che selezioniamo i circuiti
più funzionali all'ambiente in cui viviamo. Questa selezione regola in particolare l'<strong>apprendimento emotivo</strong> (già
visto nel capitolo 19), la cui memoria può essere codificata fin dalla nascita, a differenza della memoria dichiarativa, che
diventa stabile solo dopo i 3-4 anni.</p>



<h3>Gli ingredienti dei legami emotivi</h3>
<p>Argomento già trattato: la comunicazione faccia a faccia e la conoscenza relazionale implicita sono descritte nei capitoli 15
e 16. Qui si aggiunge solo che il legame di attaccamento non è quindi solo psicologico, ma anche neurobiologico, radicato nel
corpo.</p>



<h3>L'attaccamento come regolazione dello stress</h3>
<p>Il legame di attaccamento è oggi definito soprattutto come una strategia di <strong>regolazione dello stress</strong> (idea già
vista nei capitoli 11-13). La novità qui è il meccanismo: attraverso l'apprendimento emotivo condizionato, il bambino seleziona
i circuiti neuronali più efficaci per rispondere allo stress, imparando dal comportamento della madre. Per esempio, il modo in
cui una madre reagisce al pianto di un neonato — distrarlo, innervosirsi, cullarlo cantando — viene appreso dal bambino come
modello di gestione dello stress.</p>



<h3>L'etero-regolazione delle emozioni e gli stimoli stressanti</h3>
<p>Argomento già trattato: la sensibilità materna (cognizione materna, funzione riflessiva) è descritta nel capitolo 13, e
l'esempio della teoria di Sander sull'apprendimento condizionato nel capitolo 15.</p>



<h3>La regolazione delle emozioni: una sintesi</h3>
<p>Argomento già trattato: è una sintesi di concetti visti nei capitoli 11-13 e 15-16 (auto-regolazione, etero-regolazione, il
sistema di attaccamento come regolazione dello stress).</p>



<h3>Le emozioni e la bioregolazione</h3>
<p>Le emozioni, definite come processi adattivi e multi-componenziali nel capitolo 19, sono oggi considerate il sistema di
<strong>bioregolazione</strong> più importante del nostro funzionamento: rispondendo agli stimoli rilevanti, permettono al
cervello di adattarsi efficacemente all'ambiente.</p>



<h3>Le emozioni e l'emisfero destro</h3>
<p>Numerosi studi mostrano che l'<strong>emisfero destro</strong> domina in diverse componenti delle emozioni:</p>
<ul>
<li>la comunicazione attraverso il volto e la voce;</li>
<li>le reazioni corporee automatiche (vegetative) legate all'emozione;</li>
<li>l'esperienza soggettiva delle emozioni;</li>
<li>il condizionamento emozionale inconscio.</li>
</ul>
<p>L'emisfero sinistro, invece, è più coinvolto nel controllo delle risposte emozionali. Per questo l'apprendimento emotivo è
legato soprattutto ai primi anni di vita: prima dei 2 anni l'emisfero destro matura più in fretta del sinistro (che gestisce il
linguaggio) e ha un volume maggiore. Questa crescita è modulata dalla comunicazione emotiva con la figura di attaccamento, ed è
alla base dello sviluppo socio-emozionale.</p>



<h3>La comunicazione dell'emisfero destro: le prove dal neuroimaging</h3>
<p>Diversi studi supportano questa teoria:</p>
<ul>
<li>i bambini di 2 mesi mostrano una maggiore attivazione dell'emisfero destro di fronte a volti femminili;</li>
<li>nella comunicazione faccia a faccia, è l'emisfero destro del bambino a elaborare le informazioni visive e uditive;</li>
<li>l'emisfero destro materno si attiva in risposta al pianto del bambino;</li>
<li>coerentemente, la maggior parte delle madri culla il proprio bambino tenendolo dal lato sinistro del corpo, che è controllato
appunto dall'emisfero destro.</li>
</ul>



<h3>L'apprendimento emotivo dal punto di vista neurobiologico</h3>
<p>Quando un bambino viene cullato o gli viene cantata una ninna nanna, si rinforzano specifici circuiti neuronali: è il
meccanismo alla base dell'apprendimento emotivo (già visto nel capitolo 19). Poiché nei primi 2 anni di vita i circuiti limbici
dell'emisfero destro attraversano una fase critica di sviluppo, questi apprendimenti si stabilizzano attraverso un processo
simile all'imprinting descritto da Lorenz (capitolo 11). Ciò che si apprende durante la maturazione di queste aree tende cioè a
diventare parte stabile della personalità.</p>



<h3>La teoria neurobiologica dell'attaccamento di Allan Schore</h3>
<img XXclass="zoomable" src="/assets/images/Allan-Schore.webp" />
<p>Secondo <strong>Allan Schore</strong>, in una versione semplificata della sua teoria, un bambino che sviluppa un attaccamento
sicuro sviluppa efficacemente l'emisfero destro ed è predisposto a una buona salute mentale. Un attaccamento insicuro o
traumatico, al contrario, altera lo sviluppo dell'emisfero destro e predispone alla psicopatologia. In una versione più
articolata della teoria, è lo sviluppo dei sistemi limbici dell'emisfero destro — guidato dalla relazione con la figura di
riferimento nei primi due anni di vita — a determinare questa predisposizione.</p>



<h3>Il modello gerarchico dello sviluppo dei circuiti limbici dell'emisfero destro</h3>
<p>Alla nascita è attiva soprattutto l'<strong>amigdala</strong>, che regola per esempio il riconoscimento dell'odore materno.
Verso le 8 settimane inizia un periodo critico per il <strong>cingolato anteriore</strong>, legato alla regolazione di sorriso,
pianto, riconoscimento dei volti e modulazione del Sistema Nervoso Autonomo. Nel corso del primo anno maturano
l'<strong>insula</strong> e la <strong>corteccia parietale</strong>, che regolano l'esperienza delle sensazioni corporee e la
capacità di distinguere sé stessi dagli altri. Dai 9 mesi ai 2 anni si sviluppa infine la <strong>corteccia
orbitofrontale</strong>, che secondo Schore è il correlato biologico del sistema di attaccamento.</p>



<h3>La corteccia orbito-frontale</h3>
<img XXclass="zoomable" src="/assets/images/20/corteccia-e1477520590566-1.jpg" />
<p>La corteccia orbito-frontale è situata nella superficie inferiore del lobo frontale, sopra le orbite oculari. Si trova tra il
sistema limbico e la corteccia prefrontale, in una posizione che le permette di collegare le due aree. Si espande
particolarmente nell'emisfero destro, dove è considerata il sistema esecutivo, e regola anche l'asse ipotalamo-ipofisi-surrene,
collegato alle reazioni da stress.</p>


<p>Il suo sviluppo critico, tra i 10-12 mesi e la fine del secondo anno, coincide con il periodo in cui si forma, a livello
comportamentale, il sistema di attaccamento.</p> 

<p>La corteccia orbitofrontale regola diverse funzioni: l'elaborazione dei volti, le
risposte emozionali positive a stimoli tattili, gustativi, olfattivi e musicali, le risposte negative a volti tristi o
arrabbiati, e la regolazione degli stati di attivazione corporei. Regola anche l'anticipazione dei rinforzi positivi o
negativi, un aspetto centrale nel sistema di attaccamento, dato che la nostra capacità di prevedere l'ambiente si costruisce
proprio sul legame di attaccamento.</p>



