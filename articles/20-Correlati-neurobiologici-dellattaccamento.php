<h2>Correlati neurobiologici dell'attaccamento</h2>

<h3>La psicologia dinamica e lo sviluppo infantile</h3>
<p>Argomento già trattato: il metodo ricostruttivo di Freud, l'Infant Observation (Anna Freud, Esther Bick), la teoria
dell'attaccamento (Bowlby, Ainsworth) e l'Infant Research (Sander, Stern, Tronick) sono descritti nei capitoli 10, 11, 14 e 15-16.</p>
<img class="zoomable" src="/assets/images/20/Screenshot 2026-10-01 110318.webp" />
<p>La slide mostra come è cambiato il metodo di studio del bambino: Freud ricostruiva le esperienze infantili nella terapia
con gli adulti (per esempio, attraverso le associazioni libere); l'Infant Observation ha affiancato a questo metodo
l'osservazione diretta e partecipe per verificare le ipotesi psicoanalitiche. La teoria dell'attaccamento e l'Infant Research
hanno poi usato il metodo empirico.</p>



<h3>Attaccamento e funzionamento psichico</h3>
<p>Argomento già trattato: i Modelli Operativi Interni, la sensibilità genitoriale, la cognizione materna e la funzione
riflessiva sono descritti nei capitoli 12 e 13.</p>
<p>La <strong>teoria dell'attaccamento</strong> ha proposto un modello teorico su cui la mente si organizza nei primi anni di vita 
sulla base delle relazioni affettive con le figure di riferimento</p>
<p>Da Mary Ainsworth in poi l'osservazione del comportamento del bambino (attraverso la strange situation e in 
situazioni naturali) è diventata oggetto di studio empirico</p>
<p>I legami emotivi intimi tra gli individui svolgono una funzione psico-biologica specifica:</p>
<ul>
    <li>A <strong>livello cognitivo</strong> (MOI)</li>
    <li>A <strong>livello fisiologico</strong> influenzando la modalità di risposta alle situazioni stressanti</li>
</ul>
<img zzzzclass="zoomable" src="/assets/images/20/Screenshot 2026-10-01 110717.webp" />
<p>Lo schema mostra la possibile trasmissione dell'attaccamento tra generazioni: lo stile del genitore influisce sulla sua
<strong>sensibilità</strong> (capacità di cogliere e rispondere ai bisogni del bambino), che contribuisce all'attaccamento del
figlio. Quest'ultimo è collegato ai suoi <strong>Modelli Operativi Interni</strong> (rappresentazioni di sé e degli altri) e al
sistema di regolazione psicofisiologica. Lo schema collega questi aspetti al funzionamento psicosociale e alla psicopatologia
del bambino.</p>



<h3>L'Infant Research e lo sviluppo psicofisiologico</h3>
<p>Argomento già trattato: la prospettiva sistemica di Sander, il sistema di vita come adattamento reciproco tra organismo e
ambiente, è descritta nel capitolo 15.</p>
<p>Il <strong>sistema di vita</strong> è un processo di adattamento continuo e reciproco tra organismo e ambiente.
Il sistema si <strong>auto-regola</strong>: nell'interazione emergono modalità di risposta non prestabilite, selezionate con
l'esperienza per ritrovare l'equilibrio. Nel bambino, il modo in cui lui e la figura di cura gestiscono insieme i compiti
evolutivi contribuisce allo sviluppo psicofisiologico.</p>



<h3>La relazione di attaccamento influenza la struttura e la funzionalità cerebrale</h3>
<img zzzzclass="zoomable" src="/assets/images/20/Screenshot 2026-10-01 110902.webp" />
<p>Il cervello regola il comportamento, ma il comportamento modifica a sua volta la struttura e la funzionalità del cervello.
Questa capacità del sistema nervoso centrale di modificarsi in risposta all'ambiente si chiama <strong>plasticità
neuronale</strong>.</p>



<h3>La maturazione cerebrale</h3>
<p>Nei primi anni di vita, i circuiti cerebrali si formano a partire da una <strong>sovrabbondanza di contatti sinaptici</strong>,
geneticamente determinata. Sono poi i processi di interazione con l'ambiente a guidare la selezione delle connessioni più
efficaci.</p> 
<p>Questa selezione e riduzione dei circuiti in sovrabbondanza è una delle funzioni principali del cervello in fase evolutiva.</p>



<h3>Apprendimento emotivo e ingredienti dei legami emotivi</h3>
<p>La <strong>memoria emotiva</strong> è un apprendimento delle risposte emozionali ad una situazione.</p>
<p>Questa può essere appresa fin dalla nascita, al contrario della memoria dichiarativa che non si manifesta prima dei 3 o 4 anni.</p>
<p>I legami emotivi hanno come base le comunicazioni emotive con la figura di attaccamento</p>
<img zzzzclass="zoomable" src="/assets/images/20/Screenshot 2026-10-01 115216.webp" />
<p>Questi scambi vengono salvati all'interno della coscenza, non solo a livello psicologico ma anche fisiologico (radicato nel corpo)</p>



<h3>L'attaccamento come regolazione dello stress</h3>
<p>Il legame di attaccamento è oggi definito soprattutto come una strategia di <strong>regolazione dello stress</strong> (idea già
vista nei capitoli 11-13).</p> 
<p>Attraverso l'apprendimento emotivo condizionato, il bambino seleziona
i circuiti neuronali più efficaci per rispondere allo stress, imparando dal comportamento della madre. Per esempio, il modo in
cui una madre reagisce al pianto di un neonato — distrarlo, innervosirsi, cullarlo cantando — viene appreso dal bambino come
modello di gestione dello stress.</p>
<p>All'inizio la regolazione degli stati di attivazione è esterma e dipende dalla sensibilità della materna.</p>



<h3>La regolazione delle emozioni</h3>
<p>Argomento già trattato: è una sintesi di concetti visti nei capitoli 11-13 e 15-16 (auto-regolazione, etero-regolazione, il
sistema di attaccamento come regolazione dello stress).</p>
<p>La ricerca contemporanea sullo sviluppo infantile suppone che</p>
<ul>
    <li>Lo sviluppo psicofisiologico del bambino sia un processo di adattamento all'ambiente. Ciò avviene grazie alla 
        autoregolazione del bambino (capacità di relazionarsi con l'altro)
    </li>
    <li>Queste capacità di autoregolazione si organizzano in un modello organizzativo degli <strong>stati affettivi</strong></li>
    <li>Il sistema di attaccamento possa essere definito come strategia di comunicazione e gestione delle proprie emozioni</li>
    <li>Il sistema di attaccamento modula le modalità di regolazione psicofisiologica dello stress</li>
</ul>



<h3>Le emozioni e la bioregolazione</h3>
<p>Le emozioni sono <strong>processi adattivi</strong> e <strong>multi-componenziali</strong> attivati da eventi stimolo.</p>
<ul>
    <li><strong>adattivi</strong> perchèpermettono di selezionare le modalità più appropriate di risposta all'evento stimolo</li>
    <li><strong>multi-componenziali</strong> perchè le emozioni si esprimono su diversi livelli (esperinza personale
    , espressioni facciali, aumento battito cardiaco, ecc...)</li>
</ul>
<p>Le emozioni sono un sistema di regolazione chiave, perchè attraverso la capacità di rispondere a stimoli importanti il 
cervello risponde in maniera adeguata all'ambiente (promuovendo l'adattamento)</p>



<h3>Le emozioni e l'emisfero destro</h3>
<p>Numerosi studi mostrano che l'<strong>emisfero destro</strong> è più attivo per diverse componenti delle emozioni, quali:</p>
<ul>
<li>la comunicazione attraverso il volto e la voce;</li>
<li>le reazioni corporee automatiche (vegetative) legate all'emozione;</li>
<li>l'esperienza soggettiva delle emozioni;</li>
<li>il condizionamento emozionale inconscio.</li>
</ul>
<p>L'emisfero sinistro, invece, è più coinvolto nel controllo delle risposte emozionali. Per questo l'apprendimento emotivo è
legato soprattutto ai primi anni di vita: prima dei 2 anni l'emisfero destro matura più in fretta del sinistro (che gestisce il
linguaggio) e ha un volume maggiore. Questa crescita è regolata dalla comunicazione emotiva con la figura di attaccamento, ed è
alla base dello sviluppo socio-emozionale.</p>

<p>Diversi studi supportano questa teoria:</p>
<ul>
<li>i bambini di 2 mesi mostrano una maggiore attivazione dell'emisfero destro di fronte a volti femminili;</li>
<li>nella comunicazione faccia a faccia, è l'emisfero destro del bambino a elaborare le informazioni visive e uditive;</li>
<li>l'emisfero destro materno si attiva in risposta al pianto del bambino;</li>
<li>coerentemente, la maggior parte delle madri culla il proprio bambino tenendolo dal lato sinistro del corpo, che è controllato
appunto dall'emisfero destro.</li>
</ul>

<p>Quando un bambino viene cullato o gli viene cantata una ninna nanna, si rinforzano specifici circuiti neuronali: è il
meccanismo alla base dell'apprendimento emotivo (già visto nel capitolo 19).</p>
<p>Poiché nei primi 2 anni di vita i circuiti limbici
dell'emisfero destro attraversano una fase critica di sviluppo, questi apprendimenti si stabilizzano attraverso un processo
simile all'imprinting descritto da Lorenz (capitolo 11).</p> 
<p>Ciò che si apprende durante la maturazione di queste aree tende cioè a
diventare parte stabile della personalità.</p>



<h3>La teoria neurobiologica dell'attaccamento di Allan Schore</h3>
<img XXclass="zoomable" src="/assets/images/Allan-Schore.webp" />
<p>Secondo <strong>Allan Schore</strong>, in una versione semplificata della sua teoria, un bambino che sviluppa un attaccamento
sicuro sviluppa efficacemente l'emisfero destro ed è predisposto a una buona salute mentale.</p> 
<p>Un attaccamento insicuro o traumatico, al contrario, altera lo sviluppo dell'emisfero destro e predispone alla psicopatologia.</p>
