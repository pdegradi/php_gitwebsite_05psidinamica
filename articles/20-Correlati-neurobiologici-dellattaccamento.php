<h3>Il modello gerarchico dello sviluppo dei circuiti limbici dell'emisfero destro</h3>
<img class="zoomable" src="/assets/images/20/Screenshot 2026-10-01 122220.webp" />
<p>Alla nascita è attiva soprattutto l'<strong>amigdala</strong>, che regola il riconoscimento dell'odore materno.</p>
<p>Verso le 8 settimane inizia un periodo critico per il <strong>cingolato anteriore</strong>, legato alla regolazione di sorriso,
pianto, riconoscimento dei volti e modulazione del Sistema Nervoso Autonomo.</p>
<p>Nel corso del primo anno maturano
l'<strong>insula</strong> e la <strong>corteccia parietale</strong>, che regolano l'esperienza delle sensazioni corporee e la
capacità di distinguere sé stessi dagli altri.</p>
<p>Dai 9 mesi ai 2 anni si sviluppa infine la <strong>corteccia orbitofrontale</strong>, che regola il sistema di attaccamento.</p>



<h3>La corteccia orbito-frontale</h3>
<img XXclass="zoomable" src="/assets/images/20/corteccia-e1477520590566-1.jpg" />
<p>La corteccia orbito-frontale è situata nella superficie inferiore del lobo frontale, sopra le orbite oculari. Si trova tra il
sistema limbico e la corteccia prefrontale, in una posizione che le permette di collegare le due aree.</p> 
<p>Si espande particolarmente nell'emisfero destro, dove è considerata il sistema esecutivo, e regola anche 
l'asse ipotalamo-ipofisi-surrene, collegato alle reazioni da stress.</p>


<p>Il suo sviluppo critico, tra i 10-12 mesi e la fine del secondo anno, coincide con il periodo in cui si forma, a livello
comportamentale, il sistema di attaccamento.</p> 

<p>La corteccia orbitofrontale regola diverse funzioni emotive:</p> 
<ul>
    <li>elaborazione dei volti</li>
    <li>risposte emozionali positive a stimoli tattili, gustativi, olfattivi e musicali</li>
    <li>risposte negative a volti tristi o arrabbiati</li>
    <li>regolazione degli stati di attivazione corporei</li>
    <li>anticipazione dei rinforzi positivi o negativi</li>
</ul>


